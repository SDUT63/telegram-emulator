#!/usr/bin/env python3
"""Перенос ответов анкеты из бота в мини-приложение.

Зачем. Анкета есть и в боте, и в мини-приложении — это одни и те же
вопросы. Человек, который прошёл её в чате, а потом открыл приложение,
видит пустую форму и должен отвечать второй раз. Это не просто
неудобно: второй раз он отвечает иначе, и у координатора оказываются
две несовпадающие анкеты на одного подопечного.

Как решено. Бот отдаёт ссылку, внутри которой лежат уже данные ответы.
Приложение их читает и показывает анкету заполненной.

Почему не вход по номеру телефона. Номер — не пароль: его знают
родственники, соседи, любой, кому человек когда-то звонил. Вход по
одному лишь номеру означал бы, что ответы о здоровье подопечного
и его адрес откроются каждому, кто этот номер наберёт. Плюс для
такого входа нужен сервер, который хранит анкеты и отвечает из
интернета, — сейчас мини-приложение лежит статическими файлами,
и хранить там нечего.

Ссылка этих недостатков лишена: данные едут в ней самой, сервер
не участвует, и попадает она ровно тому, кому бот её прислал.
Часть ссылки после решётки браузер на сервер не отправляет —
в журналах хостинга ответов не окажется.
"""

from __future__ import annotations

import base64
import json
import os

# Адрес мини-приложения. Меняется настройкой, чтобы при переезде
# на другой хостинг не искать его по коду.
АДРЕС = os.environ.get("SDUT_APP_URL", "https://sdut.d-lemeshev88.workers.dev/")

МЕТКА = "анкета"          # имя параметра после решётки

# Длиннее этого ссылку не отдаём. Мессенджеры и браузеры режут
# сверхдлинные адреса молча, и человек открыл бы приложение
# с обрезанными данными — хуже, чем с пустой формой.
ПРЕДЕЛ = 6000


def упаковать(ответы: dict[str, str]) -> str:
    """Ответы одной строкой, пригодной для адреса."""
    чистые = {к: str(з) for к, з in (ответы or {}).items() if з}
    сырое = json.dumps(чистые, ensure_ascii=False, separators=(",", ":"))
    return base64.urlsafe_b64encode(сырое.encode("utf-8")).decode("ascii").rstrip("=")


def распаковать(код: str) -> dict[str, str]:
    """Обратно в ответы. Испорченный код — это пустой словарь,
    а не исключение: приложению важнее открыться, чем упасть."""
    if not код:
        return {}
    try:
        добивка = "=" * (-len(код) % 4)
        сырое = base64.urlsafe_b64decode(код + добивка).decode("utf-8")
        данные = json.loads(сырое)
    except Exception:                                           # noqa: BLE001
        return {}
    if not isinstance(данные, dict):
        return {}
    return {str(к): str(з) for к, з in данные.items() if з}


def ссылка(ответы: dict[str, str], адрес: str = "") -> str:
    """Адрес мини-приложения с ответами внутри.

    Если ответов слишком много, отдаём обычный адрес: пусть человек
    заполнит заново, чем откроет приложение с половиной анкеты.
    """
    основа = адрес or АДРЕС
    if not any((ответы or {}).values()):
        return основа
    код = упаковать(ответы)
    полная = f"{основа}#{МЕТКА}={код}"
    return полная if len(полная) <= ПРЕДЕЛ else основа


def из_ссылки(адрес: str) -> dict[str, str]:
    """Ответы из готовой ссылки — тем же путём, что и в приложении."""
    if "#" not in адрес:
        return {}
    хвост = адрес.split("#", 1)[1]
    for кусок in хвост.split("&"):
        имя, _, значение = кусок.partition("=")
        if имя == МЕТКА:
            return распаковать(значение)
    return {}
