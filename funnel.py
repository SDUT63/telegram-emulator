#!/usr/bin/env python3
"""Воронка: куда доходят люди и где перестают отвечать.

Зачем
-----
Люди приходят из социальной рекламы. За рекламу платят, и вопрос
«работает ли она» упирается не в число переходов, а в число карточек,
по которым координатор смог позвонить. Между «нажал на объявление»
и «координатору есть куда звонить» стоит десяток шагов, и на каждом
кто-то уходит. Пока не видно, на каком именно, любая правка анкеты —
гадание, а деньги за рекламу тратятся вслепую.

Что здесь считается
-------------------
Только числа. Ни имени, ни телефона, ни ответов, ни идентификатора
человека наружу не выходит: на входе состояния анкет, на выходе
счётчики ступеней и разделов. Поэтому отчёт можно показывать
учредителю, рекламщику и кому угодно ещё.

Чего здесь нет
--------------
Истории. Воронка считается по текущим карточкам: человек, стерший свои
данные, исчезает из неё целиком — так и должно быть по статьям 14 и 21
ФЗ-152. Значит, числа слегка занижены относительно «сколько всего
приходило», и это честнее, чем держать тень удалённого человека ради
красивой статистики.

Посмотреть глазами:
    python funnel.py
"""

from __future__ import annotations

from typing import Any, Callable, Iterable

from survey_questions import CHECKPOINT_ID, QUESTIONS, STOP_OPTION

# Вопрос, после которого координатору уже есть куда звонить. Всё, что
# до него, — это подготовка; всё, что после, — уточнения, без которых
# можно обойтись. Поэтому ступень «оставили телефон» в воронке главная.
КЛЮЧЕВОЙ_ВОПРОС = "phone"


def _ответы(карточка: dict[str, Any]) -> dict[str, Any]:
    return карточка.get("answers") or {}


def _согласился(карточка: dict[str, Any]) -> bool:
    """Согласие записано как {"at": ...}, отказ — как {"refused": ...}.

    Оба лежат в одном поле, поэтому «поле непустое» согласием не
    является: так отказавшийся попал бы в воронку как согласившийся.
    """
    отметка = карточка.get("consent") or {}
    return bool(отметка.get("at"))


def _отказался(карточка: dict[str, Any]) -> bool:
    отметка = карточка.get("consent") or {}
    return bool(отметка.get("refused"))


def _остановился_сам(карточка: dict[str, Any]) -> bool:
    """Выбрал «Достаточно, свяжитесь» — это не потеря, а решение."""
    return _ответы(карточка).get(CHECKPOINT_ID) == STOP_OPTION


# Ступени идут сверху вниз и вложены одна в другую: кто дошёл до нижней,
# прошёл и все верхние. Иначе проценты потерь читались бы неверно.
СТУПЕНИ: tuple[tuple[str, Callable[[dict[str, Any]], bool]], ...] = (
    ("Написали боту", lambda к: True),
    ("Дали согласие", _согласился),
    ("Ответили на первый вопрос", lambda к: bool(_ответы(к))),
    ("Оставили телефон", lambda к: bool(_ответы(к).get(КЛЮЧЕВОЙ_ВОПРОС))),
    ("Дошли до конца обязательной части",
     lambda к: bool(_ответы(к).get(CHECKPOINT_ID))),
    ("Согласились на подробную часть",
     lambda к: bool(_ответы(к).get(CHECKPOINT_ID)) and not _остановился_сам(к)),
    # «Достаточно, свяжитесь» тоже помечает анкету законченной — иначе
    # человек навсегда висел бы незавершённым. Но в эту ступень он
    # не входит: подробную часть он не проходил, и смешать одно
    # с другим значит сломать вложенность и все проценты потерь.
    ("Заполнили анкету полностью",
     lambda к: bool(к.get("finished")) and not _остановился_сам(к)),
)


def _раздел(шаг: int) -> str:
    """Название раздела, в котором стоит этот вопрос.

    Разделы нужны, потому что вопросов больше тридцати: список из
    тридцати строк никто не читает, а список из десяти — читают
    и по нему принимают решения.
    """
    if not 0 <= шаг < len(QUESTIONS):
        return "—"
    for i in range(шаг, -1, -1):
        название = QUESTIONS[i].get("section")
        if название:
            return название
    return QUESTIONS[0].get("section") or "—"


class Воронка:
    """Готовый отчёт: ступени, потери, места остановки."""

    def __init__(self, карточки: Iterable[dict[str, Any]]) -> None:
        все = [к for к in карточки if isinstance(к, dict)]
        self.всего = len(все)

        self.ступени: list[tuple[str, int]] = [
            (имя, sum(1 for к in все if подходит(к))) for имя, подходит in СТУПЕНИ
        ]

        # Отказ от согласия — не то же самое, что молчание: человек
        # прочитал, подумал и сказал «нет». Это разные причины уходить,
        # и лечатся они разным.
        self.отказались = sum(1 for к in все if _отказался(к))
        self.остановились_сами = sum(1 for к in все if _остановился_сам(к))

        # Где стоят те, кто начал и не закончил. Именно эти строки
        # говорят, какой вопрос переписывать.
        остановки: dict[str, int] = {}
        for к in все:
            if к.get("finished") or not _ответы(к):
                continue
            раздел = _раздел(int(к.get("step") or 0))
            остановки[раздел] = остановки.get(раздел, 0) + 1
        self.остановки = dict(
            sorted(остановки.items(), key=lambda п: (-п[1], п[0]))
        )

        # Тревоги за угрозу жизни: не воронка, но смотреть на это надо
        # в том же месте и каждый день.
        self.с_тревогой = sum(1 for к in все if (к.get("alerts") or []))

    # ------------------------------------------------------------- вывод

    def как_числа(self) -> dict[str, Any]:
        """Отчёт для машины: веб-страница, выгрузка, мониторинг."""
        return {
            "всего": self.всего,
            "ступени": [{"имя": и, "человек": n} for и, n in self.ступени],
            "отказались_от_согласия": self.отказались,
            "остановились_сами": self.остановились_сами,
            "остановки_по_разделам": self.остановки,
            "с_тревогой": self.с_тревогой,
        }

    def как_текст(self) -> str:
        """Отчёт для человека: его читают, а не разбирают."""
        if not self.всего:
            return "Пока никто не писал."

        строки = ["Куда доходят люди", ""]
        предыдущее = None
        ширина = max(len(и) for и, _ in self.ступени)
        for имя, сколько in self.ступени:
            доля = 100 * сколько / self.всего
            потеря = ""
            if предыдущее is not None and предыдущее > сколько:
                потеря = f"   ушло {предыдущее - сколько}"
            строки.append(f"  {имя:<{ширина}}  {сколько:>5}   {доля:5.1f}%{потеря}")
            предыдущее = сколько

        if self.остановки:
            строки += ["", "Где остановились те, кто не закончил", ""]
            ширина = max(len(р) for р in self.остановки)
            for раздел, сколько in self.остановки.items():
                строки.append(f"  {раздел:<{ширина}}  {сколько:>5}")

        строки += [""]
        if self.остановились_сами:
            строки.append(
                f"  Сами выбрали «достаточно, свяжитесь»: {self.остановились_сами}. "
                "Это не потеря — по ним звонят."
            )
        if self.отказались:
            строки.append(f"  Отказались от согласия: {self.отказались}.")
        if self.с_тревогой:
            строки.append(f"  Карточек с пометкой об угрозе жизни: {self.с_тревогой}.")
        return "\n".join(строки)


def по_анкете(survey: Any) -> Воронка:
    """Воронка по живой анкете — файловой, SQLite или PostgreSQL."""
    состояние = getattr(survey, "state", None) or {}
    return Воронка(состояние.values())


