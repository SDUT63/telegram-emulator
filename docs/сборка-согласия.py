def экран(текст, кнопки):
    """Показать текст бота так, как его видит человек в чате."""
    table = d.add_table(rows=1, cols=1)
    table.style = "Table Grid"
    cell = table.rows[0].cells[0]
    cell.width = Cm(17)
    строки = текст.split("\n") + ["", кнопки]
    for i, line in enumerate(строки):
        par = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        par.paragraph_format.space_after = Pt(2)
        r = par.add_run(line)
        r.font.size, r.font.name = Pt(11), FONT
        if line.startswith("["):
            r.bold = True


p("А.1. Первый экран", bold=True, after=6)
note("Короткое изложение. Человек, пришедший за помощью для лежачей матери, "
     "не должен встречать страницу юридического текста: он закроет чат. "
     "Полный текст — в одно нажатие, здесь же в чате, и кнопка согласия "
     "стоит рядом с обеими возможностями.")
