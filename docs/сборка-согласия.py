def p(text="", *, bold=False, italic=False, size=12, align="left",
      before=0, after=6, indent=None, spacing=1.15):
    par = d.add_paragraph()
    par.alignment = {"left": WD_ALIGN_PARAGRAPH.LEFT,
                     "center": WD_ALIGN_PARAGRAPH.CENTER,
                     "right": WD_ALIGN_PARAGRAPH.RIGHT,
                     "just": WD_ALIGN_PARAGRAPH.JUSTIFY}[align]
    pf = par.paragraph_format
    pf.space_before, pf.space_after = Pt(before), Pt(after)
    pf.line_spacing = spacing
    if indent is not None:
        pf.first_line_indent = Cm(indent)
    if text:
        r = par.add_run(text)
        r.bold, r.italic, r.font.size = bold, italic, Pt(size)
        r.font.name = FONT
    return par


def head(text, level=1):
    sizes = {1: 14, 2: 12}
    par = p(text, bold=True, size=sizes[level], align="center" if level == 1 else "left",
            before=14 if level == 1 else 12, after=10 if level == 1 else 6)
    return par


def fill(caption, width=None, after=10):
    """Строка для заполнения от руки с подстрочной подписью."""
    line = p("_" * (width or 88), after=0)
    if caption:
        cap = p(caption, italic=True, size=9, align="center", after=after)
    return line


def note(text):
    par = p(text, italic=True, size=10, align="just", after=8)
    return par


def bullet(text, size=12):
    par = d.add_paragraph(style="List Bullet")
    par.paragraph_format.space_after = Pt(3)
    par.paragraph_format.left_indent = Cm(0.8)
    r = par.add_run(text)
    r.font.size, r.font.name = Pt(size), FONT
    return par


def table(rows, widths, header=True):
    t = d.add_table(rows=0, cols=len(widths))
    t.style = "Table Grid"
    for i, row in enumerate(rows):
        cells = t.add_row().cells
        for c, (cell, w) in enumerate(zip(row, widths)):
            cells[c].width = Cm(w)
            par = cells[c].paragraphs[0]
            par.paragraph_format.space_after = Pt(2)
            r = par.add_run(str(cell))
            r.font.size, r.font.name = Pt(10.5), FONT
            r.bold = header and i == 0
    return t


def newpage():
    d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def signature_block():
    p("«____» ________________ 20____ г.", after=16)
    t = d.add_table(rows=1, cols=2)
    t.autofit = False
    for cell, w, txt, cap in (
        (t.rows[0].cells[0], 8.0, "_" * 26, "подпись"),
        (t.rows[0].cells[1], 9.0, "_" * 32, "фамилия, имя, отчество полностью"),
    ):
        cell.width = Cm(w)
        par = cell.paragraphs[0]
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        par.paragraph_format.space_after = Pt(0)
        r = par.add_run(txt); r.font.size, r.font.name = Pt(12), FONT
        c2 = cell.add_paragraph()
        c2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = c2.add_run(cap); r2.italic = True; r2.font.size = Pt(9); r2.font.name = FONT
    p(after=6)


