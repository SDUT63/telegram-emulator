def из_анкеты(ответы: dict[str, str]) -> dict[str, str]:
    """Позиции шкалы, которые видно из ответов боту.

    Множественный выбор («Судно, кресло; Подгузники») разбирается
    по худшему варианту: если человек отметил и то и другое,
    верно более тяжёлое.
    """
    заполнено: dict[str, str] = {}
    порядок = {САМ: 0, ЧАСТИЧНО: 1, НЕ_МОЖЕТ: 2}
    for позиция, (вопрос, таблица) in ПРАВИЛА.items():
        было = str((ответы or {}).get(вопрос, ""))
        если_нашлось = [степень for ответ, степень in таблица.items()
                        if ответ.lower() in было.lower()]
        if если_нашлось:
            заполнено[позиция] = max(если_нашлось, key=lambda с: порядок[с])
    return заполнено


def сколько_заполнится(ответы: dict[str, str]) -> int:
    return len(из_анкеты(ответы))


