def опросник_из_анкеты(ответы: dict[str, str]) -> dict[str, str]:
    """Ответы опросника плана, которые видно из анкеты бота.

    Вопросы с одним вариантом: побеждает первое подошедшее правило.
    Вопросы с несколькими: собираем всё подошедшее, порядок —
    как в самом вопросе, чтобы кнопки загорались слева направо.
    """
    from уход import ВОПРОСЫ

    ответы = ответы or {}
    порядок = {в.id: в for в in ВОПРОСЫ}
    готово: dict[str, str] = {}

    for ключ, правила in ОПРОСНИК.items():
        вопрос = порядок.get(ключ)
        if вопрос is None:
            continue
        собрано: list[str] = []
        for анкетный, таблица in правила:
            было = str(ответы.get(анкетный, "")).lower()
            if not было:
                continue
            подошло = [значение for ответ, значение in таблица.items()
                       if ответ.lower() in было]
            if not подошло:
                continue
            if not вопрос.несколько:
                собрано = [подошло[0]]
                break
            for значение in подошло:
                собрано.extend(значение.split("; "))
        if not собрано:
            continue
        if вопрос.несколько:
            готово[ключ] = "; ".join(
                в for в in вопрос.варианты if в in собрано)
        else:
            готово[ключ] = собрано[0]
    return готово
