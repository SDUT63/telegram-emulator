#!/usr/bin/env python3
"""
Какое согласие кому нужно.

Электронное согласие бот берёт до первого вопроса — иначе он собирал бы
данные без основания. Но бумажную форму подписывают разные люди и по
разным правилам, и какая именно нужна, становится понятно только после
первого вопроса анкеты: «Вы обращаетесь о себе или о близком человеке?».

Поэтому сразу после этого ответа бот говорит человеку, что ему
понадобится, что взять с собой и где форму посмотреть заранее. Это не
второе согласие — это подготовка ко встрече с координатором.

Правовая часть, из которой всё следует
--------------------------------------
Согласие даёт субъект персональных данных — тот, о чьём здоровье речь.
Родственник субъектом не является. Родство само по себе права
представлять интересы не даёт: нужен документ — решение суда,
акт органа опеки или доверенность (ст. 9 ч. 4 п. 2 ФЗ-152).

Специалист не может дать согласие ни за пациента, ни за его семью.
Он может только передать контакт; согласие оформляет служба при встрече
с самим человеком.

Когда данные получены не от субъекта, ч. 3 ст. 18 обязывает уведомить
его до начала обработки. Текст уведомления — Приложение Б комплекта
форм; произносит координатор при первом звонке.

Тексты правятся здесь и в docs/Согласие-на-обработку-ПД-СДУТ.docx
вместе. Расхождение проверяется тестом.
"""

from __future__ import annotations

# Раздел справочника с формами. Бот шлёт прямую ссылку, чтобы человек
# мог прочитать и распечатать заранее, а не искать по сайту.
APP_URL = "https://sdut.d-lemeshev88.workers.dev/"
DOCS_ANCHOR = APP_URL + "#b-docs"

# Ключ — что человек выбрал в первом вопросе. Сопоставление идёт по
# вхождению подстроки, поэтому подписи кнопок можно править.
FORMS: dict[str, dict[str, str]] = {
    "о себе": {
        "form": "Форма 1",
        "who_signs": "вы сами",
        "text": (
            "Пара слов о бумагах, чтобы потом не было неожиданностей.\n\n"
            "Вам понадобится согласие на обработку данных — вы подписываете "
            "его сами при встрече с координатором. Заранее делать ничего "
            "не нужно.\n\n"
            "С собой: паспорт.\n\n"
            "Посмотреть или распечатать заранее — по кнопке ниже."
        ),
    },
    "о близком": {
        "form": "Форма 2",
        "who_signs": "законный представитель",
        "text": (
            "Пара слов о бумагах — здесь есть тонкость.\n\n"
            "Согласие на обработку данных подписывает сам человек, о котором "
            "идёт речь. Если он может подписать — так проще всего.\n\n"
            "Если не может, подписывает законный представитель. Родство "
            "само по себе такого права не даёт: нужен документ — решение "
            "суда, акт органа опеки или доверенность.\n\n"
            "И ещё: закон обязывает нас сказать самому человеку, что вы к нам "
            "обратились. Координатор сделает это при первом звонке.\n\n"
            "С собой: паспорт и документ о полномочиях, если подписываете вы.\n\n"
            "Посмотреть формы заранее — по кнопке ниже."
        ),
    },
    "специалист": {
        "form": "оформляет служба",
        "who_signs": "сам человек или его представитель",
        "text": (
            "О бумагах: согласие за пациента специалист дать не может — "
            "по закону его подписывает сам человек либо его законный "
            "представитель.\n\n"
            "От вас нужен только контакт. Согласие оформит координатор "
            "при встрече, и он же уведомит человека, что обращение поступило "
            "от вас, — этого требует часть 3 статьи 18 закона о персональных "
            "данных.\n\n"
            "Формы, которые будут подписаны, — по кнопке ниже."
        ),
    },
}


def for_answer(answer: str) -> dict[str, str] | None:
    """Какая форма нужна тому, кто так ответил на первый вопрос."""
    low = (answer or "").lower()
    for key, form in FORMS.items():
        if key in low:
            return form
    return None


def note(answers: dict[str, str]) -> dict[str, object] | str:
    """Что сказать про бумаги и куда отправить смотреть.

    Возвращаем и текст, и ссылку: движок приложит ссылку кнопкой под
    сообщением. Пусто — значит, говорить нечего.
    """
    form = for_answer(answers.get("who", ""))
    if not form:
        return ""
    return {
        "text": form["text"],
        "links": [("Посмотреть формы согласия", DOCS_ANCHOR)],
    }
