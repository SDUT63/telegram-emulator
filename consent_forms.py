#!/usr/bin/env python3
"""
Какое согласие кому нужно.

Электронное согласие бот берёт до первого вопроса — иначе он собирал бы
данные без основания. Но бумажную форму подписывают разные люди и по
разным правилам, и какая именно нужна, становится понятно только после
первого вопроса анкеты: «Вы обращаетесь о себе или о близком человеке?».

Поэтому сразу после этого ответа бот говорит человеку, что его ждёт.
Это не второе согласие — это подготовка ко встрече с координатором.

Почему так коротко
------------------
Здесь легко написать абзац про решение суда, акт органа опеки и
доверенность — и потерять человека на втором вопросе анкеты. Он пришёл,
потому что дома лежачая мать, а получает лекцию о законодательстве.

Поэтому в чате остаётся только то, что человеку действительно надо знать
сейчас: кто подпишет и что готовить не нужно. Подробности — в полном
тексте согласия, который бот пришлёт по кнопке, и в разговоре
с координатором, где на вопросы отвечает живой человек.

Правовая часть, из которой всё следует
--------------------------------------
Согласие даёт субъект персональных данных — тот, о чьём здоровье речь.
Родственник субъектом не является. Родство само по себе права
представлять интересы не даёт: нужен документ — решение суда,
акт органа опеки или доверенность (ст. 9 ч. 4 п. 2 ФЗ-152).

Специалист не может дать согласие ни за пациента, ни за его семью.
Он может только передать контакт; согласие оформляет служба при встрече
с самим человеком.

Когда данные получены не от субъекта, ч. 3 ст. 18 обязывает уведомить
его до начала обработки. Текст уведомления — Приложение Б комплекта
форм; произносит координатор при первом звонке.

Тексты правятся здесь и в docs/Согласие-на-обработку-ПД-СДУТ.docx
вместе. Расхождение проверяется тестом.
"""

from __future__ import annotations

# Ключ — что человек выбрал в первом вопросе. Сопоставление идёт по
# вхождению подстроки, поэтому подписи кнопок можно править.
FORMS: dict[str, dict[str, str]] = {
    "о себе": {
        "form": "Форма 1",
        "who_signs": "вы сами",
        "text": (
            "Про бумаги — совсем коротко.\n\n"
            "Согласие вы подпишете сами при встрече с координатором. "
            "Заранее готовить ничего не нужно, паспорта достаточно.\n\n"
            "Что именно подпишете — по кнопке ниже."
        ),
    },
    "о близком": {
        "form": "Форма 2",
        "who_signs": "сам человек, а если он не может — его законный представитель",
        "text": (
            "Про бумаги — коротко, чтобы потом не было неожиданностей.\n\n"
            "Согласие подписывает сам человек, о котором идёт речь. "
            "Если он этого сделать не может — его законный представитель, "
            "по документу.\n\n"
            "Разберётесь не в одиночку: координатор посмотрит вашу "
            "ситуацию и скажет, что именно нужно. Заранее собирать "
            "документы не надо.\n\n"
            "Что именно подпишете — по кнопке ниже."
        ),
    },
    "специалист": {
        "form": "оформляет служба",
        "who_signs": "сам человек или его законный представитель",
        "text": (
            "Про бумаги — коротко.\n\n"
            "Согласие за пациента специалист дать не может: подписывает "
            "сам человек либо его представитель. От вас нужен только "
            "контакт.\n\n"
            "Согласие оформит координатор при встрече. Он же скажет "
            "человеку, что обращение поступило от вас, — этого требует "
            "часть 3 статьи 18 закона о персональных данных.\n\n"
            "Что подпишет человек — по кнопке ниже."
        ),
    },
}


def for_answer(answer: str) -> dict[str, str] | None:
    """Какая форма нужна тому, кто так ответил на первый вопрос."""
    low = (answer or "").lower()
    for key, form in FORMS.items():
        if key in low:
            return form
    return None


def note(answers: dict[str, str]) -> str:
    """Что сказать про бумаги сразу после первого ответа.

    Пусто — значит, говорить нечего: движок тогда ничего не приписывает.
    """
    form = for_answer(answers.get("who", ""))
    return form["text"] if form else ""


def signs(answers: dict[str, str]) -> str:
    """Кто подписывает бумажную форму. Строка для полного текста согласия."""
    form = for_answer(answers.get("who", ""))
    return form["who_signs"] if form else ""
