"""Сборка видеомануала из самого бота.

Кадры не снимаются с телефона. Скрипт прогоняет настоящий класс Survey
по реальному случаю и спрашивает у max_bot ту раскладку кнопок, которую
бот и правда пришлёт. Поэтому видео не может разойтись с ботом: поменяли
вопрос — пересобрали, и в мануале он уже другой.

Что нужно: playwright с Chromium и ffmpeg (ставится вместе с
imageio-ffmpeg). Запуск из корня проекта:

    python webapp/инструкция/сборка-видео.py

Результат — Полный-мануал-СДУТ-бот.mp4 рядом с этим файлом.
"""
