import шрифт                                            # noqa: E402
from chatbot_survey import Survey                       # noqa: E402

ШИРИНА, ВЫСОТА, КАДРОВ_В_СЕКУНДУ = 540, 960, 30
ЧЕЛОВЕК = "мануал"

# ------------------------------------------------------------------ случай
