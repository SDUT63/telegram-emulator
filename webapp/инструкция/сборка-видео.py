# Сколько секунд держать кадр. Читающему медленно нужно время, но
# однообразные экраны подряд усыпляют — держим их короче.
ПАУЗА_ОБЫЧНАЯ = 2.6
ПАУЗА_С_ПОЯСНЕНИЕМ = 4.0
ПАУЗА_ТРЕВОГА = 5.2
ПАУЗА_ПЕРВАЯ = 5.0
ПАУЗА_ПОСЛЕДНЯЯ = 6.0

# Длиннее этого сообщение в кадр не поместится: телефон пришлось бы ужать
# до нечитаемого. Такие сообщения у бота есть — например, перечень всех
# ответов в конце, — и в кадре мы показываем их начало.
ПРЕДЕЛ_КАДРА = 1000


def укоротить(текст: str) -> str:
    """Обрезать слишком длинное сообщение по абзацу, а не по букве."""
    if len(текст) <= ПРЕДЕЛ_КАДРА:
        return текст
    куски = текст.split("\n\n")
    вышло = ""
    for кусок in куски:
        если_добавить = (вышло + "\n\n" + кусок) if вышло else кусок
        if len(если_добавить) > ПРЕДЕЛ_КАДРА:
            break
        вышло = если_добавить
    return (вышло or текст[:ПРЕДЕЛ_КАДРА]) + "\n\n… дальше в чате"


def _номер(question: dict, ответ: str) -> int:
    """Номер варианта по его подписи — чтобы сценарий читался словами."""
    return question["options"].index(ответ) + 1


def собрать_кадры() -> dict:
    """Прогнать анкету и записать, что бот показывает на каждом шаге."""
    папка = tempfile.mkdtemp()
    survey = Survey(storage_path=os.path.join(папка, "мануал.json"),
                    list_options=False)
    кадры: list[dict] = []
    раздел = "Начало"

    def кнопки(подсветить: str = "") -> list[list[str]]:
        """Раскладка бота построчно; нажимаемую кнопку помечаем «@»."""
        строки = []
        for row in max_bot.layout(survey, ЧЕЛОВЕК):
            строки.append([("@" if подсветить and label.endswith(подсветить)
                            else "") + label for label, _ in row])
        return строки

    # --- согласие: то, с чего теперь начинается любой разговор
    текст = survey.handle(ЧЕЛОВЕК, "здравствуйте")
    кадры.append({"kind": "chat", "text": укоротить(текст), "keys": кнопки("продолжим"),
                  "where": "Начало",
                  "note": "Написали «здравствуйте». Бот здоровается и просит "
                          "согласие. Экран короткий — полный текст под кнопкой",
                  "hold": ПАУЗА_ПЕРВАЯ})

    # Ради этого кадра всё и затевалось: полный текст согласия приходит
    # сообщением в тот же чат, а не ссылкой на сайт.
    кадры.append({"kind": "chat", "text": укоротить(survey.consent_text(ЧЕЛОВЕК)),
                  "keys": кнопки("продолжим"), "where": "Полный текст",
                  "note": "Нажали «Прочитать полностью» — весь текст приходит "
                          "сюда же. Никуда уходить не надо",
                  "hold": ПАУЗА_ТРЕВОГА})

    текст = survey.handle(ЧЕЛОВЕК, "согласен")
    было_тревог = 0
    тревога = False          # предыдущий ответ поднял предупреждение

    def кадр(**поля) -> dict:
        """Кадр анкеты. Если бот предупредил — кадр помечается и держится дольше.

        Предупреждение бот дописывает к следующему сообщению, отдельного
        не шлёт. Поэтому и здесь оно не отдельный кадр, а тот же экран,
        только с жёлтой полосой и подольше на экране.
        """
        nonlocal тревога
        поля["text"] = укоротить(поля["text"])
        if тревога:
            тревога = False
            поля.update(kind="alert", where="Бот предупреждает",
                        note="Такое предупреждение бот показывает сразу, "
                             "не дожидаясь конца анкеты",
                        hold=ПАУЗА_ТРЕВОГА)
        return поля

    for ключ, ответ, пояснение in СЦЕНАРИЙ:
        место = survey.current(ЧЕЛОВЕК)
        if место is None:
            break
        step, question = место
        if question["id"] != ключ:
            raise SystemExit(
                f"сценарий разошёлся с анкетой: ждали «{ключ}», "
                f"а бот спрашивает «{question['id']}». Поправьте СЦЕНАРИЙ."
            )
        раздел = question.get("section", раздел)

        держать = ПАУЗА_С_ПОЯСНЕНИЕМ if пояснение else ПАУЗА_ОБЫЧНАЯ

        if isinstance(ответ, str):
            # Вопрос, где печатают руками: показываем и вопрос, и ответ
            кадры.append(кадр(kind="typed", text=текст + "\n@@" + ответ,
                              keys=None, where=раздел, note=пояснение,
                              hold=держать))
            текст = survey.handle(ЧЕЛОВЕК, ответ)
        elif question.get("multi"):
            # Мультивыбор: сначала пустой список, потом с отметками
            первый = кадр(kind="chat", text=текст, keys=кнопки(),
                          where=раздел, note=пояснение, hold=держать)
            кадры.append(первый)
            for имя in ответ:
                survey.toggle(ЧЕЛОВЕК, step, question["options"].index(имя))
            отмечено = survey.picked_names(ЧЕЛОВЕК, step)
            # Отметка не создаёт нового сообщения — бот правит то же самое,
            # поэтому и предупреждение над ним никуда не девается
            кадры.append({"kind": первый["kind"],
                          "text": укоротить(текст + "\n\nОтмечено: "
                                            + ", ".join(отмечено)),
                          "keys": кнопки("Готово · %d" % len(отмечено)),
                          "where": первый["where"],
                          "note": "Отмеченное видно и галочкой, и словами",
                          "hold": ПАУЗА_С_ПОЯСНЕНИЕМ})
            # «Готово» шлёт отмеченное тем же путём, что и напечатанные
            # номера — как это делает max_bot по кнопке d:<шаг>
            текст = survey.answer_by_numbers(
                ЧЕЛОВЕК, [i + 1 for i in survey.picked(ЧЕЛОВЕК, step)])
        else:
            кадры.append(кадр(kind="chat", text=текст, keys=кнопки(ответ[0]),
                              where=раздел, note=пояснение, hold=держать))
            текст = survey.answer_by_numbers(
                ЧЕЛОВЕК, [_номер(question, ответ[0])])

        стало = len(survey.state[ЧЕЛОВЕК]["alerts"])
        if стало > было_тревог:
            было_тревог = стало
            тревога = True

    if survey.current(ЧЕЛОВЕК) is not None:
        текст = survey.handle(ЧЕЛОВЕК, "далее")
    кадры.append(кадр(kind="chat", text=текст, keys=кнопки(),
                      where="Готово",
                      note="Заявка у координатора. Он позвонит по указанному "
                           "телефону, а следом бот выпишет все ваши ответы",
                      hold=ПАУЗА_ПОСЛЕДНЯЯ))
    кадры[-1]["hold"] = ПАУЗА_ПОСЛЕДНЯЯ

    слишком = [f for f in кадры if len(f["text"]) > ПРЕДЕЛ_КАДРА + 8]
    if слишком:
        raise SystemExit("в кадр не поместится: " + слишком[0]["text"][:80])

    return {"frames": кадры, "alerts": survey.state[ЧЕЛОВЕК]["alerts"]}


def нарисовать(данные: dict, куда: str) -> list[str]:
    """Отрисовать каждый кадр браузером — текст выходит резким на любом размере."""
    from playwright.sync_api import sync_playwright

    шаблон = open(os.path.join(ЗДЕСЬ, "кадры.html"), encoding="utf-8").read()
    страница = шрифт.вшить(шаблон).replace(
        "__ДАННЫЕ__", json.dumps(данные, ensure_ascii=False))
    путь = os.path.join(куда, "кадр.html")
    open(путь, "w", encoding="utf-8").write(страница)

    файлы = []
    with sync_playwright() as pw:
        браузер = pw.chromium.launch(executable_path=os.getenv(
            "CHROME", "/opt/pw-browsers/chromium-1194/chrome-linux/chrome"))
        лист = браузер.new_page(
            viewport={"width": ШИРИНА, "height": ВЫСОТА}, device_scale_factor=2)
        for i in range(len(данные["frames"])):
            # Номер кадра идёт в адресе: переход по «#» страницу не перерисует
            лист.goto(f"file://{путь}?{i}", wait_until="domcontentloaded")
            лист.evaluate("document.fonts.ready")
            лист.wait_for_timeout(120)
            имя = os.path.join(куда, "f%03d.png" % i)
            лист.screenshot(path=имя)
            файлы.append(имя)
        браузер.close()
    return файлы


def склеить(файлы: list[str], паузы: list[float], куда: str) -> str:
    """Собрать кадры в mp4: каждый висит столько, сколько ему отмерено."""
    import imageio_ffmpeg

    список = os.path.join(os.path.dirname(файлы[0]), "список.txt")
    with open(список, "w", encoding="utf-8") as fh:
        for имя, пауза in zip(файлы, паузы):
            fh.write("file '%s'\nduration %.2f\n" % (имя, пауза))
        fh.write("file '%s'\n" % файлы[-1])      # последний кадр — ещё раз

    subprocess.run(
        [imageio_ffmpeg.get_ffmpeg_exe(), "-y", "-f", "concat", "-safe", "0",
         "-i", список, "-vf", f"fps={КАДРОВ_В_СЕКУНДУ},format=yuv420p",
         # preset medium, а не slow: кадры статичные, разницы в размере почти
         # нет, а пересборка после правки вопросов должна быть дешёвой
         "-c:v", "libx264", "-preset", "medium", "-crf", "23",
         "-movflags", "+faststart", куда],
        check=True, capture_output=True)
    return куда


def main() -> None:
    данные = собрать_кадры()
    print("кадров:", len(данные["frames"]))
    print("тревоги в анкете:", "; ".join(данные["alerts"]) or "нет")

    папка = tempfile.mkdtemp()
    try:
        файлы = нарисовать(данные, папка)
        готово = склеить(файлы, [f["hold"] for f in данные["frames"]],
                         os.path.join(ЗДЕСЬ, "Полный-мануал-СДУТ-бот.mp4"))
    finally:
        shutil.rmtree(папка, ignore_errors=True)

    секунд = sum(f["hold"] for f in данные["frames"])
    print("готово: %s (%d:%02d)" % (готово, секунд // 60, секунд % 60))


if __name__ == "__main__":
    main()
