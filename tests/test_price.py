def test_ни_одна_цена_не_ниже_себестоимости():
    """Главная проверка всего прайса.

    В присланном файле смены, сутки и проживание продавались ниже
    себестоимости, и это было не видно: маржу считали без накладных
    расходов и без резерва отпусков. Пока цены выводятся формулой,
    такое невозможно — но формулу можно однажды поправить руками.
    """
    для_проверки = [
        ("v1", 1, 0.0, экономика.ДОРОГА),
        ("v2", 2, 0.0, экономика.ДОРОГА),
        ("v3", 3, 0.0, экономика.ДОРОГА),
        ("v4", 4, 0.0, экономика.ДОРОГА),
        ("escort", 4, 0.0, экономика.ДОРОГА),
        ("shift8", 8, 0.0, экономика.ДОРОГА),
        ("day12", 12, 0.0, экономика.ДОРОГА),
        ("night12", 12, 8.0, экономика.ДОРОГА),
        ("live_in", 8, 0.0, экономика.ДОРОГА / 7),
    ]
    for ид, блок, ночных, дорога in для_проверки:
        цена = прайс.найти(ид).цена
        себестоимость = экономика.услуга(
            блок, ночных=ночных, дорога=дорога).себестоимость
        assert цена >= себестоимость, (
            f"{ид}: цена {цена} ₽ ниже себестоимости {себестоимость:.0f} ₽")


def test_пакеты_не_ниже_себестоимости():
    """Пакет — это то, ради чего служба существует. Продавать его
    в минус значит держаться на грантах и звать это бизнес-моделью."""
    блоки = {1: 2, 2: 3, 3: 4}
    for пакет in прайс.ПАКЕТЫ:
        за_час = экономика.час(блоки[пакет.уровень]).себестоимость
        assert пакет.цена >= за_час * пакет.часов_в_месяц, пакет.название


def test_круглосуточно_это_сумма_двух_смен():
    """Сутки собираются из дневной и ночной смены, а не назначаются
    отдельно: иначе одно разойдётся с другим при первом пересчёте."""
    сутки = прайс.найти("round").цена
    assert сутки == прайс.найти("day12").цена + прайс.найти("night12").цена


def test_час_дешевеет_с_длиной_блока():
    """Единственная причина, по которой час в пакете дешевле часа
    в разовом визите, — дорога размазывается на большее число часов.
    Если лесенка сломалась, значит цену где-то вписали руками."""
    лесенка = [прайс.найти(и).цена / прайс.найти(и).часов
               for и in ("v1", "v2", "v3", "v4", "shift8", "day12")]
    assert лесенка == sorted(лесенка, reverse=True), [round(ц) for ц in лесенка]


def test_визит_на_час_самый_дорогой_по_часу():
    """Полчаса дороги на один оплаченный час. Это надо говорить вслух,
    а не прятать: иначе человек берёт часовые визиты и удивляется счёту."""
    по_часу = {у.id: у.цена / у.часов for у in прайс.УСЛУГИ if у.часов}
    assert max(по_часу, key=по_часу.get) == "first_visit"   # организатор дороже
    без_организатора = {и: ц for и, ц in по_часу.items() if и != "first_visit"}
    assert max(без_организатора, key=без_организатора.get) == "v1"


