def test_каждый_час_чем_то_оплачен():
    """Главная проверка прайса.

    Цена задана рынком и потому ниже себестоимости — это замысел,
    а не ошибка. Но разрыв должен быть закрыт: то, что платит семья,
    плюс то, что дают программы, обязано покрывать себестоимость,
    налог и резерв. Иначе служба обещает уход, который нечем оплатить,
    и узнает об этом на третий месяц.
    """
    for ид in ВСЕ:
        п = прайс.покрытие(ид)
        сошлось = п.платит_семья + п.нужно_программ
        нужно = п.себестоимость + п.налог + п.резерв
        assert сошлось >= нужно - 0.01, (
            f"{ид}: семья даёт {п.платит_семья:.0f}, программы "
            f"{п.нужно_программ:.0f}, а нужно {нужно:.0f} ₽ за час")


def test_программы_закрывают_меньше_половины():
    """Если программы тянут больше половины каждого часа, это уже
    не платная услуга, а скрытая благотворительность — и она
    кончится вместе с грантом."""
    for ид in ВСЕ:
        доля = прайс.покрытие(ид).доля_семьи
        assert доля > 0.5, f"{ид}: семья платит только {доля * 100:.0f} %"


def test_цены_не_выше_рынка():
    """Прайс, который невозможно продать, — это не прайс.
    В Тольятти агентства просят 250–350 ₽ за час; короткий визит
    дороже у всех, потому что дорога ложится на один час."""
    _, верх = прайс.РЫНОК["агентство_в_час"]
    for пакет in прайс.ПАКЕТЫ:
        за_час = пакет.цена / пакет.часов_в_месяц
        assert за_час <= верх, f"{пакет.название}: {за_час:.0f} ₽/ч дороже рынка"
    for у in прайс.УСЛУГИ:
        за_час = у.цена / у.часов
        предел = 700 if у.id == "first_visit" else 500
        assert за_час <= предел, f"{у.название}: {за_час:.0f} ₽/ч"


def test_цены_не_ниже_частного_объявления():
    """Ниже частника уходить нельзя: это значило бы демпинговать
    против людей, которые ухаживают за деньги, и обещать то,
    что не сойдётся даже с программами."""
