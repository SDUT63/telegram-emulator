"""Прайс: цифры и арифметика.

Проверяем не «работает ли код», а то, из-за чего человеку назовут
неверную сумму: разошлись цены с прайс-листом, взяли надбавку дважды,
показали скидку, которая к этому договору не относится.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))

import прайс                                                   # noqa: E402


# --------------------------------------------------------------- цифры

# Выписано из прайс-листа руками. Смысл таблицы в том, чтобы
# опечатка в модуле не прошла молча: тут цифры второй раз и из
# другого источника.
ЦЕНЫ = {
    "first_visit": 2000, "trial": 1200,
    "v1": 1100, "v2": 1490, "v3": 1930, "v4": 2340, "escort": 2340,
    "shift8": 2600, "day12": 3700, "night12": 4200,
    "round": 7700, "live_in": 2700,
}


@pytest.mark.parametrize("ид,цена", sorted(ЦЕНЫ.items()))
def test_цена_услуги_как_в_прайсе(ид, цена):
    assert прайс.найти(ид).цена == цена


@pytest.mark.parametrize("уровень,цена,часов", [(1, 20900, 52.14),
                                                (2, 32600, 86.9),
                                                (3, 40100, 112.97)])
def test_пакет_как_в_прайсе(уровень, цена, часов):
    пакет = прайс.найти(f"level{уровень}")
    assert пакет.цена == цена
    assert пакет.часов_в_месяц == часов


def test_все_позиции_прайса_различимы():
    ид = [у.id for у in прайс.УСЛУГИ] + [f"level{п.уровень}" for п in прайс.ПАКЕТЫ]
    assert len(ид) == len(set(ид)), "две позиции с одним идентификатором"


def test_каталог_услуг_полный_и_по_порядку():
    """Приложение № 6 к Приказу № 731 — ровно пятьдесят услуг."""
    номера = [н for н, _, _ in прайс.КАТАЛОГ]
    assert номера == list(range(1, 51))


def test_у_каждой_поправки_есть_пояснение():
    """Надбавка без объяснения выглядит как накрутка."""
    без = [п.id for п in прайс.ПОПРАВКИ if len(п.пояснение) < 20]
    assert без == [], без


# ------------------------------------------------------------ арифметика

def test_без_поправок_платят_прайс():
    assert прайс.посчитать("v2")["итог"] == 1490


def test_несколько_визитов_умножаются():
    assert прайс.посчитать("v1", 10)["итог"] == 11000


def test_надбавки_складываются_к_базе_а_не_друг_к_другу():
    """+20 % и +50 % — это +70 % от базы, а не 1.2 × 1.5 = +80 %.
    Так написано в прайсе, и так же должен считать договор."""
    итог = прайс.посчитать("v2", 1, ["weekend", "holiday"])
    assert итог["процент"] == 70
    assert итог["за_единицу"] == round(1490 * 1.7)


def test_скидка_вычитается():
    итог = прайс.посчитать("level1", 1, ["veteran"])
    assert итог["процент"] == -10
    assert итог["итог"] == round(20900 * 0.9)


def test_надбавка_и_скидка_вместе():
    итог = прайс.посчитать("level2", 1, ["dementia", "prepay3"])
    assert итог["процент"] == 15
    assert итог["итог"] == round(32600 * 1.15)


def test_ночная_надбавка_не_берётся_дважды():
    """У ночной смены двадцать процентов за ночь уже в цене.
    Взять их второй раз — это приписать семье 840 ₽ ни за что."""
    итог = прайс.посчитать("night12", 1, ["night"])
    assert итог["итог"] == 4200
    assert итог["учтено"] == []
    assert итог["пропущено"] == ["night"]


def test_ночная_надбавка_к_круглосуточному_тоже_не_берётся():
    итог = прайс.посчитать("round", 1, ["night"])
    assert итог["итог"] == 7700


def test_ночная_надбавка_к_дневной_смене_берётся():
    """Дневная смена в 21:00 не кончается там, где начинается ночь:
    если помощник задержался, надбавка законная."""
    итог = прайс.посчитать("day12", 1, ["night"])
    assert итог["итог"] == round(3700 * 1.2)


def test_справочная_скидка_не_применяется_молча():
    """«−20 % на второй пакет» — это про второй договор.
    Списать её с этого значило бы посчитать семье не ту сумму."""
    итог = прайс.посчитать("level1", 1, ["second_family"])
    assert итог["итог"] == 20900
    assert итог["пропущено"] == ["second_family"]


def test_скидка_по_реестру_не_считается_процентом():
    итог = прайс.посчитать("level3", 1, ["registry"])
    assert итог["итог"] == 40100
    assert итог["пропущено"] == ["registry"]


def test_цена_не_уходит_в_минус():
    """Совпасть всем скидкам разом маловероятно, но отрицательный
    счёт — это не «бесплатно», это ошибка на экране."""
    все_скидки = [п.id for п in прайс.ПОПРАВКИ if п.скидка and п.процент]
    итог = прайс.посчитать("v1", 1, все_скидки * 12)
    assert итог["итог"] >= 0


def test_цена_за_час_считается_от_времени_у_подопечного():
    assert прайс.посчитать("v4")["в_час"] == round(2340 / 4)
    assert прайс.посчитать("level1")["в_час"] == round(20900 / 52.14)


def test_сиделка_с_проживанием_считается_по_оплачиваемым_часам():
    """В сутках 24 часа, но оплачиваются восемь: остальное —
    присутствие. Делить 2700 на 24 значило бы обещать 113 ₽ в час."""
    assert прайс.найти("live_in").часов == 8
    assert прайс.посчитать("live_in")["в_час"] == round(2700 / 8)


def test_применимые_поправки_не_включают_справочные():
    ид = [п.id for п in прайс.применимы("v1")]
    assert "second_family" not in ид and "registry" not in ид
    assert "night" in ид


def test_неизвестная_позиция_это_ошибка():
    with pytest.raises(KeyError):
        прайс.посчитать("нет-такой")
    with pytest.raises(KeyError):
        прайс.посчитать("v1", 1, ["нет-такой"])


# ---------------------------------------------------- три способа суток

def test_круглосуточные_варианты_идут_от_дешёвого_к_дорогому():
    """Человек должен увидеть разницу в шесть раз раньше,
    чем решит, что круглосуточный уход ему не по карману."""
    суммы = [в["в_месяц"] for в in прайс.КРУГЛОСУТОЧНО]
    assert суммы == sorted(суммы)
    assert суммы[-1] / суммы[0] > 5


def test_месячная_цена_вариантов_сходится_с_суточной():
    для_проверки = {"live_in": 30, "two_shifts": 30}
    for в in прайс.КРУГЛОСУТОЧНО:
        дней = для_проверки.get(в["id"])
        if дней:
            assert в["в_месяц"] == в["в_сутки"] * дней


def test_вариант_с_ночью_на_семье_совпадает_с_пакетом_третьего_уровня():
    семья = next(в for в in прайс.КРУГЛОСУТОЧНО if в["id"] == "family_night")
    assert семья["в_месяц"] == прайс.найти("level3").цена


# ------------------------------------------------------------- выгрузка

def test_выгрузка_прайса_совпадает_с_модулем():
    """Страница считает по JSON. Разойдётся с модулем — семье
    назовут одну сумму на экране и другую в договоре."""
    готово = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "собрать_данные.py")],
        capture_output=True, text=True, cwd=КОРЕНЬ)
    assert готово.returncode == 0, готово.stderr

    выгрузка = json.loads((КОРЕНЬ / "webapp" / "price.json")
                          .read_text(encoding="utf-8"))
    цены = {у["id"]: у["цена"] for у in выгрузка["услуги"]}
    assert цены == {у.id: у.цена for у in прайс.УСЛУГИ}

    пакеты = {п["id"]: п["цена"] for п in выгрузка["пакеты"]}
    assert пакеты == {f"level{п.уровень}": п.цена for п in прайс.ПАКЕТЫ}

    assert len(выгрузка["каталог"]) == 50
    assert len(выгрузка["поправки"]) == len(прайс.ПОПРАВКИ)
