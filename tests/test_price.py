def test_без_программ_служба_не_выходит_в_ноль():
    """Самый неприятный вывод рыночной цены, и его надо видеть.

    На рыночной цене вклад одного часа — двадцать с небольшим
    рублей: постоянные расходы он закроет только при объёме,
    которого у начинающей службы не бывает.
    """
    средняя = (sum(у.цена / у.часов for у in прайс.УСЛУГИ if у.часов)
               / len(прайс.УСЛУГИ))
    без_программ = экономика.безубыточность(средняя)
    assert без_программ > 2000, без_программ

    средним_покрытием = (sum(прайс.покрытие(и).нужно_программ for и in ВСЕ)
                         / len(ВСЕ))
    с_программами = экономика.безубыточность(средняя, средним_покрытием)
    assert 300 < с_программами < 1200, с_программами
    assert с_программами < без_программ / 3


