def test_без_поправок_платят_прайс():
    assert прайс.посчитать("v2")["итог"] == прайс.найти("v2").цена


def test_несколько_визитов_умножаются():
    assert прайс.посчитать("v1", 10)["итог"] == прайс.найти("v1").цена * 10


def test_надбавки_складываются_к_базе_а_не_друг_к_другу():
    """+20 % и +50 % — это +70 % от базы, а не 1.2 × 1.5 = +80 %.
    Так написано в прайсе, и так же должен считать договор."""
    итог = прайс.посчитать("v2", 1, ["weekend", "holiday"])
    assert итог["процент"] == 70
    assert итог["за_единицу"] == round(прайс.найти("v2").цена * 1.7)


