def test_разбор_часа_складывается_в_себестоимость_а_не_в_цену():
    """Человеку показывают, во что обходится его час и сколько
    из этого платит он сам. Строки должны сходиться, иначе вся
    открытость обесценивается: если не сходится здесь, где ещё?"""
    for ид in ("v1", "v2", "v3", "v4", "shift8"):
        строки = прайс.разбор_часа(ид)
        итог = sum(с for _, с in строки)
        покрытие = прайс.покрытие(ид)
        assert abs(итог - (покрытие.платит_семья
                           + покрытие.нужно_программ)) <= len(строки), ид


def test_себестоимость_сходится_с_расчётом_на_бумаге():
    """Формула выписана здесь второй раз и вручную. Совпадёт —
    значит модуль считает то, что написано в пояснении к прайсу.
    """
    труд = 200 * (1 + 0.5 / 2) * 1.10 * 1.076
    накладные = 90_500 * 0.70 / 1_320
    себестоимость = труд + 12 + накладные
    assert abs(экономика.час(2).себестоимость - себестоимость) < 0.01

    # И то же для покрытия: цена рыночная, разрыв считается от неё.
    цена_часа = прайс.найти("v2").цена / 2
    нужно = себестоимость + цена_часа * 0.06 + себестоимость * 0.10 - цена_часа
    assert abs(прайс.покрытие("v2").нужно_программ - нужно) < 0.01


