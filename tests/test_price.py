def test_пакет_считается_по_длине_визита_а_не_по_часам_месяца():
    """Дорога помощника делится на часы визита, а не на часы месяца.
    Пока в расчёт попадали часы месяца, себестоимость пакета выходила
    почти без дороги — на шестую часть ниже настоящей."""
    for пакет in прайс.ПАКЕТЫ:
        assert 1 <= пакет.блок <= 8, пакет.название
        свой = прайс.покрытие(f"level{пакет.уровень}")
        как_надо = экономика.покрытие(
            пакет.блок, пакет.цена / пакет.часов_в_месяц)
        assert abs(свой.себестоимость - как_надо.себестоимость) < 0.01


