def test_разбор_часа_складывается_ровно_в_цену_на_экране():
    """Человеку показывают, из чего сложился его час. Разбор,
    не сходящийся с ценой рядом, обесценивает всю открытость:
    если не сходится здесь, где ещё не сходится?"""
    for ид in ("v1", "v2", "v3", "v4", "shift8"):
        позиция = прайс.найти(ид)
        строки = прайс.разбор_часа(ид)
        assert sum(с for _, с in строки) == round(позиция.цена / позиция.часов), ид


def test_цена_визита_сходится_с_расчётом_на_бумаге():
    """Формула выписана здесь второй раз и вручную. Совпадёт —
    значит модуль считает то, что написано в пояснении к прайсу.
    """
    труд = 200 * (1 + 0.5 / 2) * 1.10 * 1.076
    накладные = 90_500 * 0.70 / 1_320
    себестоимость = труд + 12 + накладные
    цена_часа = себестоимость / (1 - 0.10) / (1 - 0.06)
    за_визит = -(-(цена_часа * 2) // 10) * 10
    assert прайс.найти("v2").цена == за_визит


