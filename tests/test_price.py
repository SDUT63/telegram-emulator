def test_настройки_экономики_действуют_после_правки():
    """Значения по умолчанию в списке аргументов вычисляются один раз
    при загрузке модуля. Пока они там стояли, правка ДОЛИ_НАКЛАДНЫХ
    или ОБЪЁМА молча ни на что не влияла — и вариант прайса считался
    по старым цифрам."""
    было_доля, было_объём = экономика.ДОЛЯ_НАКЛАДНЫХ, экономика.ОБЪЁМ
    try:
        экономика.ДОЛЯ_НАКЛАДНЫХ = 1.0
        полные = экономика.накладные_на_час()
        экономика.ДОЛЯ_НАКЛАДНЫХ = 0.5
        половина = экономика.накладные_на_час()
        assert полные > половина * 1.9

        экономика.ДОЛЯ_НАКЛАДНЫХ = было_доля
        экономика.ОБЪЁМ = 600
        мало = экономика.час(2).цена
        экономика.ОБЪЁМ = 3000
        много = экономика.час(2).цена
        assert мало > много, "объём службы не влияет на цену часа"
    finally:
        экономика.ДОЛЯ_НАКЛАДНЫХ, экономика.ОБЪЁМ = было_доля, было_объём
