def test_шкала_ссылается_на_живые_вопросы_анкеты():
    анкета = _варианты_анкеты()
    for позиция, (вопрос, таблица) in сопоставление.ПРАВИЛА.items():
        assert вопрос in анкета, f"{позиция}: в анкете нет вопроса {вопрос}"
        for ответ in таблица:
            assert ответ in анкета[вопрос], (
                f"{позиция}: у вопроса {вопрос} нет варианта «{ответ}»")


def test_шкала_разбирает_вопрос_целиком():
    """Неперечисленный вариант — это молча незаполненная позиция."""
    анкета = _варианты_анкеты()
    for позиция, (вопрос, таблица) in сопоставление.ПРАВИЛА.items():
        assert set(таблица) == set(анкета[вопрос]), (
            f"{позиция}: не разобраны варианты "
            f"{set(анкета[вопрос]) - set(таблица)}")


def test_все_позиции_шкалы_учтены():
    все = {п.id for п in шкала.SCALE}
    из_анкеты = set(сопоставление.ПРАВИЛА)
    сами = set(сопоставление.ОТДАНО_ЧЕЛОВЕКУ)
    assert из_анкеты <= все, из_анкеты - все
    assert сами <= все, сами - все
    assert не_пересекаются(из_анкеты, сами)
    assert из_анкеты | сами == все, все - (из_анкеты | сами)


def не_пересекаются(а: set, б: set) -> bool:
    return not (а & б)


def test_опросник_ссылается_на_живые_вопросы():
    анкета = _варианты_анкеты()
    вопросы = {в.id: в for в in уход.ВОПРОСЫ}
    for ключ, правила in сопоставление.ОПРОСНИК.items():
        assert ключ in вопросы, f"в опроснике нет вопроса {ключ}"
        вопрос = вопросы[ключ]
        for анкетный, таблица in правила:
            assert анкетный in анкета, f"{ключ}: в анкете нет {анкетный}"
            for ответ, значение in таблица.items():
                assert ответ in анкета[анкетный], (
                    f"{ключ}: у {анкетный} нет варианта «{ответ}»")
                части = значение.split("; ")
                assert len(части) == 1 or вопрос.несколько, (
                    f"{ключ}: перечисление в вопросе с одним ответом")
                for часть in части:
                    assert часть in вопрос.варианты, (
                        f"{ключ}: нет варианта «{часть}»")


