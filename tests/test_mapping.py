def test_анкета_даёт_план_а_значит_и_цену():
    """Ради этого всё и затевалось: человек вставил анкету — и увидел
    план со стоимостью, ничего не нажимая."""
    ответы = сопоставление.опросник_из_анкеты(ПОЛНАЯ_АНКЕТА)
    assert "день" in ответы, "без «где проводит день» плана не будет"
    шаблон = уход.подобрать(ответы)
