"""Что приложение достраивает за человека из его анкеты бота.

Человек уже рассказал боту, как близкий ест, моется и передвигается.
Просить его отметить то же самое ещё раз — двадцать одну позицию
шкалы и девять вопросов опросника — неуважение к его времени.
Поэтому часть ответов приложение выводит само.

Опасность ровно одна и она тихая. Вариант ответа в анкете бота
переименуют — «Кресло-коляска» станет «На коляске», — и правило
перестанет срабатывать. Ошибки не будет: человек просто увидит
пустой экран вместо плана и не узнает, почему. Поэтому здесь
сверяется каждая строчка обеих таблиц с настоящей анкетой.

Второе свойство, за которым следим: при сомнении берём вариант
полегче. Завысить нуждаемость — значит показать семье уход
за 192 000 ₽ там, где хватит пакета за 16 500.
"""

