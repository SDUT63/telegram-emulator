@pytest.mark.skipif(__import__("shutil").which("node") is None, reason="нет node")
def test_страница_заполняет_опросник_так_же(tmp_path):
    """Правила живут в Python, а работают в телефоне. Разойдутся —
    человек с той же анкетой увидит другой план и другую цену."""
    страница = ШАБЛОН_СТРАНИЦЫ.read_text(encoding="utf-8")
    найдено = re.search(r"\n  function заполнитьОпросник\(\)\{.*?\n  \}\n",
                        страница, re.S)
    assert найдено, "на странице нет заполнитьОпросник"

    план = json.loads((КОРЕНЬ / "webapp" / "care.json").read_text(encoding="utf-8"))
    случаи = [ПОЛНАЯ_АНКЕТА, ЛЁГКАЯ_АНКЕТА, {}, {"mobility": "Кресло-коляска"},
              {"caregiver": "Почти никто"}, {"hours": "Круглосуточно"}]
    обвязка = """
const ПЛАН = %s;
const СЛУЧАИ = %s;
let ОТВЕТЫ_АНКЕТЫ = {}, ОТВЕТЫ_ПЛАНА = {}, ИЗ_АНКЕТЫ_ПЛАН = {};
function save(){}
%s
const итоги = СЛУЧАИ.map(о => {
  ОТВЕТЫ_АНКЕТЫ = о; ОТВЕТЫ_ПЛАНА = {}; ИЗ_АНКЕТЫ_ПЛАН = {};
  заполнитьОпросник();
  return ОТВЕТЫ_ПЛАНА;
});
console.log(JSON.stringify(итоги));
""" % (json.dumps(план, ensure_ascii=False),
       json.dumps(случаи, ensure_ascii=False),
       найдено.group(0))

    файл = tmp_path / "опросник.mjs"
    файл.write_text(обвязка, encoding="utf-8")
    готово = subprocess.run(["node", str(файл)], capture_output=True, text=True)
    assert готово.returncode == 0, готово.stderr

    for ответы, из_js in zip(случаи, json.loads(готово.stdout)):
        assert из_js == сопоставление.опросник_из_анкеты(ответы), ответы


