def test_несколько_вариантов_в_порядке_вопроса():
    ответы = сопоставление.опросник_из_анкеты(ПОЛНАЯ_АНКЕТА)
    порядок = {в.id: list(в.варианты) for в in уход.ВОПРОСЫ}
    for ключ, значение in ответы.items():
        части = значение.split("; ")
        assert части == [в for в in порядок[ключ] if в in части], ключ


