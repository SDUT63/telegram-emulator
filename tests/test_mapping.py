def test_у_каждой_программы_есть_состояние_и_срок():
    for п in прайс.ПРОГРАММЫ:
        assert п["состояние"] in (прайс.ДЕЙСТВУЕТ, прайс.В_ОЖИДАНИИ), п["id"]
        assert п.get("когда"), f"{п['id']}: не сказано, когда этого ждать"


def test_сду_в_ожидании_и_город_назван():
    """Система долговременного ухода идёт по области пилотом, в Тольятти
    её нет. Пока это так, часы по ней обещать нельзя."""
    сду = [п for п in прайс.ПРОГРАММЫ if п["id"] == "сду"][0]
    assert сду["состояние"] == прайс.В_ОЖИДАНИИ
    текст = сду["когда"] + " " + сду["что_закрывает"] + " " + сду["как_попасть"]
    assert "Тольятти" in текст
    assert "2027" in сду["когда"]


