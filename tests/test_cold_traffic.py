"""Человек пришёл из социальной рекламы и пишет своими словами.

Это основной способ, которым люди попадают в бота: увидели объявление,
нажали, и пишут так, как говорят дома. Подпись кнопки никто не
переписывает — пишут «мама», «за бабушкой», «ей 82», «утречком».

До этих проверок бот отвечал «Напишите номер ответа — от 1 до 3» на
каждую такую фразу и не двигался с места. Хуже того: на второй попытке
он обещал «напишите словами, как есть на самом деле, координатор
разберётся, ответ не пропадёт» — и следующую же фразу отвергал снова.
Обещание, которое бот не держит, дороже молчания.
"""
from __future__ import annotations

import pytest

import emergency
import survey_questions
from chatbot_survey import Survey
from survey_questions import QUESTIONS


@pytest.fixture()
def анкета(tmp_path):
    s = Survey(storage_path=str(tmp_path / "r.json"), list_options=False)
    s.handle("u1", "здравствуйте")
    s.grant_consent("u1")
    return s


def _ответ(анкета, user_id: str = "u1") -> str:
    return (анкета.state.get(user_id) or {}).get("answers", {}).get("who", "")


# ------------------------------------------------ свои слова вместо кнопки

БЫТОВЫЕ = [
    ("мама", "О близком человеке"),
    ("ухаживаю за папой", "О близком человеке"),
    ("за бабушкой смотрю", "О близком человеке"),
    ("муж лежит после инсульта", "О близком человеке"),
    ("о себе", "О себе"),
    ("я сама себе", "О себе"),
    ("я соцработник", "Я специалист"),
    ("по работе", "Я специалист"),
]


@pytest.mark.parametrize("фраза,ожидание", БЫТОВЫЕ)
def test_бытовая_фраза_засчитывается_с_первого_раза(анкета, фраза, ожидание):
    """Первый вопрос — место, где холодный человек уходит чаще всего."""
    анкета.handle("u1", фраза)
    assert _ответ(анкета) == ожидание, f"{фраза!r} не понято"


def test_двусмысленная_фраза_не_угадывается(анкета):
    """«Записанная догадка читается координатором как факт».

    «Я сиделка, обращаюсь о своей маме» — и специалист, и близкий.
    Выбрать одно значит записать в карточку неправду.
    """
    варианты = QUESTIONS[0]["options"]
    assert Survey._по_синонимам(
        "who", варианты, "я сиделка, обращаюсь о своей маме"
    ) is None


def test_возраст_числом(анкета):
    """«82» — это возраст, а не восемьдесят второй вариант ответа."""
    for число, группа in (("58", "До 60 лет"), ("70", "60–74 года"),
                          ("82", "75–84 года"), ("91", "85 и старше")):
        assert survey_questions.толкование("age", число) == группа

    # За пределами человеческого возраста — не возраст.
    assert survey_questions.толкование("age", "7") is None
    assert survey_questions.толкование("age", "200") is None
    # В любом другом вопросе число остаётся номером варианта.
    assert survey_questions.толкование("who", "82") is None


def test_отрицание_сильнее_утверждения(анкета):
    """«Не знает» содержит «знает» — и означает ровно обратное."""
    варианты = ["Да, знает", "Нет, не знает", "Не может понять"]
    assert Survey._по_синонимам("aware", варианты, "не знает") == "Нет, не знает"
    assert Survey._по_синонимам("aware", варианты, "знает") == "Да, знает"


def test_короткое_слово_не_ловится_серединой_чужого(анкета):
    """«Да» не должно срабатывать на «давление», «нет» — на «нету сил»."""
    варианты = ["Да, знает", "Нет, не знает", "Не может понять"]
    assert Survey._по_синонимам("aware", варианты, "у него давление") is None
    assert Survey._по_синонимам("aware", варианты, "нету сил объяснять") is None


# ----------------------------------------------------- обещание про «словами»

def test_обещание_написать_словами_выполняется(анкета):
    """Вторая ступень лесенки обещает, что слова примут. Проверяем обещание."""
    первый = анкета.handle("u1", "ыыы")
    assert "нажмите кнопку" in первый

    второй = анкета.handle("u1", "ыыы")
    assert "напишите словами" in второй.lower(), "лесенка изменилась — проверка устарела"

    шаг_до = анкета.current("u1")[0]
    третий = анкета.handle("u1", "затрудняюсь сказать")

    assert анкета.current("u1")[0] != шаг_до, "слова обещали принять, а вопрос не сменился"
    assert "затрудняюсь сказать" in третий


def test_принятое_словами_попадает_в_карточку(анкета):
    анкета.handle("u1", "ыыы")
    анкета.handle("u1", "затрудняюсь сказать")

    assert _ответ(анкета) == "затрудняюсь сказать"


def test_стук_по_клавиатуре_ответом_не_становится(анкета):
    """«ыыы» в карточке — это враньё координатору, а не ответ."""
    for _ in range(5):
        анкета.handle("u1", "ыыы")

    assert _ответ(анкета) == "", "мусор записан как ответ"
    assert анкета.current("u1")[0] == 0, "вопрос сменился от бессмыслицы"


def test_первая_попытка_всё_ещё_зовёт_к_кнопкам(анкета):
    """Один раз показать кнопки стоит: вариант мог и подойти."""
    ответ = анкета.handle("u1", "затрудняюсь сказать")

    assert анкета.current("u1")[0] == 0
    assert "кнопк" in ответ.lower()


def test_словами_принимают_только_там_где_есть_кнопки(анкета):
    """Телефон и адрес проверяются по существу: «как есть» тут не работает.

    По слову вместо номера координатор не дозвонится, и обещать
    обратное нельзя.
    """
    for вопрос in QUESTIONS:
        if вопрос["kind"] in ("phone", "address", "email"):
            assert Survey._свои_слова(вопрос, "потом скажу") is False, вопрос["id"]


def test_угроза_жизни_идёт_раньше_свободного_ответа(анкета):
    """Свободный ответ не должен проглотить «он не дышит»."""
    анкета.handle("u1", "ыыы")
    ответ = анкета.handle("u1", "он не дышит совсем")

    assert ответ.startswith("Если это происходит прямо сейчас")
    assert _ответ(анкета) == "", "тревога записана как ответ на вопрос"


# --------------------------------------------------------- целость словаря

def test_синонимы_ссылаются_на_существующие_варианты():
    """Переименовали кнопку — синонимы к ней молча перестают работать.

    Молча — самое неприятное слово здесь: бот не падает, он просто
    снова перестаёт понимать живую речь.
    """
    по_ид = {в["id"]: в for в in QUESTIONS}
    беда: list[str] = []
    for ид, словарь in survey_questions.СИНОНИМЫ.items():
        вопрос = по_ид.get(ид)
        if вопрос is None:
            беда.append(f"вопроса {ид} больше нет")
            continue
        for имя in словарь:
            if имя not in (вопрос.get("options") or []):
                беда.append(f"{ид}: варианта «{имя}» больше нет")
    assert беда == [], беда


def test_у_каждого_варианта_есть_живые_слова():
    """Словарь без слов к варианту — забытая половина работы."""
    пустые = [
        f"{ид}/{имя}"
        for ид, словарь in survey_questions.СИНОНИМЫ.items()
        for имя, основы in словарь.items()
        if not основы
    ]
    assert пустые == []


def test_подпись_кнопки_не_спорит_с_синонимом_другого_варианта():
    """Написал ровно то, что на кнопке, — засчитывается эта кнопка.

    Точное совпадение проверяется раньше синонимов, но если синоним
    чужого варианта покрывает целую подпись, порядок легко нарушить
    правкой. Пусть за этим следит проверка.
    """
    по_ид = {в["id"]: в for в in QUESTIONS}
    беда: list[str] = []
    for ид, словарь in survey_questions.СИНОНИМЫ.items():
        варианты = по_ид[ид]["options"]
        for подпись in варианты:
            узнано = Survey._по_синонимам(ид, варианты, подпись)
            if узнано is not None and узнано != подпись:
                беда.append(f"{ид}: «{подпись}» опознана как «{узнано}»")
    assert беда == [], беда
