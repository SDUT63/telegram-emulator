import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))

import перенос                                                 # noqa: E402
import прайс                                                   # noqa: E402

ШАБЛОН = КОРЕНЬ / "шаблоны" / "приложение.html"


# ------------------------------------------------------------- упаковка

def test_ответы_доезжают_целиком():
    ответы = {
        "who": "О близком человеке",
        "patient_name": "Анна Петровна",
        "flags": "Боль; Плохо ест",
        "address": "Тольятти, ул. Ленина, 1",
    }
    assert перенос.из_ссылки(перенос.ссылка(ответы)) == ответы


def test_кириллица_и_знаки_не_ломают_ссылку():
    ответы = {"note": "Мама «лежачая», вес 110+ кг — нужен подъёмник?"}
    assert перенос.из_ссылки(перенос.ссылка(ответы)) == ответы


def test_ответы_едут_после_решётки():
    """Часть адреса после решётки браузер на сервер не отправляет.
    Уедь она параметром — рассказ о здоровье лёг бы в журналы хостинга."""
    адрес = перенос.ссылка({"who": "О себе"})
    основа, решётка, хвост = адрес.partition("#")
    assert решётка, "ответы ушли в открытую часть адреса"
    assert "?" not in основа


def test_пустая_анкета_не_вешает_хвост():
    assert "#" not in перенос.ссылка({})
    assert "#" not in перенос.ссылка({"who": ""})


def test_испорченный_код_не_роняет_приложение():
    """Человек мог скопировать ссылку не до конца. Приложение должно
    открыться пустым, а не белым экраном."""
    for мусор in ["", "не-код", "!!!", "eyJ", "%%%%"]:
        assert перенос.распаковать(мусор) == {}


def test_слишком_длинная_анкета_отдаётся_без_хвоста():
    """Мессенджеры режут длинные адреса молча. Половина анкеты
    хуже, чем её отсутствие: человек не поймёт, чего не хватает."""
    огромная = {f"q{i}": "ответ" * 200 for i in range(40)}
    assert перенос.ссылка(огромная) == перенос.АДРЕС


def test_адрес_настраивается():
    свой = перенос.ссылка({"who": "О себе"}, "https://пример.рф/")
    assert свой.startswith("https://пример.рф/#")


