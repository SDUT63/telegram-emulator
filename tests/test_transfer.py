"""Перенос ответов из бота в мини-приложение и совпадение арифметики.

Две копии одного и того же — главный риск этой пары. Анкета живёт
в боте и на странице; прайс считает Python и он же JavaScript.
Разойдутся — человек ответит дважды или увидит на экране не ту сумму,
которая окажется в договоре.
"""

from __future__ import annotations

