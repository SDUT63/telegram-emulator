СОЧЕТАНИЯ = [
    ("v2", 8, ["weekend", "dementia"]),
    ("v1", 10, ["urgent"]),
    ("night12", 15, ["night", "far"]),
    ("round", 30, ["night", "weight110"]),
    ("live_in", 30, ["night", "stoma"]),
    ("level1", 1, ["weekend", "urgent", "veteran"]),
    ("level2", 3, ["prepay3", "dementia"]),
    ("level3", 1, ["holiday", "palliative", "second_family"]),
    ("shift8", 22, ["weight90", "far", "registry"]),
    ("first_visit", 1, ["urgent"]),
    ("v4", 1, []),
    ("escort", 4, ["holiday", "veteran", "prepay3"]),
]


@pytest.mark.skipif(shutil.which("node") is None, reason="нет node")
def test_страница_считает_так_же_как_прайс(tmp_path):
    """Арифметику приходится держать в двух местах: Python для службы,
    JavaScript для телефона. Здесь настоящий код страницы гоняется
    настоящим движком и сверяется с модулем — иначе расхождение
    всплыло бы у семьи на экране.
    """
    шаблон = ШАБЛОН.read_text(encoding="utf-8")
    кусок = re.search(r"\n  function посчитать\(\)\{.*?\n  \}\n", шаблон, re.S)
    assert кусок, "на странице больше нет функции посчитать"

    цены = json.loads((КОРЕНЬ / "webapp" / "price.json").read_text(encoding="utf-8"))
    обвязка = """
const ПРАЙС = %s;
const СЛУЧАИ = %s;
function всеПозиции(){
  const с = ПРАЙС.услуги.slice();
  ПРАЙС.пакеты.forEach(п => с.push({id: п.id, цена: п.цена,
    часов: п.часов_в_месяц, единица: 'месяц'}));
  return с;
}
let ВЫБОР = {позиция: '', сколько: 1, поправки: []};
function позиция(){ return всеПозиции().find(п => п.id === ВЫБОР.позиция) || null; }
function поправка(ид){ return ПРАЙС.поправки.find(п => п.id === ид) || null; }
%s
const итоги = СЛУЧАИ.map(([поз, n, доб]) => {
  ВЫБОР = {позиция: поз, сколько: n, поправки: доб};
  const р = посчитать();
  return {итог: р.итог, заЕдиницу: р.заЕдиницу, вЧас: р.вЧас,
          учтено: р.учтено.map(п => п.id), пропущено: р.пропущено.map(п => п.id)};
});
console.log(JSON.stringify(итоги));
""" % (json.dumps(цены, ensure_ascii=False),
       json.dumps(СОЧЕТАНИЯ, ensure_ascii=False),
       кусок.group(0))

    файл = tmp_path / "счёт.mjs"
    файл.write_text(обвязка, encoding="utf-8")
    готово = subprocess.run(["node", str(файл)], capture_output=True, text=True)
    assert готово.returncode == 0, готово.stderr
    браузер = json.loads(готово.stdout)

    for (поз, сколько, добавки), из_js in zip(СОЧЕТАНИЯ, браузер):
        из_py = прайс.посчитать(поз, сколько, добавки)
        assert из_js["итог"] == из_py["итог"], (поз, сколько, добавки)
        assert из_js["заЕдиницу"] == из_py["за_единицу"], (поз, добавки)
        assert из_js["вЧас"] == из_py["в_час"], поз
        assert из_js["учтено"] == из_py["учтено"], (поз, добавки)
        assert из_js["пропущено"] == из_py["пропущено"], (поз, добавки)
