# ------------------------------------------ рубеж анкеты словом, не цифрой

@pytest.mark.parametrize("слово", ["Продолжить", "продолжить", "дальше", "1"])
def test_рубеж_проходится_словом_а_не_только_номером(tmp_path, слово):
    """«Продолжить» — это и вариант ответа, и служебное слово «повтори
    вопрос». Пока побеждало второе, написавший его словом получал тот же
    вопрос заново — и так без конца."""
    from chatbot_survey import Survey

    анкета = Survey(storage_path=str(tmp_path / f"s{hash(слово)}.json"))
    анкета.grant_consent("u")
    for шаг in ["О близком человеке", "Дочь или сын", "Да, знает", "Ирина",
                "Анна Петровна", "89170000000", "Утром", "Тольятти, Ленина 1",
                "85 и старше", "Боль", "Помощь на дому"]:
        анкета.handle("u", шаг)
    анкета.handle("u", слово)
    assert анкета.state["u"]["answers"].get("continue") == "Продолжить"


def test_продолжить_на_обычном_вопросе_повторяет_вопрос(tmp_path):
    """Там, где «продолжить» не ответ, оно должно остаться служебным
    словом, а не записаться в имя."""
    from chatbot_survey import Survey

    анкета = Survey(storage_path=str(tmp_path / "s.json"))
    анкета.grant_consent("u")
    for шаг in ["О близком человеке", "Дочь или сын", "Да, знает"]:
        анкета.handle("u", шаг)
    анкета.handle("u", "продолжить")
    assert "name" not in анкета.state["u"]["answers"]


