def test_ровно_две_страницы(страница):
    assert страница.count('<section class="page">') == 2


def test_страницы_размером_с_лист(страница):
    """Схема должна печататься на A4 и не расползаться на третий лист."""
    assert "height:297mm" in страница
    assert "size:A4" in страница
    assert "page-break-after:always" in страница


def test_схема_читается_на_телефоне(страница):
    assert "@media (max-width:820px)" in страница
    assert "width:auto" in страница
