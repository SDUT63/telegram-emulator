"""Схема маршрутизации не должна разойтись с кодом.

Нарисованная схема живёт своей жизнью: правила меняются, картинка
остаётся, и через полгода по ней учат новых сотрудников неправильно.
Поэтому схема собирается из работающих модулей, а тест сверяет
собранный файл с ними же.
"""
import importlib.util
import io
import os
import re

import pytest

import knowledge
import routing_rules
import scale_731
import survey_questions

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
СБОРКА = os.path.join(КОРЕНЬ, "webapp", "схема", "сборка-схемы.py")
СХЕМА = os.path.join(КОРЕНЬ, "webapp", "Схема-маршрутизации.html")


@pytest.fixture(scope="module")
def сборщик():
    описание = importlib.util.spec_from_file_location("сборка_схемы", СБОРКА)
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    return модуль


@pytest.fixture(scope="module")
def страница():
    assert os.path.exists(СХЕМА), (
        "схема не собрана — запустите python webapp/схема/сборка-схемы.py")
    return io.open(СХЕМА, encoding="utf-8").read()


def без_тегов(текст: str) -> str:
    return re.sub(r"<[^>]+>", " ", текст)


# ------------------------------------------------------- собирается из кода

def test_схема_собирается(сборщик):
    данные = сборщик.собрать()
    html = сборщик.собрать_html(данные)
    assert html.startswith("<!doctype html>")
    assert len(html) > 4000


def test_данные_берутся_из_работающих_модулей(сборщик):
    д = сборщик.собрать()
    assert д["вопросов"] == len(survey_questions.QUESTIONS)
    assert д["коротких"] + д["подробных"] == д["вопросов"]
    assert д["стоп"] == list(routing_rules.URGENT_FLAGS)
    assert д["маршруты"] == dict(routing_rules.NAMES)
    assert д["статей"] == len(knowledge.загрузить())
    assert len(д["ветви"]) == len(knowledge.карта())
    assert д["шкала"] == scale_731.покрытие()


def test_схема_на_диске_не_устарела(сборщик, страница):
    """Правила поменялись, а файл не пересобрали — тест это ловит."""
    собранное = сборщик.собрать_html(сборщик.собрать())
    # Дата сборки меняется каждый день, всё остальное — нет
    убрать_дату = lambda т: re.sub(r"схема собрана из работающего кода[^<]*", "", т)
    assert убрать_дату(страница) == убрать_дату(собранное), (
        "схема устарела — запустите python webapp/схема/сборка-схемы.py")


# ------------------------------------------------------- что на ней есть

@pytest.mark.parametrize("код", ["СМП", "М1", "М2", "М3", "М4", "М5"])
def test_каждый_маршрут_на_схеме(страница, код):
    assert f">{код}<" in страница


def test_все_стоп_сигналы_названы(страница):
    текст = без_тегов(страница).lower()
    for признак in routing_rules.URGENT_FLAGS:
        assert признак.lower() in текст, признак


def test_все_ветви_базы_названы(страница):
    текст = без_тегов(страница)
    for ветвь in knowledge.карта():
        assert ветвь["название"] in текст, ветвь["название"]


def test_на_схеме_есть_граница_полномочий(страница):
    """Самое важное на схеме — чего бот не делает."""
    текст = без_тегов(страница).lower()
    for кусок in ("не ставит диагнозов", "не решает", "не устанавливает уровень",
                  "решение принимает координатор"):
        assert кусок in текст, кусок


def test_схема_не_обещает_лишнего(страница):
    текст = без_тегов(страница).lower()
    assert "гарантируем" not in текст
    assert "бот решает" not in текст


