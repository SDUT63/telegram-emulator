"""Перебор пароля к CRM должен становиться бессмысленным.

За дверью CRM — имена, телефоны, адреса и описания состояния тяжело больных
людей. Пароль без ограничения попыток не защищает их: словарный пароль
подбирается по сети за вечер, и следов этого никто не увидит.
"""
from __future__ import annotations

import pytest

from login_guard import (
    БАЗОВАЯ_ЗАДЕРЖКА,
    БЕСПЛАТНЫХ_ПОПЫТОК,
    ПРЕДЕЛ_ЗАДЕРЖКИ,
    ЗащитаВхода,
)


class Часы:
    """Управляемое время: тест не должен ничего ждать по-настоящему."""

    def __init__(self) -> None:
        self.сейчас = 1000.0

    def __call__(self) -> float:
        return self.сейчас

    def через(self, секунд: float) -> None:
        self.сейчас += секунд


@pytest.fixture()
def защита():
    часы = Часы()
    return ЗащитаВхода(часы=часы), часы


def test_честная_ошибка_не_наказывается(защита):
    страж, _ = защита
    for _ in range(БЕСПЛАТНЫХ_ПОПЫТОК):
        assert страж.неудача("anna", "10.0.0.1") == 0.0
    assert страж.задержка("anna", "10.0.0.1") == 0.0


def test_задержка_растёт_экспоненциально(защита):
    страж, _ = защита
    for _ in range(БЕСПЛАТНЫХ_ПОПЫТОК):
        страж.неудача("anna", "10.0.0.1")

    assert страж.неудача("anna", "10.0.0.1") == БАЗОВАЯ_ЗАДЕРЖКА
    assert страж.неудача("anna", "10.0.0.1") == БАЗОВАЯ_ЗАДЕРЖКА * 2
    assert страж.неудача("anna", "10.0.0.1") == БАЗОВАЯ_ЗАДЕРЖКА * 4


def test_задержка_не_растёт_бесконечно(защита):
    страж, _ = защита
    for _ in range(40):
        задержка = страж.неудача("anna", "10.0.0.1")
    assert задержка == ПРЕДЕЛ_ЗАДЕРЖКИ


def test_ожидание_истекает_и_попытка_снова_возможна(защита):
    страж, часы = защита
    for _ in range(БЕСПЛАТНЫХ_ПОПЫТОК + 1):
        страж.неудача("anna", "10.0.0.1")
    assert страж.задержка("anna", "10.0.0.1") > 0

    часы.через(БАЗОВАЯ_ЗАДЕРЖКА + 1)
    assert страж.задержка("anna", "10.0.0.1") == 0.0


def test_верный_пароль_снимает_счётчик(защита):
    страж, _ = защита
    for _ in range(БЕСПЛАТНЫХ_ПОПЫТОК + 2):
        страж.неудача("anna", "10.0.0.1")
    assert страж.задержка("anna", "10.0.0.1") > 0

    страж.успех("anna", "10.0.0.1")
    assert страж.задержка("anna", "10.0.0.1") == 0.0


def test_чужие_попытки_не_запирают_координатора(защита):
    """Иначе любой желающий закрыл бы оператору вход снаружи."""
    страж, _ = защита
    for _ in range(20):
        страж.неудача("anna", "203.0.113.7")

    assert страж.задержка("anna", "203.0.113.7") > 0
    assert страж.задержка("anna", "10.0.0.1") == 0.0, "рабочее место не должно пострадать"


def test_перебор_логинов_с_одного_адреса_тоже_замедляется(защита):
    """Счёт по паре, но каждый логин с того же адреса копит свою задержку."""
    страж, _ = защита
    for логин in ("anna", "boris", "vera"):
        for _ in range(БЕСПЛАТНЫХ_ПОПЫТОК + 1):
            страж.неудача(логин, "203.0.113.7")
        assert страж.задержка(логин, "203.0.113.7") > 0


def test_логин_не_чувствителен_к_регистру(защита):
    страж, _ = защита
    for _ in range(БЕСПЛАТНЫХ_ПОПЫТОК + 1):
        страж.неудача("Anna", "10.0.0.1")
    assert страж.задержка("anna", "10.0.0.1") > 0, "смена регистра не должна обнулять счёт"


def test_старые_записи_забываются(защита):
    страж, часы = защита
    for _ in range(БЕСПЛАТНЫХ_ПОПЫТОК + 1):
        страж.неудача("anna", "10.0.0.1")

    часы.через(3600 * 2)
    assert страж.задержка("anna", "10.0.0.1") == 0.0
    assert страж.забыть_старое() >= 0
