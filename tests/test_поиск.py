ЗАПРОСЫ = [з for з, _ in ОЖИДАНИЯ]


def _выдача(запрос: str, сколько: int = 3) -> list[str]:
    return [с.заголовок for с in knowledge.найти(запрос, сколько)]


@pytest.mark.parametrize("запрос,годные", ОЖИДАНИЯ, ids=[з for з, _ in ОЖИДАНИЯ])
def test_вопрос_приводит_куда_надо(запрос, годные):
    выдача = _выдача(запрос)
    assert выдача, f"«{запрос}» — поиск промолчал"
    assert any(г.lower() in з.lower() for з in выдача for г in годные), (
        f"«{запрос}» не находит {годные}, а находит {выдача}")


def test_ни_один_живой_вопрос_не_остаётся_без_ответа():
    """Промолчать — тоже ответ, но не на вопрос, который люди задают."""
    молчит = [з for з in ЗАПРОСЫ if not _выдача(з, 1)]
    assert not молчит, молчит


def test_выгрузка_несёт_весь_механизм_поиска():
    """Страница считает сама, по этим настройкам. Забудут добавить —
    поиск в приложении тихо станет другим."""
    выгрузка = json.loads(ВЫГРУЗКА.read_text(encoding="utf-8"))
    поиск = выгрузка["поиск"]
    assert поиск["синонимы"] == dict(knowledge.СИНОНИМЫ)
    assert поиск["обороты"] == dict(knowledge.ОБОРОТЫ)
    assert set(поиск["шум"]) == knowledge.ШУМ
    assert поиск["окончания"] == list(knowledge.ОКОНЧАНИЯ)
    assert поиск["порог"] == knowledge.ПОРОГ
    assert поиск["резкость"] == knowledge.РЕЗКОСТЬ
    assert поиск["решающее"] == knowledge.РЕШАЮЩЕЕ
    # Ключ разбивки ничьих: без него при равном весе первая строка
    # в чате и в приложении разная.
    assert all("сорт" in с for с in выгрузка["статьи"])


ОБВЯЗКА = """
const fs = require('fs');
const БАЗА = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const ЗАПРОСЫ = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
let ПОИСК = БАЗА.поиск, РЕДКОСТЬ = null;
%s
разобратьСтатьи();
console.log(JSON.stringify(
  ЗАПРОСЫ.map(q => искать(q, 3).map(с => с.заголовок))));
"""


@pytest.mark.skipif(__import__("shutil").which("node") is None, reason="нет node")
def test_страница_ищет_ровно_как_бот(tmp_path):
    страница = ШАБЛОН_СТРАНИЦЫ.read_text(encoding="utf-8")
    куски = []
    for имя in ("основа", "основы", "расширить", "разобратьСтатьи",
                "весСтатьи", "надбавка", "искать"):
        найдено = re.search(rf"\n  function {имя}\([^)]*\)\{{.*?\n  \}}\n",
                            страница, re.S)
        assert найдено, имя
        куски.append(найдено.group(0))

    скрипт = tmp_path / "поиск.cjs"
    скрипт.write_text(ОБВЯЗКА % "\n".join(куски), encoding="utf-8")
    зфайл = tmp_path / "запросы.json"
    зфайл.write_text(json.dumps(ЗАПРОСЫ, ensure_ascii=False), encoding="utf-8")

    готово = subprocess.run(["node", str(скрипт), str(ВЫГРУЗКА), str(зфайл)],
                            capture_output=True, text=True)
    assert готово.returncode == 0, готово.stderr
    страничные = json.loads(готово.stdout)

    разошлись = [(з, свои, чужие)
                 for з, чужие in zip(ЗАПРОСЫ, страничные)
                 for свои in [_выдача(з)]
                 if свои != чужие]
    assert not разошлись, разошлись[:5]
