"""Таблица соответствия не расходится ни с контрактом, ни с тестами.

Контракт (docs/МОДЕЛЬ-ОБРАЩЕНИЯ.md, раздел 15) — источник истины о том,
какие инварианты есть; сколько их, тест не знает заранее. Таблица
соответствия (docs/МОДЕЛЬ-ОБРАЩЕНИЯ-ШАГ-1.md) — о том, чем каждый
проверен. Здесь сверяется, что они не разошлись:

- номера инвариантов в контракте идут подряд, без пропусков;
- каждый инвариант назван в первом столбце хотя бы одной строки таблицы
  соответствия;
- в его строках либо названы существующие тесты и среди них есть тест
  с номером инварианта в имени, либо стоит явный «TODO»;
- каждый тест, названный в таблице соответствия, существует.

«TODO» — не реализация, а честная отметка «полного теста ещё нет».
Такие инварианты перечисляются в предупреждении при каждом прогоне,
чтобы незавершённость была видна, а не пряталась за зелёным
результатом.
"""
from __future__ import annotations

import ast
import re
import warnings
from dataclasses import dataclass, field
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
КОНТРАКТ = КОРЕНЬ / "docs" / "МОДЕЛЬ-ОБРАЩЕНИЯ.md"
СООТВЕТСТВИЕ = КОРЕНЬ / "docs" / "МОДЕЛЬ-ОБРАЩЕНИЯ-ШАГ-1.md"
ТЕСТЫ = ("test_cases_contract.py", "test_cases_postgres.py",
         "test_max_case_bridge.py", "test_case_operator_crm.py")   # шаг 2

_ИМЯ_ТЕСТА = re.compile(r"`(test_\w+)`")


def _тесты() -> set[str]:
    имена = set()
    for файл in ТЕСТЫ:
        дерево = ast.parse((КОРЕНЬ / "tests" / файл).read_text(encoding="utf-8"))
        имена |= {у.name for у in дерево.body
                  if isinstance(у, ast.FunctionDef) and у.name.startswith("test_")}
    return имена


def инварианты_контракта(контракт: str) -> list[str]:
    """Номера инвариантов из таблицы раздела 15 — в порядке контракта."""
    return re.findall(r"^\| (И\d+) \|", контракт, re.M)


def строки_соответствия(соответствие: str) -> dict[str, list[str]]:
    """Инвариант → последний столбец («тесты») каждой строки таблиц,
    где инвариант назван в первом столбце."""
    итог: dict[str, list[str]] = {}
    for строка in соответствие.splitlines():
        if not строка.startswith("|") or set(строка) <= set("|-: "):
            continue
        ячейки = [ячейка.strip() for ячейка in строка.strip().strip("|").split("|")]
        if len(ячейки) < 2:
            continue
        for инвариант in re.findall(r"И\d+", ячейки[0]):
            итог.setdefault(инвариант, []).append(ячейки[-1])
    return итог


@dataclass
class Сверка:
    без_строки: list[str] = field(default_factory=list)
    без_теста: list[str] = field(default_factory=list)
    несуществующие: list[tuple[str, list[str]]] = field(default_factory=list)
    todo: list[str] = field(default_factory=list)


def сверить(контракт: str, соответствие: str, тесты: set[str]) -> Сверка:
    сверка = Сверка()
    строки = строки_соответствия(соответствие)
    for инвариант in инварианты_контракта(контракт):
        ячейки = строки.get(инвариант)
        if not ячейки:
            сверка.без_строки.append(инвариант)
            continue
        названные = {имя for ячейка in ячейки for имя in _ИМЯ_ТЕСТА.findall(ячейка)}
        if названные - тесты:
            сверка.несуществующие.append((инвариант, sorted(названные - тесты)))
        if any("TODO" in ячейка for ячейка in ячейки):
            сверка.todo.append(инвариант)
            continue
        if not any(имя.startswith(f"test_{инвариант.lower()}_") for имя in названные):
            сверка.без_теста.append(инвариант)
    return сверка


def test_инварианты_контракта_идут_подряд():
    инварианты = инварианты_контракта(КОНТРАКТ.read_text(encoding="utf-8"))
    assert инварианты, "в разделе 15 контракта не нашлось ни одного инварианта"
    assert инварианты == [f"И{n}" for n in range(1, len(инварианты) + 1)]


def test_у_каждого_инварианта_есть_тест_или_явный_todo():
    сверка = сверить(КОНТРАКТ.read_text(encoding="utf-8"),
                     СООТВЕТСТВИЕ.read_text(encoding="utf-8"), _тесты())
    assert сверка.без_строки == [], "инвариант контракта не назван в таблице соответствия"
    assert сверка.несуществующие == [], "таблица соответствия называет тест, которого нет"
    assert сверка.без_теста == [], "нет ни теста с номером инварианта в имени, ни явного TODO"
    if сверка.todo:
        warnings.warn("полного теста ещё нет (TODO в таблице соответствия): "
                      + ", ".join(сверка.todo), stacklevel=1)


def test_тесты_из_таблицы_существуют():
    названные = set(_ИМЯ_ТЕСТА.findall(СООТВЕТСТВИЕ.read_text(encoding="utf-8")))
    assert названные, "в документе соответствия не нашлось ни одного теста"
    assert названные - _тесты() == set()


# --- Сама сверка ловит то, что должна, — на документах-образцах ----------------

_КОНТРАКТ_ОБРАЗЕЦ = """
| № | Инвариант |
|---|---|
| И1 | первый |
| И2 | второй |
| И3 | третий |
"""


def test_сверка_ловит_инвариант_без_теста_и_без_todo():
    соответствие = """
| № | Где | Тесты |
|---|---|---|
| И1 | там | `test_и1_есть` |
| И2 | там | `test_про_другое` |
| И3 — новое правило | там | TODO: тест после реализации |
"""
    сверка = сверить(_КОНТРАКТ_ОБРАЗЕЦ, соответствие, {"test_и1_есть", "test_про_другое"})
    assert сверка.без_теста == ["И2"]          # тест есть, но не про И2 — не считается
    assert сверка.todo == ["И3"]               # TODO — разрешение, а не реализация
    assert сверка.без_строки == [] and сверка.несуществующие == []


def test_сверка_ловит_пропущенный_инвариант_и_выдуманный_тест():
    соответствие = """
| № | Где | Тесты |
|---|---|---|
| И1 | там | `test_и1_есть` |
| И3 | там | `test_и3_выдуманный`; TODO: дополнить |
"""
    сверка = сверить(_КОНТРАКТ_ОБРАЗЕЦ, соответствие, {"test_и1_есть"})
    assert сверка.без_строки == ["И2"]
    assert сверка.несуществующие == [("И3", ["test_и3_выдуманный"])]   # TODO не прикрывает несуществующий тест
