"""Ответ, данный после ошибки, должен попасть в карточку.

Найдено проходом по анкете на боевом стеке, а не чтением кода: человек
ошибся один раз, потом ответил верно — и верный ответ исчез. Бот при
этом показывал следующий вопрос, так что со стороны всё выглядело
правильно. Следующий ответ ложился в карточку на место предыдущего.

Причина: `save()` внутри транзакции подменял объект состояния новым,
а `_accept` держал ссылку на прежний и дописывал в него. Сохранение
случалось посреди `_accept` — его делает `understood()`, сбрасывая
счётчик непонимания. То есть ломалось ровно там, где человек ошибся.

Проверяется на PostgreSQL: на файловом хранилище этой беды нет, а люди
приходят в тот бот, который работает на PostgreSQL.
"""
from __future__ import annotations

import os
import uuid

import pytest

from storage_postgres import _TX_EVENT

pytestmark = pytest.mark.skipif(
    not os.getenv("SDUT_DATABASE_URL"),
    reason="SDUT_DATABASE_URL is required for PostgreSQL integration tests",
)


@pytest.fixture()
def анкета():
    from production_outbox import DurableProductionPostgresSurvey

    return DurableProductionPostgresSurvey()


def _событие(анкета, user_id: str, text: str) -> str:
    """Одно сообщение — одна транзакция, как в жизни."""
    токен = _TX_EVENT.set(f"e-{uuid.uuid4().hex}")
    try:
        return анкета.handle(user_id, text)
    finally:
        _TX_EVENT.reset(токен)


def _состояние(анкета, user_id: str) -> dict:
    import psycopg

    with psycopg.connect(os.environ["SDUT_DATABASE_URL"]) as conn:
        строка = conn.execute(
            "SELECT state_json FROM survey_state WHERE user_id=%s", (user_id,)
        ).fetchone()
    return (строка[0] if строка else {}) or {}


def test_ответ_после_ошибки_не_теряется(анкета):
    u = f"lost-{uuid.uuid4().hex}"
    _событие(анкета, u, "здравствуйте")
    анкета.grant_consent(u)

    _событие(анкета, u, "ыыы")          # промах: счётчик непонимания взведён
    _событие(анкета, u, "2")            # верный ответ сразу после промаха

    состояние = _состояние(анкета, u)
    assert состояние.get("answers", {}).get("who") == "О близком человеке", (
        "верный ответ после ошибки не записан в карточку"
    )
    assert состояние.get("step") == 1, "анкета осталась на прежнем вопросе"


def test_показанный_вопрос_совпадает_с_записанным_шагом(анкета):
    """Хуже потери — расхождение: человек отвечает на один вопрос,
    а ответ ложится в другой."""
    u = f"lost-{uuid.uuid4().hex}"
    _событие(анкета, u, "здравствуйте")
    анкета.grant_consent(u)
    _событие(анкета, u, "ыыы")

    ответ = _событие(анкета, u, "2")
    шаг = _состояние(анкета, u).get("step")

    from survey_questions import QUESTIONS

    показанный = QUESTIONS[шаг]["text"].split("\n")[0]
    assert показанный in ответ, (
        "бот показал один вопрос, а ждёт ответа на другой"
    )


def test_состояние_остаётся_тем_же_объектом_внутри_события(анкета):
    """Корень беды, отдельно от анкеты.

    В начале события состояние читается из базы заново — так и должно
    быть, иначе бот работал бы по своей памяти вместо общей истины.
    Но пока событие идёт, объект обязан оставаться тем же: анкета
    держит на него ссылку и дописывает в неё по шагам.
    """
    u = f"ident-{uuid.uuid4().hex}"
    _событие(анкета, u, "здравствуйте")

    подмены: list[str] = []
    токен = _TX_EVENT.set(f"e-{uuid.uuid4().hex}")
    try:
        with анкета._atomic(u, "message", {"kind": "message"}) as принято:
            assert принято
            было = анкета.state.get(u)
            ответы_было = было.get("answers")

            анкета.save()          # сохранение посреди события

            if анкета.state.get(u) is not было:
                подмены.append("сам словарь состояния")
            if анкета.state[u].get("answers") is not ответы_было:
                подмены.append("вложенный answers")
    finally:
        _TX_EVENT.reset(токен)

    assert подмены == [], f"сохранение подменило: {подмены}"


def test_несколько_ошибок_подряд_не_сбивают_запись(анкета):
    """Лесенка непонимания длинная, и на каждой ступени идёт сохранение."""
    u = f"lost-{uuid.uuid4().hex}"
    _событие(анкета, u, "здравствуйте")
    анкета.grant_consent(u)

    for _ in range(4):
        _событие(анкета, u, "ыыы")
    _событие(анкета, u, "3")

    состояние = _состояние(анкета, u)
    assert состояние.get("answers", {}).get("who") == "Я специалист"
    # Дальше идёт не второй вопрос, а третий: «кем вы приходитесь»
    # специалисту не задают — он никем не приходится, он по работе.
    assert состояние.get("step") > 0, "анкета осталась на прежнем вопросе"
