# ------------------------------------------------------------- вариатор
#
# Половина людей не знает, что спрашивать. Проверяем не «умность»
# подсказок, а то, что они всегда есть, всегда ведут к существующей
# статье и помещаются на кнопку.

def test_подсказки_есть_всегда(база):
    """Даже на пустой вопрос человеку должно быть что нажать."""
    for вопрос in ("", "мама лежит", "не знаю", "аывафыва", "спасибо"):
        assert knowledge.подсказки(вопрос), f"нет подсказок: {вопрос!r}"


def test_каждая_подсказка_ведёт_к_статье(база):
    for вопрос in ("", "болит", "устала", "как получить коляску", "деменция"):
        for з in knowledge.подсказки(вопрос):
            assert knowledge.по_заголовку(з), f"подсказка в никуда: {з}"


def test_подсказка_не_повторяет_показанное(база):
    показано = "Пролежни: где искать и что делать при покраснении"
    подсказки = knowledge.подсказки("у мамы пролежень", кроме=показано)
    assert показано not in подсказки


def test_подсказки_не_повторяются(база):
    подсказки = knowledge.подсказки("мама лежит и не встаёт", сколько=4)
    assert len(подсказки) == len(set(подсказки))


@pytest.mark.parametrize("вопрос, ждём", [
    ("мама лежит", "лежач"),
    ("устала", "справля"),
    ("болит", "боль"),
    ("памперсы", "недержан"),
    ("папа путается", "путат"),
    ("нужна коляска", "средства"),
])
def test_короткий_вопрос_получает_свою_тему(база, вопрос, ждём):
    """«Мама лежит» — не вопрос, а состояние. Подсказки должны это понять."""
    всё = " ".join(knowledge.подсказки(вопрос)).lower()
    assert ждём in всё, f"{вопрос}: {всё}"


def test_меню_для_того_кто_не_знает_с_чего_начать(база):
    вступление, вопросы = knowledge.начать()
    assert "напишите своими словами" in вступление
    assert len(вопросы) >= 4
    assert all(knowledge.по_заголовку(в) for в in вопросы)
    # Первое, что видит растерянный человек, — что делать при угрозе жизни
    assert "плохо прямо сейчас" in вопросы[0]


def test_подписи_кнопок_помещаются_на_экран(база):
    """MAX режет длинную подпись многоточием — режем сами и по слову."""
    import max_bot
    длинные = []
    for с in база:
        п = knowledge.подпись(с.заголовок)
        if max_bot._width(п) > 34:
            длинные.append((п, round(max_bot._width(п), 1)))
    assert not длинные, f"не поместится на кнопке: {длинные[:3]}"


def test_подпись_не_теряет_смысла(база):
    """Однословная подпись у вопроса — это загадка, а не подсказка."""
    короткие = [knowledge.подпись(с.заголовок) for с in база
                if len(с.заголовок.split()) > 3]
    беда = [п for п in короткие if len(п.split()) < 2]
    assert not беда, f"подпись из одного слова: {беда[:3]}"


