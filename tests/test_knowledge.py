"""База знаний: то, из чего бот отвечает на вопросы.

Проверяем не «умность» поиска, а свойства, на которые опирается всё
остальное: база непуста, нормативные статьи на месте, поиск находит
очевидное и молчит на пустом вопросе. Молчание здесь так же важно, как
попадание: выдать статью не по делу хуже, чем сказать «спросите
координатора».
"""
import pytest

import knowledge


@pytest.fixture(scope="module")
def база():
    return knowledge.загрузить(перечитать=True)


# --------------------------------------------------------------- состав

def test_база_не_пустая(база):
    assert len(база) > 50, "справочник разобрался не полностью"


def test_есть_нормативные_статьи(база):
    разделы = {с.раздел for с in база}
    assert "Оценка нуждаемости по Приказу № 731" in разделы
    assert "Паллиативная помощь" in разделы
    assert "Маршруты службы" in разделы


def test_справочник_попал_в_базу(база):
    """Всё, что опубликовано в «Навигаторе», бот берёт оттуда, а не из копии."""
    из_справочника = [с for с in база if "Навигатор" in с.источник]
    assert len(из_справочника) > 40


def test_у_нормативных_статей_указан_источник(база):
    без_источника = [с.заголовок for с in база
                     if с.раздел.startswith(("Оценка нуждаемости по", "Паллиативная помощь"))
                     and not с.источник]
    assert not без_источника, f"статья без ссылки на документ: {без_источника}"


def test_статьи_не_обрезаны(база):
    короткие = [с.заголовок for с in база if len(с.текст) < 40]
    assert not короткие, f"пустые статьи: {короткие}"


def test_в_базе_нет_разметки(база):
    """Разбор HTML не должен протаскивать теги в ответ человеку."""
    с_тегами = [с.заголовок for с in база if "<" in с.текст and ">" in с.текст]
    assert not с_тегами, с_тегами


def test_один_текст_не_попадает_дважды(база):
    """Раскрывающийся вопрос лежит внутри карточки — легко посчитать дважды."""
    тексты = [с.текст[:120] for с in база]
    повторы = {т for т in тексты if тексты.count(т) > 1}
    assert not повторы, f"дубли в базе: {list(повторы)[:2]}"


# ---------------------------------------------------------------- поиск

@pytest.mark.parametrize("вопрос, ждём", [
    ("какие бывают уровни и сколько часов помощи", "уровн"),
    ("как оформить паллиативный статус", "паллиатив"),
    ("у мамы пролежень, что делать", "пролежн"),
    ("мама поперхивается когда ест", "пищ"),
    ("я очень устала и не справляюсь", "выгор"),
])
def test_поиск_находит_очевидное(база, вопрос, ждём):
    найдено = knowledge.найти(вопрос, сколько=3)
    assert найдено, f"ничего не нашлось: {вопрос}"
    всё = " ".join((с.заголовок + " " + с.текст).lower() for с in найдено)
    assert ждём in всё, f"{вопрос}: не нашлось «{ждём}»"


@pytest.mark.parametrize("пустое", ["", "   ", "привет", "ок", "ага"])
def test_на_пустой_вопрос_база_молчит(база, пустое):
    assert knowledge.найти(пустое) == []


def test_редкое_слово_весит_больше_частого(база):
    """«Пролежень» указывает на ответ точнее, чем «обращаться»."""
    первый = knowledge.найти("пролежень", сколько=1)
    assert первый and "пролежн" in первый[0].текст.lower()


def test_синонимы_переводят_с_человеческого(база):
    """Люди пишут «памперсы», в материалах написано «абсорбирующее бельё»."""
    найдено = knowledge.найти("как часто менять памперсы", сколько=2)
    всё = " ".join(с.заголовок.lower() for с in найдено)
    assert "абсорбир" in всё or "бель" in всё


# -------------------------------------------------------------- выдержка

def test_выдержка_не_длиннее_предела(база):
    статьи = knowledge.найти("уровни нуждаемости и часы помощи", сколько=3)
    текст = knowledge.выдержка(статьи, предел=500)
    assert len(текст) <= 500 + 200        # последний кусок не режем посередине


def test_выдержка_несёт_источник(база):
    статьи = knowledge.найти("паллиативный статус кто решает", сколько=1)
    assert "источник:" in knowledge.выдержка(статьи)


# ------------------------------------------------------- ответ без модели

def test_бот_отвечает_и_без_модели(база):
    """Модель — надстройка. База должна отвечать сама."""
    ответ = knowledge.ответ_без_модели("какие бывают уровни нуждаемости в уходе")
    assert ответ and "уровн" in ответ.lower()
    assert "координатор" in ответ, "человеку нужен путь к живому человеку"


def test_без_модели_на_невнятное_молчим(база):
    assert knowledge.ответ_без_модели("ну как там") is None


def test_ответ_не_длиннее_экрана(база):
    ответ = knowledge.ответ_без_модели("что такое долговременный уход")
    assert ответ is None or len(ответ) < 1200


# ---------------------------------------------------------------- шкала 731

def test_шкала_приказа_на_месте():
    import scale_731 as шкала
    assert len(шкала.SCALE) == 21
    assert шкала.MAX_SCORE == 55.0


def test_неполная_шкала_не_даёт_уровня():
    """Частичный подсчёт занизил бы уровень, а уровень — это часы помощи."""
    import scale_731 as шкала
    итог = шкала.score({"cook": шкала.CANNOT})
    assert итог.complete is False
    assert итог.level is None and итог.total == 0.0


def test_полная_шкала_даёт_уровень_и_часы():
    import scale_731 as шкала
    итог = шкала.score({i.id: шкала.CANNOT for i in шкала.SCALE})
    assert итог.total == 55.0
    assert итог.level == 3 and итог.package_hours == (25, 28)
    assert "предварительно" in итог.note.lower()


def test_действующая_анкета_шкалу_не_закрывает():
    """Известный разрыв. Тест сторожит, чтобы о нём не забыли молча."""
    import scale_731 as шкала
    п = шкала.покрытие()
    assert п["закрыто"] < п["всего"], "если закрылась — обновите документацию"
    assert п["максимум_по_анкете"] < 35.5, (
        "III уровень по действующей анкете недостижим — так и должно быть, "
        "пока анкета не расширена")


def test_ответы_анкеты_ложатся_на_шкалу(consented):
    import scale_731 as шкала
    import walk
    walk.пройти(consented, ветка=1, ответы={"mobility": [5]})
    заполнено = шкала.из_анкеты(consented.state["u1"]["answers"])
    assert заполнено, "ни одна позиция не сопоставилась"
    assert заполнено.get("walk_home") == шкала.CANNOT
