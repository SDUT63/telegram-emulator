"""Проход по анкете в тестах.

Вопросов больше тридцати, и порядок их будет меняться и дальше. Тесты, где
ответы записаны списком номеров, ломались от каждого нового вопроса — хотя
проверяли совсем другое. Поэтому ходим по анкете так же, как ходит человек:
смотрим, что спрашивают, и отвечаем.
"""
ЗАГЛУШКИ = {"phone": "89171234567", "address": "Ворошилова 19, кв. 5"}

# Мимоходом на «тревожные признаки» отвечаем «ничего нет»: иначе каждый проход
# мимо этого вопроса поднимал бы тревогу, к тесту отношения не имеющую.
СПОКОЙНО = {"flags": "Ничего из этого нет"}

ПРЕДЕЛ = 60      # вопросов вдвое меньше; это защита от зацикливания


def ответить(s, u, q, ответы=None):
    """Ответить на вопрос: как велено в `ответы` или самым безобидным образом."""
    свой = (ответы or {}).get(q["id"])
    if свой is not None:
        return s.answer_by_numbers(u, свой) if isinstance(свой, list) else s.handle(u, свой)
    if q["kind"] == "choice":
        спокойный = СПОКОЙНО.get(q["id"])
        номер = q["options"].index(спокойный) + 1 if спокойный else 1
        return s.answer_by_numbers(u, [номер])
    return s.handle(u, ЗАГЛУШКИ.get(q["kind"], "Ответ текстом"))


def _ответы(ветка, ответы):
    свои = dict(ответы or {})
    свои.setdefault("who", [ветка])
    return свои


def дойти_до(s, ключ, u="u1", ветка=2, ответы=None):
    """Отвечать по порядку, пока не спросят `ключ`. Вернуть (шаг, вопрос).

    На сам `ключ` ответа не даётся — что на него ответить, решает тест.
    `ветка` — номер варианта в первом вопросе: 1 о себе, 2 о близком,
    3 специалист. Отдельные ответы можно задать по id вопроса.
    """
    свои = _ответы(ветка, ответы)
    for _ in range(ПРЕДЕЛ):
        текущий = s.current(u)
        if текущий is None:
            raise AssertionError(f"анкета кончилась, а «{ключ}» так и не спросили")
        step, q = текущий
        if q["id"] == ключ:
            return step, q
        ответить(s, u, q, свои)
    raise AssertionError(f"«{ключ}» не встретился за {ПРЕДЕЛ} вопросов")


def пройти(s, u="u1", ветка=2, ответы=None):
    """Пройти анкету до конца и вернуть id заданных вопросов по порядку."""
    свои = _ответы(ветка, ответы)
    заданные = []
    for _ in range(ПРЕДЕЛ):
        текущий = s.current(u)
        if текущий is None:
            return заданные
        step, q = текущий
        заданные.append(q["id"])
        ответить(s, u, q, свои)
    raise AssertionError(f"анкета не кончилась за {ПРЕДЕЛ} вопросов")
