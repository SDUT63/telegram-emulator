@pytest.mark.skipif(__import__("shutil").which("node") is None, reason="нет node")
def test_страница_подбирает_тот_же_шаблон(tmp_path):
    """Подбор живёт в двух местах: Python для службы, JavaScript
    для телефона. Разойдутся — человек увидит не свой план."""
    шаблон = ШАБЛОН_СТРАНИЦЫ.read_text(encoding="utf-8")
    куски = []
    for имя in ("подобратьШаблон", "уточнения", "частиСуток"):
        найдено = re.search(rf"\n  function {имя}\([^)]*\)\{{.*?\n  \}}\n",
                            шаблон, re.S)
        assert найдено, имя
        куски.append(найдено.group(0))

    план = json.loads((КОРЕНЬ / "webapp" / "care.json").read_text(encoding="utf-8"))
    обвязка = """
const ПЛАН = %s;
const СЛУЧАИ = %s;
let ОТВЕТЫ_ПЛАНА = {};
%s
const итоги = СЛУЧАИ.map(о => {
  ОТВЕТЫ_ПЛАНА = о;
  const ш = подобратьШаблон();
  return {
    шаблон: ш ? ш.id : null,
    части: ш ? частиСуток(ш).map(б => б.время) : [],
    уточнения: уточнения().map(д => д.заголовок)
  };
});
console.log(JSON.stringify(итоги));
""" % (json.dumps(план, ensure_ascii=False),
       json.dumps(СЛУЧАИ, ensure_ascii=False),
       "\n".join(куски))

    файл = tmp_path / "план.mjs"
    файл.write_text(обвязка, encoding="utf-8")
    готово = subprocess.run(["node", str(файл)], capture_output=True, text=True)
    assert готово.returncode == 0, готово.stderr
    браузер = json.loads(готово.stdout)

    for ответы, из_js in zip(СЛУЧАИ, браузер):
        шаблон_py = уход.подобрать(ответы)
        assert из_js["шаблон"] == (шаблон_py.id if шаблон_py else None), ответы
        assert из_js["уточнения"] == [д["заголовок"] for д in уход.добавки(ответы)]
        if шаблон_py:
            свои = [б.время for б in уход.блоки_по_ответам(шаблон_py, ответы)]
            assert из_js["части"] == свои, ответы


