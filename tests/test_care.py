def _слова(текст: str) -> set[str]:
    служебные = {"человек", "это", "как", "что", "нужна", "нужно", "если",
                 "или", "для", "при", "его", "вам", "уже", "есть", "быть",
                 "сколько", "какое", "кто", "где", "чем", "того", "кому"}
    найдено = re.findall(r"[а-яё]{4,}", текст.lower())
    return {с[:5] for с in найдено if с not in служебные}


# ------------------------------------------------- не пересекается с ботом

def test_опросник_не_повторяет_анкету_бота():
    """Ни одного общего идентификатора: иначе человек отвечает дважды."""
    from survey_questions import QUESTIONS

    бот = {в["id"] for в in QUESTIONS}
    приложение = {в.id for в in уход.ВОПРОСЫ}
    assert бот & приложение == set(), бот & приложение


def test_вопросы_приложения_спрашивают_о_другом():
    """Разные не только идентификаторы, но и смысл. Проверяем по
    пересечению значимых слов: «Как человек передвигается?» и
    «Где человек проводит день?» — разные вопросы, а вот дубль
    поймается."""
    from survey_questions import QUESTIONS

    вопросы_бота = [(в["id"], _слова(в["text"].splitlines()[0]))
                    for в in QUESTIONS]
    for свой in уход.ВОПРОСЫ:
        мои = _слова(свой.текст)
        for ид, чужие in вопросы_бота:
            общие = мои & чужие
            assert len(общие) < 2, (
                f"«{свой.текст}» слишком похож на вопрос бота {ид}: {общие}")


def test_приложение_не_спрашивает_персональные_данные():
    """Имя, телефон, адрес собирает бот — с согласием по ФЗ-152.
    В приложении их спрашивать нельзя: согласия там никто не давал."""
    запрещено = ("имя", "зовут", "телефон", "адрес", "номер", "фамилия")
    for в in уход.ВОПРОСЫ:
        низом = в.текст.lower()
        for слово in запрещено:
            assert слово not in низом, (в.id, слово)


