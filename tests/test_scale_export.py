def test_инструкция_для_обратившихся_не_отстала_от_бота():
    """Инструкция для поста нарисована руками, и однажды она уже описывала
    бота, которого нет: район отдельной кнопкой, «вопрос 9 из 14», без
    кнопки «Открыть приложение». Человек открывал бота и видел другое.
    Проверяем то, что человек сверит глазами первым делом."""
    import re
    from survey_questions import APP_OPTION, QUESTIONS
    текст = (КОРЕНЬ / "webapp" / "Инструкция-чат-бот-СДУТ.html").read_text(encoding="utf-8")
    вопросы = {в["id"]: в for в in QUESTIONS}
    assert вопросы["who"]["text"] in текст
    assert APP_OPTION in текст, "нет кнопки перехода в приложение"
    for вариант in вопросы["flags"]["options"][:2]:
        assert вариант in текст, вариант
    # до контрольной точки — двенадцать вопросов, больше «из» быть не может
    первые = [в["id"] for в in QUESTIONS].index("continue") + 1
    for всего in map(int, re.findall(r"вопрос \d+ из (\d+)", текст)):
        assert всего <= первые, f"«из {всего}» — в первом блоке {первые} вопросов"
