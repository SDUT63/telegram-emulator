"""Мини-приложение считает уровень само — и должно совпадать с ботом.

Страница на Cloudflare статическая: Python там не исполняется, шкалу
она считает своим кодом. Значит нормативные веса существуют в двух
местах, и разойтись они могут молча: человек увидит на странице один
уровень, а служба посчитает другой. По этим числам людям назначают
часы помощи.

Отсюда правило: единственный источник — scale_731.py, выгрузка делается
скриптом, а эта проверка сверяет их позиция за позицией.
"""
from __future__ import annotations

import json
import pathlib
import subprocess
import sys

import pytest

import scale_731 as шкала

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ВЫГРУЗКА = КОРЕНЬ / "webapp" / "шкала.json"


@pytest.fixture(scope="module")
def данные() -> dict:
    if not ВЫГРУЗКА.exists():
        pytest.fail("нет webapp/шкала.json — запустите scripts/собрать_шкалу.py")
    return json.loads(ВЫГРУЗКА.read_text(encoding="utf-8"))


def test_позиций_столько_же(данные):
    assert len(данные["позиции"]) == len(шкала.SCALE)


def test_веса_совпадают_позиция_за_позицией(данные):
    """Разъехавшийся вес — это чужой уровень и чужие часы помощи."""
    по_id = {п["id"]: п for п in данные["позиции"]}
    расхождения = []
    for и in шкала.SCALE:
        выгружено = по_id.get(и.id)
        if выгружено is None:
            расхождения.append(f"{и.id}: нет в выгрузке")
            continue
        if выгружено["частично"] != и.mid or выгружено["не_может"] != и.full:
            расхождения.append(
                f"{и.id}: {выгружено['частично']}/{выгружено['не_может']} "
                f"вместо {и.mid}/{и.full}"
            )
    assert расхождения == [], расхождения


def test_максимум_совпадает(данные):
    assert данные["максимум"] == sum(и.full for и in шкала.SCALE)


def test_уровни_и_часы_совпадают(данные):
    ожидание = [
        {"от": низ, "номер": номер, "часов_в_неделю": list(шкала.PACKAGE_HOURS.get(номер, (0, 0)))}
        for низ, _, номер, _ in шкала.LEVELS
    ]
    вышло = [
        {"от": у["от"], "номер": у["номер"], "часов_в_неделю": у["часов_в_неделю"]}
        for у in данные["уровни"]
    ]
    assert вышло == ожидание


def test_оговорка_о_предварительности_не_потерялась(данные):
    """Уровень устанавливают два эксперта очно. Страница, которая
    об этом умалчивает, обещает то, чего не может дать."""
    assert данные["оговорка"] == шкала.PRELIMINARY
    assert "эксперта" in данные["оговорка"]


def test_выгрузка_совпадает_с_текущим_кодом():
    """Правка шкалы без пересборки выгрузки — расхождение, которое
    никто не заметит до разговора с человеком."""
    готово = subprocess.run(
        [sys.executable, str(КОРЕНЬ / "scripts" / "собрать_шкалу.py")],
        capture_output=True, text=True, cwd=КОРЕНЬ,
    )
    assert готово.returncode == 0, готово.stderr
    проверка = subprocess.run(["git", "diff", "--stat", "--", "webapp/шкала.json"],
                              capture_output=True, text=True, cwd=КОРЕНЬ)
    assert проверка.stdout.strip() == "", (
        "webapp/шкала.json отстал от scale_731.py — "
        "запустите scripts/собрать_шкалу.py и закоммитьте"
    )


def test_каждая_позиция_спрашивает_человеческим_языком(данные):
    """Формулировка приказа нужна координатору, а на экране — та,
    которую поймёт родственник."""
    плохие = [
        п["id"] for п in данные["позиции"]
        if not п["вопрос"].strip() or not п["вопрос"].strip().endswith("?")
    ]
    assert плохие == [], плохие
