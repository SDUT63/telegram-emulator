def test_позиций_столько_же(данные):
    assert len(данные["позиции"]) == len(шкала.SCALE)


def test_веса_совпадают_позиция_за_позицией(данные):
    """Разъехавшийся вес — это чужой уровень и чужие часы помощи."""
    по_id = {п["id"]: п for п in данные["позиции"]}
    расхождения = []
    for и in шкала.SCALE:
        выгружено = по_id.get(и.id)
        if выгружено is None:
            расхождения.append(f"{и.id}: нет в выгрузке")
            continue
        if выгружено["частично"] != и.mid or выгружено["не_может"] != и.full:
            расхождения.append(
                f"{и.id}: {выгружено['частично']}/{выгружено['не_может']} "
                f"вместо {и.mid}/{и.full}"
            )
    assert расхождения == [], расхождения


def test_максимум_совпадает(данные):
    assert данные["максимум"] == sum(и.full for и in шкала.SCALE)


def test_уровни_и_часы_совпадают(данные):
    ожидание = [
        {"от": низ, "номер": номер, "часов_в_неделю": list(шкала.PACKAGE_HOURS.get(номер, (0, 0)))}
        for низ, _, номер, _ in шкала.LEVELS
    ]
    вышло = [
        {"от": у["от"], "номер": у["номер"], "часов_в_неделю": у["часов_в_неделю"]}
        for у in данные["уровни"]
    ]
    assert вышло == ожидание


