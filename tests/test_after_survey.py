"""Разговор после заполненной анкеты.

Найдено живым прохождением. Человек прошёл анкету целиком и обнаружил:
кнопка предлагает «продолжить подробную анкету», хотя продолжать нечего;
меню тем вызвать нечем; а на вопрос в чат бот не отвечает вовсе.

Последнее было самым тяжёлым: `handle` возвращал пустую строку, пилот
пустую строку не отправляет — и человек писал «пролежни» в тишину.
"""
from __future__ import annotations

import pytest

import walk
from chatbot_survey import ANSWERED, Survey
from survey_questions import CHECKPOINT_ID, STOP_OPTION


@pytest.fixture()
def прошёл_целиком(tmp_path):
    s = Survey(storage_path=str(tmp_path / "целиком.json"), list_options=False)
    s.handle("u", "здравствуйте")
    s.grant_consent("u")
    walk.пройти(s, u="u")
    assert (s.state["u"]).get("finished")
    return s


@pytest.fixture()
def остановился_сам(tmp_path):
    s = Survey(storage_path=str(tmp_path / "рубеж.json"), list_options=False)
    s.handle("u", "здравствуйте")
    s.grant_consent("u")
    walk.дойти_до(s, CHECKPOINT_ID, u="u")
    s.handle("u", STOP_OPTION)
    assert (s.state["u"]).get("finished")
    return s


# ------------------------------------------------- бот не должен молчать

ВОПРОСЫ = ["пролежни", "как оформить инвалидность", "что делать при пролежнях",
           "нужна сиделка", "сколько стоит"]


@pytest.mark.parametrize("вопрос", ВОПРОСЫ)
def test_на_вопрос_после_анкеты_есть_ответ(прошёл_целиком, вопрос):
    ответ = прошёл_целиком.handle("u", вопрос)

    assert ответ, f"бот промолчал на {вопрос!r}"


def test_первый_же_вопрос_получает_ответ_по_существу(прошёл_целиком):
    """Раньше первый вопрос съедало подтверждение «записал, передам»,
    и человек задавал его впустую."""
    ответ = прошёл_целиком.handle("u", "пролежни")

    assert "Пролежни" in ответ, "вместо статьи пришло что-то другое"
    assert ANSWERED in ответ, "обещание передать координатору пропало"


def test_подтверждение_не_повторяется_но_ответы_продолжаются(прошёл_целиком):
    s = прошёл_целиком
    s.handle("u", "пролежни")

    второй = s.handle("u", "как оформить инвалидность")
    assert ANSWERED not in второй, "подтверждение повторилось"
    assert "инвалидност" in второй.lower(), "второй вопрос остался без ответа"


def test_зов_человека_не_подменяется_статьёй(прошёл_целиком):
    """«Перезвоните» — просьба о связи, а не вопрос.

    Статья из материалов службы здесь была бы отпиской вместо
    обещанного звонка.
    """
    ответ = прошёл_целиком.handle("u", "перезвоните пожалуйста")

    assert ответ == ANSWERED


def test_непонятный_вопрос_не_остаётся_без_ответа(прошёл_целиком):
    ответ = прошёл_целиком.handle("u", "абырвалг шмумба")

    assert ответ, "на непонятное бот обязан отвечать лесенкой, а не молчать"


def test_вопрос_попадает_в_переписку_координатору(прошёл_целиком):
    прошёл_целиком.handle("u", "а когда позвонят")

    переписка = " ".join(m["text"] for m in прошёл_целиком.messages("u"))
    assert "когда позвонят" in переписка


# ----------------------------------------------------- кнопки не должны врать

def _подписи(s, u="u"):
    from max_ui import questionnaire_keyboard

    return [кнопка[0] for ряд in questionnaire_keyboard(s, u) for кнопка in ряд]


def test_пройденная_целиком_анкета_не_предлагает_продолжение(прошёл_целиком):
    подписи = _подписи(прошёл_целиком)

    assert not any("Продолжить" in п for п in подписи), подписи
    assert any("Заново" in п or "заново" in п for п in подписи), подписи


def test_остановившемуся_на_рубеже_продолжение_предлагается(остановился_сам):
    """Он выбрал «Достаточно, свяжитесь» — подробная часть впереди."""
    подписи = _подписи(остановился_сам)

    assert any("Продолжить подробную" in п for п in подписи), подписи


def test_после_анкеты_есть_кнопка_тем(прошёл_целиком):
    """Иначе человек должен угадать слово «спросить», а он его
    ниоткуда не знает — и остаётся один на один с ботом."""
    from max_ui import questionnaire_keyboard

    действия = [к[1] for ряд in questionnaire_keyboard(прошёл_целиком, "u") for к in ряд]
    assert "map" in действия, действия


def test_признак_продолжения_различает_два_случая(прошёл_целиком, остановился_сам):
    assert прошёл_целиком.есть_что_продолжить("u") is False
    assert остановился_сам.есть_что_продолжить("u") is True


def test_продолжение_не_спрашивает_имя_и_телефон_заново(остановился_сам):
    s = остановился_сам
    было = dict(s.state["u"]["answers"])

    s.continue_detailed("u")

    стало = s.state["u"]["answers"]
    assert стало.get("name") == было.get("name")
    assert стало.get("phone") == было.get("phone")
    assert s.current("u") is not None, "анкета не продолжилась"


def test_подписи_кнопок_работают_и_словами():
    """Человек читает кнопку и печатает её текст — особенно если
    нажатие не сработало с первого раза. Подпись, которую бот
    не понимает набранной, выглядит как сломанная кнопка."""
    from max_ui import ASK_WORDS

    не_понято = [
        подпись for подпись in ("Спросить о другом", "Просто почитать", "Все темы")
        if подпись.casefold().strip(" ?!.") not in ASK_WORDS
    ]
    assert не_понято == [], не_понято
