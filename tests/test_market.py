"""Рынок ухода: наблюдения, оценки и где на нём наша цена.

Прайс больше не назначается руками — он выводится из уровня своего
города. Значит, ошибка в этом модуле тихо уезжает во все цены сразу,
и проверять его надо строже, чем обычные данные.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))

import прайс                                                    # noqa: E402
import рынок                                                    # noqa: E402


def test_модель_сходится_с_наблюдением():
    """Главная проверка. По Тольятти есть и наблюдение (проживание
    от 1800 ₽ в сутки), и оценка по коэффициенту от Петербурга.
    Сойдутся — коэффициентам можно верить. Разойдутся — врут они,
    а не рынок, и прайс надо пересматривать.
    """
    город = рынок.найти("крупный")
    наблюдение = город.наблюдение("проживание_месяц")
    оценка = город.оценка("проживание_месяц")
    assert наблюдение, "наблюдение по проживанию исчезло"
    расхождение = abs(оценка - наблюдение) / наблюдение
    assert расхождение < 0.10, (
        f"оценка {оценка} против наблюдения {наблюдение}: "
        f"расходятся на {расхождение * 100:.0f} %")


def test_наблюдение_всегда_побеждает_оценку():
    """Считанная цифра важнее выведенной: иначе зачем было считать."""
    for город in рынок.ГОРОДА:
        for имя, значение, _ in город.наблюдения:
            if имя in рынок.ОПОРА:
                assert город.цена(имя) == значение, (город.id, имя)


def test_у_каждого_наблюдения_есть_источник():
    """Цифра без источника через полгода неотличима от выдумки."""
    for город in рынок.ГОРОДА:
        assert len(город.откуда_частник) > 10, город.id
        for имя, _, откуда in город.наблюдения:
            assert len(откуда) > 10, (город.id, имя)


def test_города_идут_от_дорогого_к_дешёвому():
    """Порядок — часть смысла: человек читает таблицу сверху вниз
    и должен видеть, что Москва дороже райцентра, а не наоборот."""
    цены = [г.частник_час for г in рынок.ГОРОДА]
    assert цены == sorted(цены, reverse=True), цены
    for что in ("смена12", "сутки", "проживание_месяц"):
        ряд = [г.цена(что) for г in рынок.ГОРОДА]
        assert ряд == sorted(ряд, reverse=True), (что, ряд)


def test_служба_дороже_частника_но_не_втрое():
    """Ниже частника — демпинг против людей, которые ухаживают
    за деньги. Втрое дороже — прайс, который не продаётся."""
    for город in рынок.ГОРОДА:
        низ, верх = город.вилка_часа()
        assert низ > город.частник_час, город.id
        assert верх < город.частник_час * 3, город.id


def test_час_дешевеет_с_длиной_блока():
    ставки = [рынок.ставка_часа(б) for б in (1, 2, 3, 4, 8, 12)]
    assert ставки == sorted(ставки, reverse=True), ставки


def test_все_наши_цены_внутри_вилки_своего_города():
    """Прайс должен лежать в коридоре местных агентств. Короткий
    визит — исключение: полчаса дороги ложатся на один час."""
    низ, верх = рынок.наш().вилка_часа()
    for пакет in прайс.ПАКЕТЫ:
        за_час = пакет.цена / пакет.часов_в_месяц
        assert низ <= за_час <= верх, (пакет.название, за_час)
    for услуга in прайс.УСЛУГИ:
        if услуга.id in ("first_visit", "v1"):
            continue
        за_час = услуга.цена / услуга.часов
        assert за_час <= верх, (услуга.название, за_час)


def test_смена_и_сутки_в_пределах_рынка_города():
    """Отдельно — крупные позиции: по ним человек сравнивает
    в первую очередь."""
    город = рынок.наш()
    сутки = прайс.найти("round").цена
    assert сутки <= город.цена("сутки") * 2.5, сутки
    проживание = прайс.найти("live_in").цена * 30
    assert проживание <= город.цена("проживание_месяц") * 1.3, проживание


def test_переезд_в_другой_город_двигает_весь_прайс():
    """Служба переедет — прайс должен поехать за ней, а не остаться
    тольяттинским. Проверяем, что цены и правда зависят от города."""
    было = рынок.НАШ_ГОРОД
    try:
        рынок.НАШ_ГОРОД = "москва"
        московская = рынок.ставка_часа(2)
        рынок.НАШ_ГОРОД = "малый"
        районная = рынок.ставка_часа(2)
    finally:
        рынок.НАШ_ГОРОД = было
    assert московская > районная * 2, (московская, районная)


def test_где_мы_показывает_четыре_ориентира():
    где = прайс.где_на_рынке("v2")
    что = [с["что"] for с in где["шкала"]]
    assert "Наша цена" in что and "Частное объявление" in что
    assert где["внутри_вилки"], где["вилка"]
    наша = next(с for с in где["шкала"] if с["что"] == "Наша цена")
    частник = next(с for с in где["шкала"] if с["что"] == "Частное объявление")
    assert наша["рублей"] > частник["рублей"]


def test_обычаи_рынка_объяснены():
    """Надбавки, которые берут все. Без объяснения выглядят
    как наша выдумка."""
    assert len(рынок.ОБЫЧАИ_РЫНКА) >= 3
    for что, сколько, пояснение in рынок.ОБЫЧАИ_РЫНКА:
        assert что and сколько and len(пояснение) > 25


def test_неизвестный_город_это_ошибка():
    assert рынок.найти("атлантида") is None
    было = рынок.НАШ_ГОРОД
    try:
        рынок.НАШ_ГОРОД = "атлантида"
        with pytest.raises(KeyError):
            рынок.наш()
    finally:
        рынок.НАШ_ГОРОД = было


def test_выгрузка_рынка_совпадает_с_модулем():
    выгрузка = json.loads((КОРЕНЬ / "webapp" / "price.json")
                          .read_text(encoding="utf-8"))
    assert [г["id"] for г in выгрузка["города"]] == [г.id for г in рынок.ГОРОДА]
    наш = [г for г in выгрузка["города"] if г["наш"]]
    assert len(наш) == 1 and наш[0]["id"] == рынок.НАШ_ГОРОД
    assert выгрузка["где_на_рынке"]["внутри_вилки"]


def test_план_ухода_называет_порядок_суммы():
    """Человек, увидевший план и не увидевший цифры, всё равно
    придумает их сам — и обычно неверно."""
    import уход

    for шаблон in уход.ШАБЛОНЫ:
        сколько = уход.сколько_примерно(шаблон.id)
        assert сколько, шаблон.id
        assert сколько["в_месяц"] > 0
        assert 50 < сколько["доля_семьи"] <= 100, шаблон.id
        assert прайс.найти(сколько["позиция"]) is not None
