"""Угроза жизни: бот обязан назвать номер и не мешать.

Это единственное место в системе, где ошибка стоит не удобства, а жизни.
До этих проверок бот на «он не дышит» отвечал «Напишите номер ответа —
от 1 до 3».
"""
from __future__ import annotations

import pytest

import emergency
from chatbot_survey import Survey

# Как люди пишут на самом деле: без запятых, капсом, в разных формах.
ОПАСНЫЕ = [
    "он не дышит",
    "перестал дышать",
    "ЗАДЫХАЕТСЯ!!!",
    "мама без сознания",
    "потеряла сознание и не приходит в себя",
    "не реагирует совсем",
    "кажется инфаркт, давит в груди",
    "похоже на инсульт, перекосило лицо",
    "сильное кровотечение не могу остановить",
    "судороги начались",
    "упал и не встаёт",
    "наглотался таблеток",
    "подавился",
    "он умирает",
    "вызовите скорую",
    "нужна скорая срочно",
    "человеку плохо прямо сейчас",
    "спасите",
]

СПОКОЙНЫЕ = [
    "как оформить сиделку",
    "дышит нормально, спит",
    "хочу узнать про уровни ухода",
    "какие документы нужны",
    "спасибо, всё понятно",
    "мама ходит с ходунками",
]


@pytest.mark.parametrize("фраза", ОПАСНЫЕ)
def test_опасная_фраза_распознаётся(фраза):
    сигнал = emergency.распознать(фраза)
    assert сигнал is not None, f"не распознано: {фраза!r}"
    assert "103" in сигнал.ответ or "8-800" in сигнал.ответ


@pytest.mark.parametrize("фраза", СПОКОЙНЫЕ)
def test_обычная_фраза_не_поднимает_тревогу(фраза):
    assert emergency.распознать(фраза) is None, f"ложная тревога: {фраза!r}"


def test_разговор_о_смерти_ведёт_к_телефону_доверия():
    """Ответ на риск суицида отличается: человеку нужен собеседник сейчас."""
    сигнал = emergency.распознать("не хочу жить")
    assert сигнал is not None
    assert сигнал.вид == "поддержка"
    assert "8-800-2000-122" in сигнал.ответ
    assert "103" in сигнал.ответ


def test_нормализация_не_мешает_распознаванию():
    """Капс, «ё», лишние знаки и пробелы — обычное письмо в панике."""
    for вариант in ("НЕ ДЫШИТ", "не  дышит...", "не дышит!!!", "Не Дышит"):
        assert emergency.распознать(вариант) is not None, вариант


@pytest.fixture()
def анкета(tmp_path):
    survey = Survey(storage_path=str(tmp_path / "responses.json"), list_options=False)
    survey.handle("u1", "здравствуйте")
    return survey


def test_экстренный_ответ_идёт_раньше_анкеты(анкета):
    анкета.grant_consent("u1")
    ответ = анкета.handle("u1", "он не дышит")

    assert ответ.startswith("Если это происходит прямо сейчас"), (
        "номер должен быть в первой строке, а не в конце сообщения"
    )
    assert "Напишите номер ответа" not in ответ.split("—" * 20)[0]


def test_согласие_не_стоит_на_пути_экстренного(анкета):
    """Человек ещё не нажал «Согласен». Это не повод молчать про 103."""
    assert анкета.stage("u1") == "consent"
    ответ = анкета.handle("u1", "он не дышит")

    assert "103" in ответ
    assert ответ.startswith("Если это происходит прямо сейчас")


def test_анкета_не_теряется_после_тревоги(анкета):
    анкета.grant_consent("u1")
    шаг_до = анкета.current("u1")[0]

    ответ = анкета.handle("u1", "умирает")

    assert анкета.current("u1")[0] == шаг_до, "тревога не должна съедать ответ на вопрос"
    assert анкета.question_text("u1").split("\n")[0] in ответ, "вопрос должен остаться перед человеком"


def test_оператор_видит_пометку_об_угрозе(анкета):
    анкета.grant_consent("u1")
    анкета.handle("u1", "он не дышит")

    пометки = (анкета.state.get("u1") or {}).get("alerts") or []
    assert any("Угроза жизни" in п for п in пометки), f"в CRM не видно тревоги: {пометки}"


def test_повтор_тревоги_не_плодит_одинаковые_пометки(анкета):
    анкета.grant_consent("u1")
    for _ in range(3):
        анкета.handle("u1", "он не дышит")

    пометки = [п for п in ((анкета.state.get("u1") or {}).get("alerts") or []) if "не дыш" in п]
    assert len(пометки) == 1


def test_после_тревоги_анкета_продолжается(анкета):
    """Тревога — не тупик: человек возвращается и дозаполняет."""
    анкета.grant_consent("u1")
    анкета.handle("u1", "он не дышит")

    шаг = анкета.current("u1")[0]
    анкета.answer_by_numbers("u1", [1])
    assert анкета.current("u1") is None or анкета.current("u1")[0] != шаг
