@pytest.mark.parametrize("признак", sorted(emergency.НЕ_БЫВАЕТ_В_ПРОШЛОМ))
def test_признак_без_прошедшего_времени_не_глушится_никогда(признак):
    """«Не дышит давно» — это всё ещё «не дышит».

    Часть признаков описывает только то, что происходит сейчас: у них
    нет хронического прочтения. Слово «давно» рядом с таким признаком
    не смеет ничего отменить.
    """
    for обрамление in ("давно {}", "после {}", "{} в прошлом году",
                       "перенесла {}", "{} много лет"):
        фраза = обрамление.format(признак)
        assert emergency.распознать(фраза) is not None, фраза


def test_список_без_прошедшего_времени_не_пересекается_с_хроническим():
    """Инсульт и перелом в истории болезни бывают, остановка дыхания — нет.

    Если признак попадёт в оба списка сразу, правило станет
    непредсказуемым: проверка держит разделение явным.
    """
    хронические = set(
        emergency.ИНСУЛЬТ + emergency.ТРАВМА + emergency.ОЖОГИ
        + emergency.ОТРАВЛЕНИЕ + emergency.СУДОРОГИ + emergency.ДАВЛЕНИЕ
    )
    assert хронические & emergency.НЕ_БЫВАЕТ_В_ПРОШЛОМ == set()
