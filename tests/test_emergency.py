def test_экстренный_ответ_идёт_раньше_анкеты(анкета):
    анкета.grant_consent("u1")
    ответ = анкета.handle("u1", "он не дышит")

    assert ответ.startswith("Если это происходит прямо сейчас"), (
        "номер должен быть в первой строке, а не в конце сообщения"
    )
    assert "Напишите номер ответа" not in ответ.split("—" * 20)[0]


def test_согласие_не_стоит_на_пути_экстренного(анкета):
    """Человек ещё не нажал «Согласен». Это не повод молчать про 103."""
    assert анкета.stage("u1") == "consent"
    ответ = анкета.handle("u1", "он не дышит")

    assert "103" in ответ
    assert ответ.startswith("Если это происходит прямо сейчас")


def test_анкета_не_теряется_после_тревоги(анкета):
    анкета.grant_consent("u1")
    шаг_до = анкета.current("u1")[0]

    ответ = анкета.handle("u1", "умирает")

    assert анкета.current("u1")[0] == шаг_до, "тревога не должна съедать ответ на вопрос"
    assert анкета.question_text("u1").split("\n")[0] in ответ, "вопрос должен остаться перед человеком"


def test_оператор_видит_пометку_об_угрозе(анкета):
    анкета.grant_consent("u1")
    анкета.handle("u1", "он не дышит")

    пометки = (анкета.state.get("u1") or {}).get("alerts") or []
    assert any("Угроза жизни" in п for п in пометки), f"в CRM не видно тревоги: {пометки}"


def test_повтор_тревоги_не_плодит_одинаковые_пометки(анкета):
    анкета.grant_consent("u1")
    for _ in range(3):
        анкета.handle("u1", "он не дышит")

    пометки = [п for п in ((анкета.state.get("u1") or {}).get("alerts") or []) if "не дыш" in п]
    assert len(пометки) == 1


def test_после_тревоги_анкета_продолжается(анкета):
    """Тревога — не тупик: человек возвращается и дозаполняет."""
    анкета.grant_consent("u1")
    анкета.handle("u1", "он не дышит")

    шаг = анкета.current("u1")[0]
    анкета.answer_by_numbers("u1", [1])
    assert анкета.current("u1") is None or анкета.current("u1")[0] != шаг


def test_ответ_кнопкой_не_перехватывается_тревогой(анкета):
    """Вопрос о признаках сам содержит «Тяжело дышит» и «Боль».

    Если написать ровно то, что на кнопке, человек отвечает на вопрос,
    а не зовёт на помощь. Перехватить такой ответ значит не дать его
    записать — и потерять именно то сведение, ради которого спрашивали.
    """
    import walk

    анкета.grant_consent("u1")
    walk.дойти_до(анкета, "flags", u="u1")
    _, вопрос = анкета.current("u1")

    for вариант in вопрос["options"]:
        assert emergency.распознать(вариант, вопрос["options"]) is None, вариант


def test_свободная_фраза_с_теми_же_словами_тревогу_поднимает(анкета):
    """«Тяжело дышит» на кнопке — ответ. «Он тяжело дышит уже час» — тревога."""
    анкета.grant_consent("u1")
    ответ = анкета.handle("u1", "он тяжело дышит уже час, весь синий")

    assert ответ.startswith("Если это происходит прямо сейчас")


