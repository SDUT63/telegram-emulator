"""Заведение оператора: команда, которой пользуются руками.

Пароль вводился вслепую и дважды. На компьютере, где и так лежит CRM
с телефонами и адресами, скрытый ввод ничего не защищает — зато человек
не видит раскладку, опечатку и залипший Caps Lock, и узнаёт об этом
только когда оператор не может войти.

Отдельная беда была в том, что команда всегда заводила обычного
оператора: старшего, без которого нельзя отменить ошибочный контрольный
звонок, создать было нечем.
"""
from __future__ import annotations

import io
import json
import re

import pytest

import crm_store as store


@pytest.fixture()
def файл(tmp_path, monkeypatch):
    monkeypatch.setattr(store, "OPERATORS", str(tmp_path / "operators.json"))
    return tmp_path / "operators.json"


def _ответы(monkeypatch, *строки: str) -> None:
    monkeypatch.setattr("sys.stdin", io.StringIO("\n".join(строки) + "\n"))


def _записи(файл) -> dict:
    """Что легло в файл. Отменённое действие файла не создаёт вовсе."""
    if not файл.exists():
        return {}
    return json.loads(файл.read_text(encoding="utf-8"))


# ------------------------------------------------------------ пароль

def test_пароль_виден_на_экране(файл, monkeypatch, capsys):
    """Главное изменение: человек видит, что набрал."""
    _ответы(monkeypatch, "anna", "Анна", "1", "лодка-парус-берег-заря")
    store._cli()

    видно = capsys.readouterr().out
    assert "лодка-парус-берег-заря" in видно, "пароль не показан"
    assert "ещё раз" not in видно, "пароль всё ещё спрашивают дважды"


def test_пароль_не_запрашивается_дважды(файл, monkeypatch):
    """Раз пароль виден, второй ввод — лишний повод ошибиться.

    Проверка кончится ошибкой чтения, если команда попросит ввод,
    которого в заготовленных ответах нет.
    """
    _ответы(monkeypatch, "anna", "Анна", "1", "лодка-парус-берег-заря")
    store._cli()

    assert "anna" in _записи(файл)


def test_готовый_пароль_принимается_пустым_вводом(файл, monkeypatch, capsys):
    """Человеку не надо придумывать — Enter берёт предложенный."""
    _ответы(monkeypatch, "anna", "Анна", "1", "")
    store._cli()

    вывод = capsys.readouterr().out
    предложен = re.search(r"Готовый надёжный пароль: (\S+)", вывод)
    assert предложен, "готовый пароль не предложен"
    assert store.verify("anna", предложен.group(1)) == "Анна", (
        "предложенный пароль не подошёл при входе"
    )


def test_пароль_сохраняется_хешем_а_не_как_есть(файл, monkeypatch):
    _ответы(monkeypatch, "anna", "Анна", "1", "лодка-парус-берег-заря")
    store._cli()

    хранимое = _записи(файл)["anna"]["password"]
    assert "лодка" not in хранимое
    assert "$" in хранимое and len(хранимое) > 60


def test_короткий_пароль_не_проходит(файл, monkeypatch):
    _ответы(monkeypatch, "boris", "Борис", "1", "семь777")
    store._cli()

    assert "boris" not in _записи(файл), "пароль короче восьми знаков прошёл"


def test_заведомо_плохой_пароль_не_проходит(файл, monkeypatch):
    _ответы(monkeypatch, "anna", "Анна", "1", "12345678")
    store._cli()
    assert _записи(файл) == {}


# ------------------------------------------------------------- роль

def test_можно_завести_старшего(файл, monkeypatch):
    """Без старшего некому отменить ошибочный контрольный звонок."""
    _ответы(monkeypatch, "boss", "Старший", "2", "лодка-парус-берег-заря")
    store._cli()

    assert _записи(файл)["boss"]["role"] == "supervisor"


def test_роль_по_умолчанию_обычный_оператор(файл, monkeypatch):
    _ответы(monkeypatch, "anna", "Анна", "", "лодка-парус-берег-заря")
    store._cli()

    assert _записи(файл)["anna"]["role"] == "operator"


def test_несуществующая_роль_отменяет_действие(файл, monkeypatch):
    _ответы(monkeypatch, "anna", "Анна", "9", "лодка-парус-берег-заря")
    store._cli()

    assert _записи(файл) == {}


def test_предупреждает_когда_старшего_нет(файл, monkeypatch, capsys):
    _ответы(monkeypatch, "anna", "Анна", "1", "лодка-парус-берег-заря")
    store._cli()

    assert "Ни одного старшего" in capsys.readouterr().out


def test_не_предупреждает_когда_старший_есть(файл, monkeypatch, capsys):
    store.add_operator("boss", "Старший", "длинный-пароль", role="supervisor")
    _ответы(monkeypatch, "anna", "Анна", "1", "лодка-парус-берег-заря")
    store._cli()

    assert "Ни одного старшего" not in capsys.readouterr().out


# ---------------------------------------------------- существующий логин

def test_существующий_логин_требует_подтверждения(файл, monkeypatch):
    """Иначе одно нажатие Enter молча меняет пароль работающему человеку."""
    store.add_operator("anna", "Анна", "старый-пароль-тут", role="operator")

    _ответы(monkeypatch, "anna", "нет")
    store._cli()

    assert store.verify("anna", "старый-пароль-тут") == "Анна", "пароль сменили без спроса"


def test_существующему_логину_можно_сменить_пароль(файл, monkeypatch):
    store.add_operator("anna", "Анна", "старый-пароль-тут", role="operator")

    _ответы(monkeypatch, "anna", "да", "Анна", "1", "новый-пароль-совсем")
    store._cli()

    assert store.verify("anna", "новый-пароль-совсем") == "Анна"
    assert store.verify("anna", "старый-пароль-тут") is None


# ------------------------------------------------------- готовый пароль

def test_готовый_пароль_только_из_русских_букв_и_дефисов():
    """Его диктуют по телефону и набирают с чужой клавиатуры."""
    for _ in range(50):
        пароль = store._пароль_по_умолчанию()
        assert re.fullmatch(r"[а-я]+(-[а-я]+){3}", пароль), пароль
        assert "ё" not in пароль


def test_словарь_готового_пароля_без_повторов_и_мусора():
    assert len(set(store.СЛОВА)) == len(store.СЛОВА)
    плохие = [с for с in store.СЛОВА if not re.fullmatch(r"[а-я]+", с)]
    assert плохие == [], плохие
    # Меньше тысячи слов в словаре — значит, стойкость держится на длине.
    # Четыре слова из шестидесяти дают миллионы сочетаний; вместе
    # с задержкой после неудачных попыток этого достаточно.
    assert len(store.СЛОВА) ** 4 > 10_000_000
