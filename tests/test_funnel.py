"""Воронка: видно ли, где люди перестают отвечать.

За рекламу платят, и вопрос «работает ли она» упирается не в число
переходов, а в число карточек, по которым координатор смог позвонить.
Без этих чисел правка анкеты — гадание.

Отдельно проверяется, что наружу выходят только числа: отчёт показывают
учредителю и рекламщику, и имени с телефоном в нём быть не должно.
"""
from __future__ import annotations

import json

import pytest

import funnel
import walk
from chatbot_survey import Survey


@pytest.fixture()
def анкета(tmp_path):
    return Survey(storage_path=str(tmp_path / "r.json"), list_options=False)


def _пришёл(анкета, u: str) -> None:
    анкета.handle(u, "здравствуйте")


def _дошёл_до(анкета, u: str, ключ: str) -> None:
    _пришёл(анкета, u)
    анкета.grant_consent(u)
    walk.дойти_до(анкета, ключ, u=u, ответы={"mobility": "лежачая"})


def _прошёл_целиком(анкета, u: str) -> None:
    _пришёл(анкета, u)
    анкета.grant_consent(u)
    walk.пройти(анкета, u=u)


def _ступень(в: funnel.Воронка, имя: str) -> int:
    for название, сколько in в.ступени:
        if название == имя:
            return сколько
    raise AssertionError(f"нет ступени «{имя}»: {[и for и, _ in в.ступени]}")


def test_пустая_воронка_не_врёт(анкета):
    assert funnel.по_анкете(анкета).как_текст() == "Пока никто не писал."


def test_отказ_от_согласия_не_считается_согласием(анкета):
    """Согласие и отказ лежат в одном поле — и это разные вещи."""
    _пришёл(анкета, "u1")
    анкета.refuse_consent("u1")

    в = funnel.по_анкете(анкета)
    assert _ступень(в, "Дали согласие") == 0
    assert в.отказались == 1


def test_ступени_вложены_одна_в_другую(анкета):
    """Кто дошёл до нижней, прошёл и все верхние.

    Если это перестанет быть правдой, проценты потерь станут враньём,
    а решения по ним — вредом. Поэтому проверяется на разнородном
    наборе, а не на одном удобном случае.
    """
    _пришёл(анкета, "молчун")
    _пришёл(анкета, "отказ")
    анкета.refuse_consent("отказ")
    _дошёл_до(анкета, "имя", "name")
    _дошёл_до(анкета, "возраст", "age")
    _дошёл_до(анкета, "подвижность", "mobility")
    _прошёл_целиком(анкета, "до конца")

    _пришёл(анкета, "достаточно")
    анкета.grant_consent("достаточно")
    walk.дойти_до(анкета, "continue", u="достаточно")
    анкета.handle("достаточно", "хватит, позвоните")

    числа = [n for _, n in funnel.по_анкете(анкета).ступени]
    assert числа == sorted(числа, reverse=True), числа


def test_остановившийся_сам_не_считается_заполнившим(анкета):
    """«Достаточно, свяжитесь» помечает анкету законченной.

    Но подробную часть человек не проходил, и считать его заполнившим
    её целиком значит завысить итог воронки ровно на тех, ради кого
    подробную часть и добавляли.
    """
    _пришёл(анкета, "u1")
    анкета.grant_consent("u1")
    walk.дойти_до(анкета, "continue", u="u1")
    анкета.handle("u1", "хватит, позвоните")

    в = funnel.по_анкете(анкета)
    assert _ступень(в, "Заполнили анкету полностью") == 0
    assert в.остановились_сами == 1
    assert "по ним звонят" in в.как_текст()


def test_телефон_считается_отдельной_ступенью(анкета):
    """С телефона начинается работа координатора — это главный рубеж."""
    _дошёл_до(анкета, "без телефона", "phone")   # стоит на вопросе, не ответил
    _дошёл_до(анкета, "с телефоном", "age")      # телефон уже позади

    assert _ступень(funnel.по_анкете(анкета), "Оставили телефон") == 1


def test_видно_на_каком_разделе_остановились(анкета):
    _дошёл_до(анкета, "u1", "age")
    _дошёл_до(анкета, "u2", "age")
    _дошёл_до(анкета, "u3", "mobility")

    остановки = funnel.по_анкете(анкета).остановки
    assert остановки.get("Состояние сейчас") == 2
    assert остановки.get("Подвижность") == 1
    # Самый людный раздел — первым: по нему и принимают решение.
    assert list(остановки)[0] == "Состояние сейчас"


def test_дошедшие_до_конца_в_остановки_не_попадают(анкета):
    _прошёл_целиком(анкета, "u1")
    assert funnel.по_анкете(анкета).остановки == {}


def test_тревоги_видны_в_том_же_отчёте(анкета):
    _пришёл(анкета, "u1")
    анкета.grant_consent("u1")
    анкета.handle("u1", "он не дышит")

    в = funnel.по_анкете(анкета)
    assert в.с_тревогой == 1
    assert "угрозе жизни" in в.как_текст()


def test_в_отчёт_не_попадают_персональные_данные(анкета):
    """Отчёт показывают учредителю и рекламщику.

    Наружу выходят числа — ни имени, ни телефона, ни адреса, ни того,
    что человек написал своими словами, ни его идентификатора.
    """
    _пришёл(анкета, "max-user-778899")
    анкета.grant_consent("max-user-778899")
    walk.дойти_до(анкета, "age", u="max-user-778899",
                  ответы={"name": "Ольга Петровна", "patient_name": "Нина Ивановна",
                          "phone": "89171234567",
                          "address": "Революционная 12, кв 5"})

    в = funnel.по_анкете(анкета)
    выдача = в.как_текст() + json.dumps(в.как_числа(), ensure_ascii=False)

    for тайна in ("Ольга", "Нина", "89171234567", "Революционная",
                  "max-user-778899"):
        assert тайна not in выдача, f"в отчёте оказалось: {тайна}"


def test_числа_и_текст_говорят_одно_и_то_же(анкета):
    _дошёл_до(анкета, "u1", "age")
    _прошёл_целиком(анкета, "u2")

    в = funnel.по_анкете(анкета)
    числа = в.как_числа()
    assert числа["всего"] == 2
    assert [с["человек"] for с in числа["ступени"]] == [n for _, n in в.ступени]


def test_ступени_описаны_в_том_же_порядке_что_считаются():
    """Имена ступеней — это то, что читает человек. Они должны быть
    не пустыми и не повторяться, иначе отчёт нечитаем."""
    имена = [и for и, _ in funnel.СТУПЕНИ]
    assert all(имена)
    assert len(set(имена)) == len(имена)
    assert имена[0] == "Написали боту"
