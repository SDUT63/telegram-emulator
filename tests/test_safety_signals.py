"""Сигналы безопасности: какой сценарий ведёт ответ (мануал по архиву, §6).

`emergency.оценить` различает то, чего не различает `распознать`: о себе
пишет человек или пересказывает близкого, острое это состояние или
побочный эффект лечения, кризис или истощение. Фразы — из бенчмарка
`tests/fixtures/scenario_benchmark.json`: пересказ и составные примеры,
не цитаты.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

import emergency

БЕНЧМАРК = json.loads(
    (Path(__file__).resolve().with_name("fixtures") / "scenario_benchmark.json")
    .read_text(encoding="utf-8"))["cases"]
СВОБОДНЫЙ_ТЕКСТ = [c for c in БЕНЧМАРК if c["context"] == "free_text"]


@pytest.mark.parametrize("случай", СВОБОДНЫЙ_ТЕКСТ, ids=[c["id"] for c in СВОБОДНЫЙ_ТЕКСТ])
def test_ведущий_сценарий(случай):
    оценка = emergency.оценить(случай["input"])
    ожидаемо = случай["expect"]
    assert (оценка.ведущий if оценка else None) == ожидаемо["lead"]
    if оценка is None:
        return
    assert оценка.несовершеннолетний == bool(ожидаемо.get("minor"))
    assert оценка.эвтаназия == bool(ожидаемо.get("euthanasia"))
    for попутный in ожидаемо.get("also", []):
        assert попутный in оценка.попутно


def test_о_себе_и_о_близком_сразу_ведёт_кризис_с_попутным_ра4():
    оценка = emergency.оценить("Мама просит дать ей умереть, и я сама уже не хочу жить")
    assert оценка.ведущий == emergency.P0_SUICIDE
    assert emergency.RA4 in оценка.попутно


def test_хочется_не_путается_с_хочет():
    """«Жить совсем не хочется» — о себе, а не пересказ близкого."""
    оценка = emergency.оценить("жить совсем не хочется")
    assert оценка.ведущий == emergency.P0_SUICIDE
    assert оценка.попутно == ()


def test_боль_в_просьбе_близкого_ведёт_к_ра4_а_другое_острое_к_103():
    """Боль — причина просьбы, ответ на неё — паллиативная служба.

    Другой признак острого состояния по-прежнему ведёт к 103.
    """
    assert emergency.оценить(
        "папа говорит, что хочет умереть, у него сильные боли").ведущий == emergency.RA4
    assert emergency.оценить(
        "папа просит дать ему умереть и сейчас без сознания").ведущий == emergency.P0_MEDICAL


@pytest.mark.parametrize("фраза", [
    "мама хочет умереть дома, а не в больнице",
    "он хочет умереть у себя, в своей постели",
])
def test_место_смерти_не_желание_смерти(фраза):
    assert emergency.оценить(фраза) is None


@pytest.mark.parametrize("фраза", [
    "в правой руке нет силы, пальцы немеют",
    "врач выгорела на работе, не разговаривает",
    "больше не могу дозвониться до поликлиники",
    "аппарат ПЭТ сломался, перенесли",
])
def test_истощение_только_целыми_словами_и_о_себе(фраза):
    assert emergency.оценить(фраза) is None


def test_ответ_кнопкой_не_перехватывается():
    """Подпись варианта анкеты «На пределе» — ответ, а не сигнал."""
    assert emergency.оценить("На пределе", ["Справляемся", "На пределе"]) is None


def test_старый_распознаватель_не_изменился_для_судорог():
    """До подписи врача (Р-А1) действует прежнее поведение — оно строится
    на `распознать`, поэтому тот обязан видеть судороги как раньше."""
    assert emergency.распознать("судороги в ногах на тамоксифене").вид == "скорая"
