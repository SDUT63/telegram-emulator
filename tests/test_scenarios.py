def test_утверждённый_подписан_неутверждённый_без_подписи():
    for с in scenarios.СЦЕНАРИИ.values():
        assert (с.status == "approved") == bool(с.approved_by and с.approved_at), с.id


def test_ждут_подписи_именно_те_что_решено():
    """P0 (медицина) — действующий текст; остальное ждёт врача и психолога."""
    ждут = {с.id for с in scenarios.СЦЕНАРИИ.values() if с.status == "pending"}
    assert ждут == {emergency.P0_SUICIDE, emergency.P2, emergency.RA4,
                    emergency.RA1_CONVULSIONS, emergency.RA1_BURN}


def test_боевой_режим_даёт_минимум_одним_сообщением(боевой):
    for фраза in ("я на пределе, не справляюсь", "муж просит дать ему умереть"):
        ответ = _ответ(фраза)
        assert ответ.ожидание is None and scenarios.кнопки(ответ.ожидание) == []


def test_боевой_режим_кризис_прежний_текст_с_взрослым_номером(боевой):
    ответ = _ответ("не хочу больше жить")
    assert ответ.текст == emergency.ПОДДЕРЖКА


def test_боевой_режим_судороги_как_прежде(боевой):
    """Р-А1 до подписи врача — ответ `распознать`, каким он был."""
    ответ = _ответ("судороги в ногах на тамоксифене")
    assert ответ.текст == emergency.СКОРАЯ
    assert ответ.пометка.startswith("Угроза жизни")
    # «Свело пальцы» прежде тревоги не давало — и сейчас не даёт.
    assert _ответ("свело пальцы на руке") is None


def test_тестовый_режим_ведёт_по_шагам(все):
    ответ = _ответ("я на пределе, не справляюсь")
    assert ответ.ожидание == (emergency.P2, 1, "safety_q")
    assert [п for п, _ in scenarios.кнопки(ответ.ожидание)] == ["Да", "Нет", "Не хочу отвечать"]


def test_до_согласия_всегда_минимум_и_без_ожидания(все):
    """Режим А: вопрос с кнопками требует помнить, о чём спросили, а до
    согласия помнить нечего и негде."""
    for фраза in ("я на пределе, не справляюсь", "муж просит дать ему умереть"):
        ответ = _ответ(фраза, согласие=False)
        assert ответ.ожидание is None
        assert "Координатор" not in ответ.текст and "координатору" not in ответ.текст


def test_после_согласия_минимум_говорит_о_координаторе(боевой):
    assert "Координатор свяжется" in _ответ("я на пределе, не справляюсь").текст
    assert "координатору в первую очередь" in _ответ("муж просит дать ему умереть").текст


