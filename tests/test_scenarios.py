"""Сценарии безопасности: тексты, статусы, ветки (мануал по архиву, §4, §8.3).

Контрактные тесты 2 (номера только из справочника), 4 (статусы) и 9
(без обещаний срока — решение 3). Боевой режим — переменная
`SDUT_SCENARIOS` не задана: работают только утверждённые сценарии,
остальные — безопасным минимумом. Тестовый — `SDUT_SCENARIOS=all`.
"""
from __future__ import annotations

import re

import pytest

import emergency
import scenarios
import support_contacts


@pytest.fixture()
def боевой(monkeypatch):
    monkeypatch.delenv("SDUT_SCENARIOS", raising=False)


@pytest.fixture()
def все(monkeypatch):
    monkeypatch.setenv("SDUT_SCENARIOS", "all")


def _тексты():
    for с in scenarios.СЦЕНАРИИ.values():
        for текст in (с.minimal, с.after_consent):
            if текст and текст != "legacy":
                yield с.id, текст
        for шаг in с.steps.values():
            for текст in (шаг.say, шаг.ask, *[к.label for к in шаг.buttons]):
                if текст:
                    yield f"{с.id}.{шаг.id}", текст


ТЕКСТЫ = list(_тексты())


def _ответ(фраза, согласие=True):
    return scenarios.ответ(emergency.оценить(фраза), фраза, согласие=согласие)


# ---------------------------------------------------------- тест 2: номера


@pytest.mark.parametrize("где, текст", ТЕКСТЫ, ids=[г for г, _ in ТЕКСТЫ])
def test_в_тексте_сценария_номера_только_ссылками(где, текст):
    без_ссылок = re.sub(r"\{contact:[a-z0-9_]+\}", "", текст)
    # «ст. 45», «№ 323-ФЗ» — номера статей закона, не телефоны.
    без_закона = re.sub(r"(ст\.\s*\d+|№\s*\d+-ФЗ)", "", без_ссылок)
    assert not re.search(r"\d{2,}", без_закона), где
    for id in support_contacts.ссылки(текст.replace("{contact:crisis}", "{contact:crisis_adult}")):
        assert id in support_contacts.СПРАВОЧНИК, (где, id)


# ---------------------------------------------------------- тест 9: сроки


ОБЕЩАНИЯ_СРОКА = re.compile(
    r"в течение|в течении|\bчас(?:а|ов)?\b|до конца|сегодня|завтра|в \d|минут|рабочего дня|в понедельник")


@pytest.mark.parametrize("где, текст", ТЕКСТЫ, ids=[г for г, _ in ТЕКСТЫ])
def test_сценарий_не_обещает_срок(где, текст):
    """Решение 3: срок связи человеку не называется нигде.

    «В рабочее время» — не срок, а честное «не ночью и не в выходные».
    «В ближайшие дни», «в ближайший рабочий день» — совет человеку, когда
    сходить к врачу, а не обещание службы.
    """
    assert not ОБЕЩАНИЯ_СРОКА.search(текст.lower()), где


