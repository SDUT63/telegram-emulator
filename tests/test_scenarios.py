def test_эвтаназия_только_на_вопрос(все):
    с_вопросом = _ответ("он просит эвтаназию, можно ли это где-то сделать").текст
    без = _ответ("бабушка просит усыпить её").текст
    assert "ст. 45" in с_вопросом and "ст. 45" not in без


