"""Формы согласия по группам обратившихся.

Проверяем не тексты, а то, что от них зависит: каждому варианту первого
вопроса соответствует своя форма, и все три варианта покрыты.
"""
import pytest

import consent_forms as cf
import max_bot
import walk
from survey_questions import QUESTIONS


def первый_вопрос():
    return next(q for q in QUESTIONS if q["id"] == "who")


def test_каждый_вариант_первого_вопроса_имеет_форму():
    непокрытые = [o for o in первый_вопрос()["options"] if cf.for_answer(o) is None]
    assert not непокрытые, f"нет формы для: {непокрытые}"


def test_форма_привязана_к_первому_вопросу():
    assert первый_вопрос().get("after") is cf.note


def test_на_чужой_ответ_ничего_не_говорим():
    assert cf.for_answer("что-то другое") is None
    assert cf.note({"who": "что-то другое"}) == ""
    assert cf.signs({"who": "что-то другое"}) == ""


def test_о_близком_говорит_кто_подписывает():
    текст = cf.for_answer("О близком человеке")["text"]
    assert "законный представитель" in текст.lower()
    assert "координатор" in текст.lower(), "человека нельзя оставлять один на один"


@pytest.mark.parametrize("ответ", ["О себе", "О близком человеке", "Я специалист"])
def test_записка_о_бумагах_короткая(ответ):
    """Второй экран подряд с юридическим текстом человека теряет."""
    текст = cf.for_answer(ответ)["text"]
    assert len(текст) < 450, f"{ответ}: {len(текст)} знаков — многовато"
    assert "суда" not in текст, "подробности — в полном тексте, не здесь"


def test_специалисту_сказано_что_он_не_может_дать_согласие():
    текст = cf.for_answer("Я специалист")["text"]
    assert "не может" in текст.lower()
    assert "18" in текст, "нужна ссылка на обязанность уведомить субъекта"


def test_кто_подписывает_попадает_в_полный_текст(consented):
    """Полный текст согласия знает, кто именно подпишет бумагу."""
    s = consented
    s.answer_by_numbers("u1", [2])
    assert "законный представитель" in s.consent_text("u1")


def test_записка_не_уводит_на_сайт():
    """Мини-приложение открывается своей кнопкой. Дублировать её глупо,
    а отправлять человека на сайт за текстом согласия — тем более."""
    for ответ in ("О себе", "О близком человеке", "Я специалист"):
        assert "http" not in cf.note({"who": ответ})
    assert not hasattr(cf, "DOCS_ANCHOR"), "ссылку убрали — константа лишняя"


def test_к_записке_приложен_полный_текст(consented):
    s = consented
    s.answer_by_numbers("u1", [2])
    assert s.reading("u1"), "после первого вопроса текст в одно нажатие"
    кнопки = [д for row in max_bot.layout(s, "u1") for _, д in row]
    assert кнопки[0] == "c:full", "и стоит он первой строкой, не среди ответов"


def test_кнопка_снимается_после_следующего_ответа(consented):
    s = consented
    s.answer_by_numbers("u1", [2])
    assert s.reading("u1")
    step, q = s.current("u1")
    walk.ответить(s, "u1", q)
    assert s.reading("u1") is False, "под всей анкетой она висеть не должна"


def test_реквизиты_организации_совпадают_с_егрюл():
    """Один и тот же ОГРН в справочнике и в формах — иначе кто-то устарел."""
    страница = open("webapp/index.html", encoding="utf-8").read()
    for значение in ("1266300009766", "6320093220", "632001001"):
        assert значение in страница, f"в справочнике нет {значение}"
