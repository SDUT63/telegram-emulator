#!/usr/bin/env python3
"""Защита входа оператора от перебора пароля.

За этой дверью лежат имена, телефоны, адреса и описания состояния тяжело
больных людей. Пароль без ограничения попыток — это не защита: подобрать
словарный пароль по сети можно за вечер, и никто об этом не узнает.

Как устроено
------------
Окно с экспоненциальной задержкой по паре «логин + адрес». Считаем именно
пару: блокировать логин по чужим попыткам значит дать любому желающему
запереть координатора снаружи, а блокировать только адрес — пропустить
перебор одного пароля по списку логинов.

Успешный вход очищает счётчик: человек, который ошибся дважды и вспомнил
пароль, не должен ждать.

Хранение в памяти процесса
--------------------------
CRM — одиночный процесс на рабочем месте, общей БД у него нет. Память
переживает перебор, но не перезапуск; это осознанный размен. Если CRM
когда-нибудь поедет в несколько инстансов, счётчик надо перенести в
PostgreSQL — интерфейс для этого менять не придётся.
"""
from __future__ import annotations

import threading
import time
from dataclasses import dataclass, field

# Первые попытки бесплатны: человек честно ошибается. Дальше задержка
# удваивается, и перебор становится бессмысленным задолго до того, как
# переберёт что-то осмысленное.
БЕСПЛАТНЫХ_ПОПЫТОК = 3
БАЗОВАЯ_ЗАДЕРЖКА = 5.0        # секунд после первой лишней ошибки
ПРЕДЕЛ_ЗАДЕРЖКИ = 900.0       # пятнадцать минут — дальше расти незачем
ОКНО_ЗАБВЕНИЯ = 3600.0        # час без ошибок обнуляет счётчик


@dataclass
class _Счёт:
    ошибок: int = 0
    последняя: float = 0.0
    ждать_до: float = 0.0


@dataclass
class ЗащитаВхода:
    """Счётчик неудачных попыток по паре «логин + адрес»."""

    часы: object = time.monotonic
    _записи: dict[tuple[str, str], _Счёт] = field(default_factory=dict)
    _замок: threading.Lock = field(default_factory=threading.Lock)

    def _ключ(self, логин: str, адрес: str) -> tuple[str, str]:
        return (str(логин or "").strip().lower(), str(адрес or "").strip())

    def задержка(self, логин: str, адрес: str) -> float:
        """Сколько секунд осталось ждать. Ноль — можно пробовать."""
        сейчас = self.часы()
        with self._замок:
            запись = self._записи.get(self._ключ(логин, адрес))
            if запись is None:
                return 0.0
            if сейчас - запись.последняя > ОКНО_ЗАБВЕНИЯ:
                self._записи.pop(self._ключ(логин, адрес), None)
                return 0.0
            return max(0.0, запись.ждать_до - сейчас)

    def неудача(self, логин: str, адрес: str) -> float:
        """Записать неудачную попытку. Вернуть новую задержку."""
        сейчас = self.часы()
        ключ = self._ключ(логин, адрес)
        with self._замок:
            запись = self._записи.get(ключ)
            if запись is None or сейчас - запись.последняя > ОКНО_ЗАБВЕНИЯ:
                запись = _Счёт()
                self._записи[ключ] = запись
            запись.ошибок += 1
            запись.последняя = сейчас
            лишних = запись.ошибок - БЕСПЛАТНЫХ_ПОПЫТОК
            if лишних <= 0:
                запись.ждать_до = сейчас
                return 0.0
            задержка = min(ПРЕДЕЛ_ЗАДЕРЖКИ, БАЗОВАЯ_ЗАДЕРЖКА * (2 ** (лишних - 1)))
            запись.ждать_до = сейчас + задержка
            return задержка

    def успех(self, логин: str, адрес: str) -> None:
        """Верный пароль снимает счётчик: честная ошибка не наказывается."""
        with self._замок:
            self._записи.pop(self._ключ(логин, адрес), None)

    def забыть_старое(self) -> int:
        """Убрать записи старше окна. Возвращает, сколько убрано."""
        сейчас = self.часы()
        with self._замок:
            старые = [к for к, з in self._записи.items() if сейчас - з.последняя > ОКНО_ЗАБВЕНИЯ]
            for ключ in старые:
                self._записи.pop(ключ, None)
        return len(старые)


ЗАЩИТА = ЗащитаВхода()

__all__ = ["ЗащитаВхода", "ЗАЩИТА", "БЕСПЛАТНЫХ_ПОПЫТОК", "БАЗОВАЯ_ЗАДЕРЖКА", "ПРЕДЕЛ_ЗАДЕРЖКИ"]
