#!/usr/bin/env python3
"""Обезвреживание значений, которые уезжают в таблицу.

Зачем. В анкете человек пишет что угодно, включая своё имя. Если имя
начинается со знака равенства, Excel считает содержимое ячейки
формулой и выполняет её при открытии файла — вместе с переходами
по ссылкам, обращениями к внешним данным, а в старых версиях
и с запуском команд через DDE.

Путь атаки короткий: любой, кто может написать боту, кладёт формулу
в ответ на вопрос об имени; координатор выгружает обращения в Excel
и открывает файл у себя на компьютере. Между «написал в чат» и
«выполнилось на рабочем месте» нет ни одного препятствия.

Проверено стендом нагрузка/сервер.py: до этой правки выгрузка
содержала работающий =HYPERLINK, положенный через обычный ответ
на вопрос анкеты.

Значение не искажаем: координатор должен увидеть ровно то, что
написал человек, — это может быть уликой. Поэтому не вырезаем, а
помечаем как текст.
"""

from __future__ import annotations

from typing import Any

# С этих знаков Excel, LibreOffice и Google Sheets начинают формулу.
# Табуляция и возврат каретки — потому что их дописывают перед знаком
# равенства, чтобы обойти проверку на первый символ.
ОПАСНОЕ_НАЧАЛО = ("=", "+", "-", "@", "\t", "\r", "\n")


def опасно(значение: Any) -> bool:
    """Начнёт ли таблица считать это формулой."""
    return isinstance(значение, str) and значение[:1] in ОПАСНОЕ_НАЧАЛО


def для_csv(значение: Any) -> Any:
    """Значение для CSV: опасное начало прикрываем апострофом.

    В CSV таблица разбирает содержимое при открытии, и другого способа
    сказать «это текст» в самом файле нет.
    """
    if опасно(значение):
        return "'" + значение
    return значение


def в_ячейку(лист, строка: int, столбец: int, значение: Any) -> None:
    """Записать значение в ячейку xlsx, не превратив его в формулу.

    openpyxl сам решает, что строка со знаком равенства — формула,
    и пишет её формулой. Ставим тип «строка» обратно: Excel не
    разбирает то, что лежит в файле как строка, и показывает текст
    как есть.
    """
    ячейка = лист.cell(row=строка, column=столбец)
    ячейка.value = значение
    if опасно(значение):
        ячейка.data_type = "s"
        ячейка.quotePrefix = True


def строкой(лист, значения: list) -> None:
    """Добавить строку целиком — замена sheet.append()."""
    номер = лист.max_row + 1 if лист.max_row > 1 or лист["A1"].value is not None else 1
    for столбец, значение in enumerate(значения, start=1):
        в_ячейку(лист, номер, столбец, значение)
