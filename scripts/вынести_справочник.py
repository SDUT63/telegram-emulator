#!/usr/bin/env python3
"""Разовый перенос: статьи из webapp/guide.html — в база/*.md.

Справочник был страницей и одновременно источником базы знаний.
Это работало, пока страница была входом. Теперь вход — приложение
с поиском, и держать полотно ради того, чтобы из него разбирать
статьи, незачем: статьи должны лежать статьями.

Картинки остаются: они и есть половина ценности этих материалов.
Каждая едет со своей статьёй как поле «картинка».

Скрипт одноразовый и лежит здесь как документ: по нему видно,
что именно перенесено и ничего не потерялось.
"""

from __future__ import annotations

import html
import os
import re
import sys
from collections import OrderedDict

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, КОРЕНЬ)

import knowledge                                                # noqa: E402

СПРАВОЧНИК = os.path.join(КОРЕНЬ, "webapp", "guide.html")
КУДА = os.path.join(КОРЕНЬ, "база")

КАРТИНКА = re.compile(r'<img src="(?P<src>img/[^"]+)"[^>]*?alt="(?P<alt>[^"]*)"', re.S)
ПОДПИСЬ = re.compile(r"<figcaption>(?P<t>.*?)</figcaption>", re.S)

ИМЕНА = {
    "b-now": "справочник-срочно",
    "b-line": "справочник-куда-обратиться",
    "b-model": "справочник-что-такое-уход",
    "b-levels": "справочник-оценка-и-уровни",
    "b-care": "справочник-практика-ухода",
    "b-equip": "справочник-оборудование",
    "b-family": "справочник-тому-кто-ухаживает",
    "b-pall": "справочник-паллиатив",
    "b-rights": "справочник-права-и-контроль",
    "b-docs": "справочник-согласие-на-обработку",
    "b-media": "справочник-материалы",
    "b-org": "справочник-реквизиты",
}


def _чисто(кусок: str) -> str:
    return knowledge._без_разметки(кусок)


def _картинка(кусок: str) -> tuple[str, str]:
    """Первая картинка внутри куска и подпись к ней."""
    найдено = КАРТИНКА.search(кусок)
    if not найдено:
        return "", ""
    подпись = ПОДПИСЬ.search(кусок)
    текст = html.unescape(подпись.group("t")).strip() if подпись else ""
    текст = re.sub(r"<[^>]+>", " ", текст).strip()
    return найдено.group("src"), текст or html.unescape(найдено.group("alt"))[:120]


def собрать() -> "OrderedDict[str, list[dict]]":
    страница = open(СПРАВОЧНИК, encoding="utf-8").read()
    по_файлам: OrderedDict[str, list[dict]] = OrderedDict()

    for блок in knowledge.БЛОК.finditer(страница):
        ид = блок.group("id")
        раздел = _чисто(блок.group("name"))
        тело = блок.group("body")
        имя = ИМЕНА.get(ид, "справочник-" + ид)
        статьи = по_файлам.setdefault(имя, [])

        def добавить(титул: str, текст: str, кусок: str) -> None:
            if len(текст) < knowledge.КОРОТКАЯ:
                return
            картинка, подпись = _картинка(кусок)
            статьи.append({
                "заголовок": титул or раздел,
                "раздел": раздел,
                "текст": текст,
                "картинка": картинка,
                "подпись": подпись,
            })

        for вопрос in knowledge.ВОПРОС.finditer(тело):
            добавить(_чисто(вопрос.group("title")),
                     _чисто(вопрос.group("body")), вопрос.group("body"))
        тело = knowledge.ВОПРОС.sub(" ", тело)

        for строка in knowledge.СТРОКА.finditer(тело):
            титул = _чисто(строка.group("title"))
            добавить(титул, титул + " — " + _чисто(строка.group("body")),
                     строка.group(0))
        тело = knowledge.СТРОКА.sub(" ", тело)

        for карточка in knowledge.КАРТОЧКА.finditer(тело):
            сырое = карточка.group("body")
            титул = knowledge.ПОДЗАГОЛОВОК.search(сырое)
            добавить(_чисто(титул.group(1)) if титул else "",
                     _чисто(сырое), сырое)

    return по_файлам


ШАПКА = """<!--
Перенесено из справочника «Навигатор помощи» скриптом
scripts/вынести_справочник.py. Справочник был страницей и
одновременно источником базы; теперь статьи лежат статьями,
а входом служит мини-приложение с поиском.

Картинки — в webapp/img, поле «картинка» указывает на них.
-->
"""


def записать(по_файлам: "OrderedDict[str, list[dict]]") -> int:
    всего = 0
    for имя, статьи in по_файлам.items():
        if not статьи:
            continue
        куски = [ШАПКА]
        for с in статьи:
            строки = [f"# {с['заголовок']}", f"раздел: {с['раздел']}"]
            if с["картинка"]:
                строки.append(f"картинка: {с['картинка']}")
            if с["подпись"]:
                строки.append(f"подпись: {с['подпись']}")
            строки.append("источник: справочник службы")
            строки.append("")
            строки.append(с["текст"])
            куски.append("\n".join(строки))
            всего += 1
        путь = os.path.join(КУДА, имя + ".md")
        with open(путь, "w", encoding="utf-8") as файл:
            файл.write("\n\n".join(куски).rstrip() + "\n")
        с_картинкой = sum(1 for с in статьи if с["картинка"])
        print(f"  {имя}.md — {len(статьи)} статей, "
              f"с картинками {с_картинкой}")
    return всего


def main() -> int:
    было = len([с for с in knowledge.загрузить()
                if "Навигатор помощи" in с.источник])
    по_файлам = собрать()
    всего = записать(по_файлам)
    print(f"\nбыло в справочнике: {было}, перенесено: {всего}")
    return 0 if всего >= было else 1


if __name__ == "__main__":
    raise SystemExit(main())
