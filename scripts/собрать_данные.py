def собрать_страницу(шкала_данные: dict, база: dict, анкета: dict,
                     цены: dict, план: dict, железо: dict) -> None:
    """Собрать мини-приложение в один самодостаточный файл.

    Данные вшиваются в саму страницу. Сначала они лежали отдельными
    файлами, и на Cloudflare это не заработало: имена были кириллицей,
    браузер запрашивал их процентным кодированием, хостинг не находил —
    поиск, калькулятор и анкета молча оставались пустыми.

    Один файл нельзя разложить наполовину, и открывается он даже
    с диска, без сервера.
    """
    шаблон = ШАБЛОН.read_text(encoding="utf-8")
    начало = шаблон.index("/*ДАННЫЕ*/")
    конец = шаблон.index("/*КОНЕЦ*/") + len("/*КОНЕЦ*/")
    данные = {
        "scale.json": шкала_данные,
        "kb.json": база,
        "survey.json": анкета,
        "price.json": цены,
        "care.json": план,
        "gear.json": железо,
    }
    вшито = json.dumps(данные, ensure_ascii=False, separators=(",", ":"))
    СТРАНИЦА.write_text(шаблон[:начало] + вшито + шаблон[конец:], encoding="utf-8")
    print(f"index.html:  {СТРАНИЦА.stat().st_size / 1024:.0f} КБ, данные внутри")
    _старый_адрес()


def _старый_адрес() -> None:
    """Переадресация со старого адреса приложения на корень.

    Мини-приложение лежало по адресу app.html, и эта ссылка уже
    разошлась: она в чатах, в закладках и на уже выложенном сайте.
    Убрать её молча — значит отправить человека на «страница не
    найдена». Ответы из ссылки после решётки переносим вместе с ней,
    иначе перенос анкеты потерялся бы по дороге.
    """
    СТАРЫЙ_АДРЕС.write_text(
        '''<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Помощь дома — СДУТ</title>
<script>location.replace("index.html" + location.search + location.hash);</script>
<meta http-equiv="refresh" content="0; url=index.html">
</head>
<body style="font-family:system-ui,sans-serif;padding:2rem;line-height:1.6">
<p>Приложение переехало на главную страницу.</p>
<p><a href="index.html">Открыть приложение</a></p>
</body>
</html>
''',
        encoding="utf-8")
    print(f"app.html:    {СТАРЫЙ_АДРЕС.stat().st_size} Б, переадресация на корень")


