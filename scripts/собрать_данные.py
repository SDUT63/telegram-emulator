#!/usr/bin/env python3
"""Выгрузить данные бота в JSON для мини-приложения.

Мини-приложение — статическая страница на Cloudflare: Python там
не исполняется, и шкалу оно считает само. Переписывать её в HTML
руками нельзя: две копии нормативных весов разойдутся, и страница
начнёт показывать не тот уровень, который посчитает служба.

Поэтому единственный источник — scale_731.py, а этот скрипт делает
из него данные. Расхождение ловит проверка tests/test_scale_export.py.

    python scripts/собрать_данные.py

Делает три файла в webapp/:
    шкала.json   — оценочная шкала Приказа № 731 (21 позиция)
    база.json    — все статьи, которые знает бот
    анкета.json  — вопросы анкеты вместе с условиями ветвления
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))

import scale_731 as шкала                                    # noqa: E402

ШКАЛА = КОРЕНЬ / "webapp" / "scale.json"
БАЗА = КОРЕНЬ / "webapp" / "kb.json"
АНКЕТА = КОРЕНЬ / "webapp" / "survey.json"
ШАБЛОН = КОРЕНЬ / "шаблоны" / "приложение.html"
СТРАНИЦА = КОРЕНЬ / "webapp" / "app.html"


# Условия ветвления анкеты живут в survey_questions функциями Python.
# В статическую страницу функцию не положишь, поэтому здесь они описаны
# данными. Совпадение с настоящими функциями сверяет проверка
# tests/test_scale_export.py на всех сочетаниях ответов: разошлись бы —
# и мини-приложение спрашивало бы не то, что бот.
ВЕТВЛЕНИЕ: dict[str, dict] = {
    "relation": {"есть": ["who", ["о близком"]]},
    "aware": {"не": {"есть": ["who", ["о себе"]]}},
    # Имя подопечного спрашивают, только когда речь не о самом
    # обратившемся. Забыть это правило — значит спросить у человека
    # имя того, о ком он не говорил.
    "patient_name": {"не": {"есть": ["who", ["о себе"]]}},
    "turning": {"и": [{"есть": ["continue", ["продолж"]]},
                      {"есть": ["mobility", ["не встаёт", "коляск"]]}]},
    "skin": {"и": [{"есть": ["continue", ["продолж"]]},
                   {"есть": ["mobility", ["не встаёт", "коляск"]]}]},
    "falls": {"и": [{"есть": ["continue", ["продолж"]]},
                    {"не": {"есть": ["mobility", ["не встаёт"]]}}]},
    "pain_limits": {"и": [{"есть": ["continue", ["продолж"]]},
                          {"есть": ["pain", ["постоянная", "бывает"]]}]},
}
# Всё остальное, у чего есть «when», продолжает подробную часть.
ПОДРОБНАЯ_ЧАСТЬ = {"есть": ["continue", ["продолж"]]}


def собрать() -> dict:
    return {
        "источник": "Приказ Минтруда России № 731 от 23.12.2025, "
                    "приложение № 3, бланк «Блок В», раздел 4",
        "оговорка": шкала.PRELIMINARY,
        "максимум": sum(и.full for и in шкала.SCALE),
        "позиции": [
            {
                "id": и.id,
                "вопрос": и.plain,
                "официально": и.official,
                "раздел": и.group,
                "частично": и.mid,
                "не_может": и.full,
            }
            for и in шкала.SCALE
        ],
        "уровни": [
            {
                "от": низ,
                "до": верх,
                "номер": номер,
                "название": имя,
                "часов_в_неделю": list(шкала.PACKAGE_HOURS.get(номер, (0, 0))),
            }
            for низ, верх, номер, имя in шкала.LEVELS
        ],
    }


def собрать_базу() -> dict:
    """Все статьи, которые знает бот.

    Мини-приложение до сих пор показывало только те, что попали
    в справочник, — 86 из 240. Две трети материалов, включая всё
    об оценке нуждаемости и паллиативной помощи, человек не видел.
    """
    import knowledge

    статьи = knowledge.загрузить()
    return {
        "статей": len(статьи),
        "статьи": [
            {
                "id": hashlib.sha256(с.заголовок.encode("utf-8")).hexdigest()[:12],
                "заголовок": с.заголовок,
                "раздел": с.раздел,
                "текст": с.текст,
                "источник": с.источник,
                "ключи": list(с.ключи),
            }
            for с in статьи
        ],
    }


def собрать_анкету() -> dict:
    """Вопросы анкеты вместе с условиями ветвления."""
    from survey_questions import CHECKPOINT_ID, QUESTIONS, STOP_OPTION

    вопросы = []
    for в in QUESTIONS:
        запись = {
            "id": в["id"],
            "текст": в["text"],
            "вид": в["kind"],
            "обязательный": bool(в.get("required", True)),
        }
        if в.get("section"):
            запись["раздел"] = в["section"]
        if в.get("options"):
            запись["варианты"] = list(в["options"])
        if в.get("multi"):
            запись["несколько"] = True
        if в.get("when"):
            запись["когда"] = ВЕТВЛЕНИЕ.get(в["id"], ПОДРОБНАЯ_ЧАСТЬ)
        вопросы.append(запись)

    return {
        "рубеж": CHECKPOINT_ID,
        "остановиться": STOP_OPTION,
        "вопросов": len(вопросы),
        "вопросы": вопросы,
    }


def main() -> int:
    шкала_данные = собрать()
    ШКАЛА.write_text(json.dumps(шкала_данные, ensure_ascii=False, indent=2) + "\n",
                     encoding="utf-8")
    print(f"scale.json:  позиций {len(шкала_данные['позиции'])}, "
          f"максимум {шкала_данные['максимум']} баллов")

    база = собрать_базу()
    БАЗА.write_text(json.dumps(база, ensure_ascii=False, separators=(",", ":")) + "\n",
                    encoding="utf-8")
    размер = БАЗА.stat().st_size / 1024
    print(f"kb.json:     статей {база['статей']}, {размер:.0f} КБ")

    анкета = собрать_анкету()
    АНКЕТА.write_text(json.dumps(анкета, ensure_ascii=False, indent=2) + "\n",
                      encoding="utf-8")
    ветвятся = sum(1 for в in анкета["вопросы"] if "когда" in в)
    print(f"survey.json: вопросов {анкета['вопросов']}, из них с условием {ветвятся}")

    собрать_страницу(шкала_данные, база, анкета)
    return 0


def собрать_страницу(шкала_данные: dict, база: dict, анкета: dict) -> None:
    """Собрать мини-приложение в один самодостаточный файл.

    Данные вшиваются в саму страницу. Сначала они лежали отдельными
    файлами, и на Cloudflare это не заработало: имена были кириллицей,
    браузер запрашивал их процентным кодированием, хостинг не находил —
    поиск, калькулятор и анкета молча оставались пустыми.

    Один файл нельзя разложить наполовину, и открывается он даже
    с диска, без сервера.
    """
    шаблон = ШАБЛОН.read_text(encoding="utf-8")
    начало = шаблон.index("/*ДАННЫЕ*/")
    конец = шаблон.index("/*КОНЕЦ*/") + len("/*КОНЕЦ*/")
    данные = {
        "scale.json": шкала_данные,
        "kb.json": база,
        "survey.json": анкета,
    }
    вшито = json.dumps(данные, ensure_ascii=False, separators=(",", ":"))
    СТРАНИЦА.write_text(шаблон[:начало] + вшито + шаблон[конец:], encoding="utf-8")
    print(f"app.html:    {СТРАНИЦА.stat().st_size / 1024:.0f} КБ, данные внутри")


if __name__ == "__main__":
    raise SystemExit(main())
