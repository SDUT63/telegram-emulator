def фраза(попытка: int, где: str = ВОПРОС, *, пропуск: bool = True) -> str:
    """Что сказать на N-е подряд непонимание.

    Попытки считаются с единицы. Меньше единицы не бывает, больше длины
    лесенки — сколько угодно: дальше повторяется последняя ступень.
    Это и значит «бот не молчит»: ответ есть на любой попытке.

    `пропуск` — можно ли пропустить вопрос, на котором человек застрял.
    Нельзя — значит, и предлагать это не будем.
    """
    лесенка = ЛЕСЕНКИ.get(где) or ПО_ВОПРОСУ
    номер = min(max(1, int(попытка or 1)), len(лесенка))
    if где == АНКЕТА and not пропуск and номер in ПО_АНКЕТЕ_БЕЗ_ПРОПУСКА:
        return ПО_АНКЕТЕ_БЕЗ_ПРОПУСКА[номер]
    return лесенка[номер - 1]


def ступеней(где: str = ВОПРОС) -> int:
    """Сколько разных фраз есть для этого места разговора."""
    return len(ЛЕСЕНКИ.get(где) or ПО_ВОПРОСУ)


