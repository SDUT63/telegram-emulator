#!/usr/bin/env python3
"""Можно ли запускать бота в работу и давать рекламу.

Зачем отдельно от diagnose.py
-----------------------------
`diagnose.py` отвечает на вопрос «почему бот не подключается». Этот
модуль отвечает на другой: «всё ли на месте, чтобы включить бота
круглосуточно и позвать людей». Это разные вопросы. Бот, который
прекрасно подключается, может при этом работать без резервных копий,
с паролем оператора «123» и без единой применённой миграции.

Реклама делает цену ошибки другой. Пока бота знают пять человек, беду
замечают и чинят руками. Когда по объявлению приходит сотня семей, никто
не заметит, что карточки не сохраняются, — их просто не будет, а люди
будут думать, что им не ответили.

Как читать
----------
Три уровня, и они значат ровно то, что написано:

    НЕЛЬЗЯ   запускать нельзя: данные будут теряться или утекать;
    ВНИМАНИЕ запускать можно, но это надо закрыть в ближайшие дни;
    ГОТОВО   проверено.

Запуск:
    python preflight.py
"""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

НЕЛЬЗЯ = "НЕЛЬЗЯ"
ВНИМАНИЕ = "ВНИМАНИЕ"
ГОТОВО = "ГОТОВО"

ЗДЕСЬ = Path(__file__).resolve().parent


@dataclass(frozen=True)
class Итог:
    уровень: str
    что: str
    подробность: str = ""
    делать: str = ""


# --------------------------------------------------------------- проверки


def токен_max() -> Итог:
    try:
        import max_config

        токен = max_config.read_token(ЗДЕСЬ)
    # read_token не возвращает пустую строку, а поднимает SystemExit —
    # чтобы пустой токен никогда не ушёл в MAX. Здесь это не выход
    # из программы, а одна строка отчёта: остальные проверки должны
    # отработать и сказать, что ещё не готово.
    except SystemExit as ошибка:
        return Итог(НЕЛЬЗЯ, "Токен MAX", str(ошибка),
                    "Положите токен в token.txt рядом с ботом "
                    "или задайте MAX_BOT_TOKEN.")
    except Exception as ошибка:
        return Итог(НЕЛЬЗЯ, "Токен MAX", f"{type(ошибка).__name__}: {ошибка}",
                    "Положите токен в token.txt рядом с ботом.")
    if len(токен) < 20:
        return Итог(НЕЛЬЗЯ, "Токен MAX", "подозрительно короткий",
                    "Проверьте, что скопирован весь токен целиком.")
    return Итог(ГОТОВО, "Токен MAX", f"{len(токен)} знаков")


def хранилище() -> Итог:
    """Круглосуточная работа — это PostgreSQL, а не файл рядом с ботом.

    Файловое хранилище задумано для ноутбука и не переживает двух
    процессов сразу: при перезапуске воркера или второй копии бота
    ответы начнут затирать друг друга.
    """
    адрес = (os.getenv("SDUT_DATABASE_URL") or "").strip()
    if not адрес:
        return Итог(НЕЛЬЗЯ, "База данных", "SDUT_DATABASE_URL не задан",
                    "Круглосуточно бот работает на PostgreSQL. "
                    "См. ЗАПУСК_БОТА.md.")
    try:
        import psycopg

        with psycopg.connect(адрес) as conn:
            conn.execute("SELECT 1").fetchone()
    except Exception as ошибка:
        return Итог(НЕЛЬЗЯ, "База данных", f"{type(ошибка).__name__}: {ошибка}",
                    "Бот не сохранит ни одного ответа. Проверьте адрес и то, "
                    "что PostgreSQL запущен.")
    return Итог(ГОТОВО, "База данных", "PostgreSQL отвечает")


def миграции() -> Итог:
    if not (os.getenv("SDUT_DATABASE_URL") or "").strip():
        return Итог(ВНИМАНИЕ, "Миграции", "нечего проверять без базы")
    try:
        import postgres_guard

        postgres_guard.require_migrations()
    except Exception as ошибка:
        return Итог(НЕЛЬЗЯ, "Миграции", str(ошибка),
                    "Примените миграции до запуска: бот остановится сам, "
                    "но лучше не при живых людях.")
    return Итог(ГОТОВО, "Миграции", "все применены и совпадают по отпечатку")


def операторы() -> Итог:
    """CRM без старшего — это CRM, где никто не отменит ложный звонок."""
    try:
        import crm_store as store

        все = store.load_operators()
    except Exception as ошибка:
        return Итог(ВНИМАНИЕ, "Операторы CRM", str(ошибка))
    if not все:
        return Итог(НЕЛЬЗЯ, "Операторы CRM", "не заведён ни один",
                    "Пока операторов нет, обращения читать некому.")

    роли = {логин: (запись or {}).get("role", "operator") for логин, запись in все.items()}
    старшие = [л for л, р in роли.items() if р in ("supervisor", "admin")]
    if not старшие:
        return Итог(ВНИМАНИЕ, "Операторы CRM",
                    f"{len(все)} операторов, ни одного старшего",
                    "Отмена контрольного звонка требует роли supervisor — "
                    "сейчас её сделать некому.")

    слабые = [л for л in все if store.check_password("123456", все[л].get("password", ""))
              or store.check_password("password", все[л].get("password", ""))]
    if слабые:
        return Итог(НЕЛЬЗЯ, "Операторы CRM",
                    f"пароль по умолчанию у: {', '.join(sorted(слабые))}",
                    "В CRM лежат персональные данные. Смените пароли.")
    return Итог(ГОТОВО, "Операторы CRM",
                f"{len(все)}, из них старших {len(старшие)}")


def резервные_копии() -> Итог:
    путь = (os.getenv("SDUT_BACKUP_PASSPHRASE_FILE") or "").strip()
    if not путь:
        return Итог(НЕЛЬЗЯ, "Резервные копии",
                    "SDUT_BACKUP_PASSPHRASE_FILE не задан",
                    "Без ключа шифрования ops/backup_postgres.sh не запустится, "
                    "а без копий одна ошибка стирает работу всей службы.")
    файл = Path(путь)
    if not файл.is_file() or not os.access(файл, os.R_OK):
        return Итог(НЕЛЬЗЯ, "Резервные копии", f"файл ключа не читается: {путь}")
    if файл.stat().st_size == 0:
        return Итог(НЕЛЬЗЯ, "Резервные копии", "файл ключа пуст")
    режим = файл.stat().st_mode & 0o077
    if режим:
        return Итог(ВНИМАНИЕ, "Резервные копии",
                    f"ключ читают посторонние (права {oct(файл.stat().st_mode & 0o777)})",
                    "chmod 600 на файл с ключом.")
    return Итог(ГОТОВО, "Резервные копии", "ключ шифрования на месте")


def карточки_видны_координатору() -> Итог:
    """Бот пишет в одно хранилище, CRM читает то же самое.

    Пока они расходились, координатор видел ноль обращений при полной
    базе — молча, без всякой ошибки. Проверка смотрит не на настройку,
    а на то, что CRM действительно достаёт: сколько карточек и сколько
    из них с телефоном, по которому можно звонить.
    """
    try:
        import storage

        где = storage.где_данные()
        анкета = storage.открыть()
        начато, закончено = анкета.stats()
        с_телефоном = sum(
            1 for к in (анкета.state or {}).values()
            if isinstance(к, dict) and (к.get("answers") or {}).get("phone")
        )
    except Exception as ошибка:
        return Итог(НЕЛЬЗЯ, "Карточки видны координатору",
                    f"{type(ошибка).__name__}: {ошибка}",
                    "CRM не сможет открыть хранилище бота.")

    if где == "файл" and адрес_базы_задан():
        return Итог(НЕЛЬЗЯ, "Карточки видны координатору",
                    "бот на PostgreSQL, а читается файл",
                    "Координатор увидит ноль обращений при полной базе.")
    подробность = f"хранилище {где}: обращений {начато}, с телефоном {с_телефоном}"
    if начато and not с_телефоном:
        return Итог(ВНИМАНИЕ, "Карточки видны координатору", подробность,
                    "Ни одного телефона — звонить некуда. Посмотрите воронку: "
                    "python funnel.py")
    return Итог(ГОТОВО, "Карточки видны координатору", подробность)


def адрес_базы_задан() -> bool:
    return bool((os.getenv("SDUT_DATABASE_URL") or "").strip())


def очередь_исходящих() -> Итог:
    """Строка со статусом dead — это сообщение, которое человек не получил."""
    if not (os.getenv("SDUT_DATABASE_URL") or "").strip():
        return Итог(ВНИМАНИЕ, "Очередь исходящих", "нечего проверять без базы")
    try:
        from outbox_postgres import PostgresOutbox

        числа = PostgresOutbox().stats()
    except Exception as ошибка:
        return Итог(ВНИМАНИЕ, "Очередь исходящих", str(ошибка))
    мёртвых = int(числа.get("dead") or 0)
    if мёртвых:
        return Итог(ВНИМАНИЕ, "Очередь исходящих", f"{мёртвых} не доставлено",
                    "Это люди, которым бот не ответил. Посмотрите last_error "
                    "в outbox_messages.")
    ждут = int(числа.get("pending") or 0)
    return Итог(ГОТОВО, "Очередь исходящих", f"в работе {ждут}, потерянных нет")


def угрозы_жизни() -> Итог:
    """Самое дорогое место: проверяем не код, а поведение."""
    try:
        import emergency
    except Exception as ошибка:
        return Итог(НЕЛЬЗЯ, "Распознавание угрозы жизни", str(ошибка))

    обязаны_сработать = ("он не дышит", "мама без сознания", "поперхнулся кашей",
                         "кровь не останавливается", "не хочу жить")
    обязаны_молчать = ("муж лежит после инсульта", "болит спина по утрам",
                       "хочу узнать про уход")

    пропущено = [ф for ф in обязаны_сработать if emergency.распознать(ф) is None]
    ложные = [ф for ф in обязаны_молчать if emergency.распознать(ф) is not None]
    if пропущено:
        return Итог(НЕЛЬЗЯ, "Распознавание угрозы жизни",
                    f"не распознано: {пропущено}",
                    "Бот промолчит там, где надо назвать 103.")
    if ложные:
        return Итог(ВНИМАНИЕ, "Распознавание угрозы жизни",
                    f"ложная тревога на: {ложные}",
                    "Бот, кричащий «103» на каждое второе обращение, "
                    "перестаёт быть слышимым.")
    return Итог(ГОТОВО, "Распознавание угрозы жизни",
                "эталонные фразы разбираются верно")


def анкета_проходится() -> Итог:
    """Анкета целиком, живой речью, в отдельной папке — ответы не тронуты."""
    import tempfile

    try:
        from chatbot_survey import Survey

        sys.path.insert(0, str(ЗДЕСЬ / "tests"))
        from test_cold_traffic import ЖИВАЯ_РЕЧЬ

        with tempfile.TemporaryDirectory() as папка:
            анкета = Survey(storage_path=os.path.join(папка, "p.json"),
                            list_options=False)
            анкета.handle("preflight", "здравствуйте")
            анкета.grant_consent("preflight")
            непонятое = []
            for _ in range(60):
                место = анкета.current("preflight")
                if место is None:
                    break
                ид = место[1]["id"]
                анкета.handle("preflight", ЖИВАЯ_РЕЧЬ[ид])
                ещё = анкета.current("preflight")
                if ещё and ещё[1]["id"] == ид:
                    непонятое.append(ид)
                    анкета.answer_by_numbers("preflight", [1])
            готово = bool((анкета.state.get("preflight") or {}).get("finished"))
    except Exception as ошибка:
        return Итог(ВНИМАНИЕ, "Анкета живой речью",
                    f"{type(ошибка).__name__}: {ошибка}")

    if not готово:
        return Итог(НЕЛЬЗЯ, "Анкета живой речью", "не доходит до конца")
    if непонятое:
        return Итог(ВНИМАНИЕ, "Анкета живой речью",
                    f"не понял своими словами: {непонятое}",
                    "Человек упрётся в эти вопросы. См. СИНОНИМЫ "
                    "в survey_questions.py.")
    return Итог(ГОТОВО, "Анкета живой речью", "проходится целиком")


def метрики_наружу() -> Итог:
    есть_токен = bool((os.getenv("SDUT_METRICS_TOKEN") or "").strip())
    if не_только_локально() and not есть_токен:
        return Итог(ВНИМАНИЕ, "Доступ к /metrics",
                    "слушаем не только этот компьютер, а токена нет",
                    "Задайте SDUT_METRICS_TOKEN.")
    return Итог(ГОТОВО, "Доступ к /metrics",
                "закрыт токеном" if есть_токен else "доступен только локально")


def не_только_локально() -> bool:
    for имя in ("MAX_WEBHOOK_HOST", "CRM_HOST"):
        адрес = (os.getenv(имя) or "").strip()
        if адрес and адрес not in ("127.0.0.1", "localhost", "::1"):
            return True
    return False


def crm_наружу() -> Итог:
    адрес = (os.getenv("CRM_HOST") or "127.0.0.1").strip()
    if адрес in ("127.0.0.1", "localhost", "::1"):
        return Итог(ГОТОВО, "Доступ к CRM", "только с этого компьютера")
    return Итог(ВНИМАНИЕ, "Доступ к CRM", f"слушает {адрес}",
                "В CRM лежат имена, телефоны и адреса. Открывать её в сеть "
                "можно только за HTTPS и с разговором о том, кто получит доступ.")


ПРОВЕРКИ: tuple[Callable[[], Итог], ...] = (
    токен_max,
    хранилище,
    миграции,
    операторы,
    карточки_видны_координатору,
    резервные_копии,
    очередь_исходящих,
    угрозы_жизни,
    анкета_проходится,
    метрики_наружу,
    crm_наружу,
)


def проверить() -> list[Итог]:
    итоги = []
    for проверка in ПРОВЕРКИ:
        try:
            итоги.append(проверка())
        # SystemExit не наследует Exception: без него одна упавшая
        # проверка обрывала бы весь отчёт, и остальное осталось бы
        # непроверенным именно тогда, когда проверять важнее всего.
        except (Exception, SystemExit) as ошибка:          # pragma: no cover
            итоги.append(Итог(ВНИМАНИЕ, проверка.__name__,
                              f"проверка не отработала: {ошибка!r}"))
    return итоги


def отчёт(итоги: list[Итог]) -> str:
    знак = {ГОТОВО: "  ok  ", ВНИМАНИЕ: " !    ", НЕЛЬЗЯ: " СТОП "}
    ширина = max(len(и.что) for и in итоги)
    строки = ["Готовность к работе", ""]
    for и in итоги:
        строки.append(f"[{знак[и.уровень]}] {и.что:<{ширина}}  {и.подробность}")
        if и.делать:
            строки.append(f"{'':>{ширина + 11}}{и.делать}")
    нельзя = [и for и in итоги if и.уровень == НЕЛЬЗЯ]
    внимание = [и for и in итоги if и.уровень == ВНИМАНИЕ]
    строки.append("")
    if нельзя:
        строки.append(f"Запускать нельзя: не закрыто {len(нельзя)}.")
    elif внимание:
        строки.append(f"Запускать можно. Осталось закрыть в ближайшие дни: {len(внимание)}.")
    else:
        строки.append("Всё проверено. Можно включать круглосуточно.")
    return "\n".join(строки)


def main() -> int:
    итоги = проверить()
    print(отчёт(итоги))
    return 1 if any(и.уровень == НЕЛЬЗЯ for и in итоги) else 0


if __name__ == "__main__":                                  # pragma: no cover
    raise SystemExit(main())
