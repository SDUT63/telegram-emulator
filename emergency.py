#!/usr/bin/env python3
"""Распознавание угрозы жизни в сообщении человека.

Почему это отдельный модуль
---------------------------
Здесь единственная логика в системе, где ошибка стоит жизни, а не неудобства.
Она должна читаться целиком, проверяться отдельно от анкеты и срабатывать
раньше всего остального — раньше согласия, раньше разбора ответа, раньше
базы знаний. Человек, у которого кто-то не дышит, не должен получить
«Напишите номер ответа — от 1 до 3».

Полнота важнее точности
-----------------------
Ложное срабатывание стоит одной лишней строки «если это прямо сейчас —
звоните 103». Пропуск стоит несоизмеримо больше. Поэтому признаки заданы
широко, а текст ответа сформулирован так, что он уместен и когда тревога
ложная: он не утверждает, что беда происходит, он говорит, что делать,
если происходит.

Чего здесь нет
--------------
Здесь нет медицинских советов и нет попытки оценить тяжесть. Бот не врач.
Единственное, что он делает, — называет номер и не мешает.
"""
