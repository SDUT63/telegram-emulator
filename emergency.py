@dataclass(frozen=True)
class Тревога:
    """Что распознали и что на это ответить."""

    вид: str          # "скорая" | "поддержка"
    признак: str      # какая основа сработала — для записи оператору
    ответ: str

    @property
    def пометка(self) -> str:
        """Строка для alerts: оператор видит её в CRM как ⚠."""
        return f"Угроза жизни: {self.признак}"


_ПРОБЕЛЫ = re.compile(r"\s+")


def _нормализовать(текст: str) -> str:
    """Привести к виду, в котором сравнение устойчиво к написанию.

    Человек в панике пишет капсом, без запятых, через «ё» и не через «ё»,
    с лишними пробелами. Всё это не должно мешать распознаванию.
    """
    низ = (текст or "").lower().replace("ё", "е")
    низ = re.sub(r"[^\w\s-]+", " ", низ, flags=re.UNICODE)
    return _ПРОБЕЛЫ.sub(" ", низ).strip()


def _найти(текст: str, основы: tuple[str, ...]) -> str | None:
    for основа in основы:
        if _нормализовать(основа) in текст:
            return основа
    return None


def распознать(текст: str, варианты: tuple[str, ...] | list[str] | None = None) -> Тревога | None:
    """Вернуть тревогу, если в сообщении есть признак угрозы жизни.

    `варианты` — подписи кнопок текущего вопроса анкеты. Если человек написал
    ровно то, что написано на кнопке, он отвечает на вопрос, а не зовёт на
    помощь: вопрос о тревожных признаках сам содержит слова «Тяжело дышит» и
    «Боль». Перехватывать такой ответ значит не дать его записать.

    Порядок важен: риск суицида проверяется первым, потому что ответ на него
    отличается и не должен подменяться общим «звоните 103».
    """
    нормализованный = _нормализовать(текст)
    if not нормализованный:
        return None

    for вариант in варианты or ():
        if _нормализовать(вариант) == нормализованный:
            return None

    признак = _найти(нормализованный, СУИЦИД)
    if признак:
        return Тревога(вид="поддержка", признак=признак, ответ=ПОДДЕРЖКА)

    признак = _найти(нормализованный, ОПАСНОЕ_ПОВЕДЕНИЕ)
    if признак:
        return Тревога(вид="скорая", признак=признак, ответ=СКОРАЯ)

    признак = _найти(нормализованный, МЕДИЦИНСКИЕ)
    if признак:
        return Тревога(вид="скорая", признак=признак, ответ=СКОРАЯ)
    return None


