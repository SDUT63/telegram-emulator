def из_анкеты(answers: dict[str, str]) -> dict[str, str]:
    """Грубо заполнить шкалу ответами действующей анкеты.

    Возвращает только то, что удалось сопоставить. Остальные позиции
    остаются незаполненными — и шкала честно считается неполной.
    """
    вышло: dict[str, str] = {}
    for позиция, вопрос in ОТКУДА.items():
        ответ = (answers or {}).get(вопрос, "")
        градация = СООТВЕТСТВИЕ.get(позиция, {}).get(ответ)
        if градация:
            вышло[позиция] = градация
    return вышло


def покрытие() -> dict[str, object]:
    """Насколько действующая анкета закрывает шкалу приказа."""
    закрыто = sorted(ОТКУДА)
    не_закрыто = [i.id for i in SCALE if i.id not in ОТКУДА]
    # Один вопрос анкеты на две позиции шкалы — разделить его ответ нельзя
    слипшиеся = [в for в in set(ОТКУДА.values())
                 if list(ОТКУДА.values()).count(в) > 1]
    добираемо = sum(BY_ID[i].full for i in закрыто)
    return {
        "закрыто": len(закрыто),
        "всего": len(SCALE),
        "не_закрыто": tuple(не_закрыто),
        "слипшиеся_вопросы": tuple(sorted(слипшиеся)),
        "максимум_по_анкете": round(добираемо, 1),
        "максимум_по_шкале": MAX_SCORE,
        "достижимый_уровень": level_for(добираемо)[1],
    }


