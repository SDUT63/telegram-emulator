# Объём социального пакета по уровням (пп. 43–45 Типовой модели), часов в неделю.
PACKAGE_HOURS = {1: (11, 14), 2: (18, 21), 3: (25, 28), 0: (0, 0)}


def level_for(total: float) -> tuple[int, str]:
    for low, high, num, name in LEVELS:
        if total >= low:
            return num, name
    return 0, LEVELS[-1][3]


@dataclass
class Result:
    total: float
    answered: int
    missing: tuple[str, ...]
    complete: bool
    level: int | None
    level_name: str
    note: str

    @property
    def package_hours(self) -> tuple[int, int]:
        return PACKAGE_HOURS.get(self.level or 0, (0, 0))


PRELIMINARY = (
    "Предварительно, со слов заявителя. Уровень нуждаемости устанавливают "
    "два эксперта по оценке нуждаемости очно и одновременно "
    "(п. 2 приложения № 1 к Типовой модели, Приказ № 731)."
)
INCOMPLETE = (
    "Шкала заполнена не полностью, сумма баллов не считается. "
    "Недостающие позиции уточняет координатор."
)


def score(answers: dict[str, str]) -> Result:
    """Считает предварительную сумму баллов по 21 позиции шкалы.

    Неполная шкала не даёт ни суммы, ни уровня: частичный подсчёт создал бы
    заниженный уровень, а он влияет на объём социального пакета.
    """
    missing = tuple(i.id for i in SCALE
                    if answers.get(i.id, UNKNOWN) not in (CAN, PARTLY, CANNOT))
    answered = len(SCALE) - len(missing)
    if missing:
        return Result(0.0, answered, missing, False, None, "", INCOMPLETE)
    total = round(sum(BY_ID[k].score(v) for k, v in answers.items() if k in BY_ID), 1)
    num, name = level_for(total)
    return Result(total, answered, (), True, num, name, PRELIMINARY)


def explain(answers: dict[str, str]) -> list[tuple[str, str, float]]:
    """Построчная расшифровка для координатора: позиция, ответ, баллы."""
    out = []
    for item in SCALE:
        grade = answers.get(item.id, UNKNOWN)
        out.append((item.official, grade, item.score(grade)))
    return out


