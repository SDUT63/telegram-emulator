#!/usr/bin/env python3
"""Из чего складывается час ухода. Отсюда берутся цены прайса.

Зачем отдельный модуль. Присланный прайс был набором цифр: цены
проставлены, а проверить их нечем. Пересчёт показал, что цифры
не сходятся — часовой визит стоил втрое дороже себестоимости,
а смены и сутки продавались ниже неё. Так бывает, когда цену
назначают, а не выводят.

Здесь цена выводится. Меняется ставка помощника или объём службы —
меняются все цены разом, и ни одна не может оказаться ниже
себестоимости: это сторожит tests/test_economics.py.

Что учтено и почему.

  Труд.  Помощник работает по трудовому договору, значит служба
         платит не только за час у подопечного. Дорога между
         адресами — рабочее время (ст. 91 ТК РФ). Отпуск 28
         календарных дней и первые три дня больничного тоже
         оплачивает работодатель — это ещё десятая часть фонда.
         Ночные часы — не меньше чем в полуторном... нет, не меньше
         чем на 20 % дороже (ст. 154 ТК РФ и постановление
         Правительства РФ № 554).

  Взносы. 7,6 % — единый пониженный тариф для НКО на УСН,
         фактически ведущих деятельность в области социального
         обслуживания населения (пп. 7 п. 1 и п. 2.2 ст. 427 НК РФ,
         действует по 2026 год включительно). Льгота привязана
         к фактической деятельности, а не к коду ОКВЭД.

  Накладные.  Организатор ухода, бухгалтерия, связь, офис, банк —
         это постоянные расходы, и они не зависят от того, сколько
         часов служба продала. Разделённые на часы, они и решают,
         сходится прайс или нет: при шестистах часах в месяц
         накладные съедают 151 ₽ с каждого часа, при двух тысячах —
         45 ₽. Именно этого в присланном расчёте не было совсем.

  Уставные источники.  АНО вправе вести приносящую доход
         деятельность в рамках устава, и платные услуги — законный
         источник наравне с грантами и пожертвованиями. Но
         накладные расходы платные услуги несут не целиком:
         часть закрывают гранты и целевые поступления. Доля
         задана явно (ДОЛЯ_НАКЛАДНЫХ) — чтобы было видно, сколько
         службе нужно привлечь помимо выручки.

  УСН 6 % считается от цены, а не от себестоимости, поэтому в цену
         входит делением, а не прибавкой.

Прибыли в привычном смысле у АНО нет: заложенная рентабельность —
это резерв на замену заболевшего помощника, кассовый разрыв и
обучение. Без неё первая же болезнь помощника срывает уход.
"""

from __future__ import annotations

from dataclasses import dataclass

# ------------------------------------------------------------- вводные

МРОТ = 27_093                 # с 01.01.2026
НОРМА_ЧАСОВ = 164.3           # среднемесячная при 40-часовой неделе
ВЗНОСЫ = 0.076                # пп. 7 п. 1 и п. 2.2 ст. 427 НК РФ
УСН = 0.06                    # «доходы»
НДФЛ = 0.13                   # удерживается у работника, в расход не идёт

РЕЗЕРВ_ОТПУСКОВ = 0.10        # 28 к. д. отпуска + первые 3 дня больничного
НОЧНОЙ_КОЭФФИЦИЕНТ = 1.2      # ст. 154 ТК РФ
НОЧЬ_С, НОЧЬ_ДО = 22, 6       # ночное время по ст. 96 ТК РФ

СТАВКА_ПОМОЩНИКА = 200        # ₽ за час рабочего времени
СТАВКА_ОРГАНИЗАТОРА = 350     # ₽ за час рабочего времени
ДОРОГА = 0.5                  # ч на один выезд
РАСХОДНИКИ = 12               # ₽ на час у подопечного: перчатки, антисептик

# Постоянные расходы службы в месяц.
ПОСТОЯННЫЕ = {
    "организатор ухода": 68_000,   # ставка с взносами и резервом отпуска
    "бухгалтерия": 8_000,
    "связь, хостинг, CRM": 3_000,
    "помещение": 10_000,
    "банк и прочее": 1_500,
}

ОБЪЁМ = 1_320                 # оплачиваемых часов в месяц, целевой
ДОЛЯ_НАКЛАДНЫХ = 0.70         # сколько накладных несут платные услуги
РЕНТАБЕЛЬНОСТЬ = 0.10         # резерв на замены и кассовый разрыв


@dataclass(frozen=True)
class Расчёт:
    """Из чего сложился час у подопечного."""

    труд: float
    расходники: float
    накладные: float
    себестоимость: float
    рентабельность: float
    налог: float
    цена: float

    def как_строки(self) -> list[tuple[str, float]]:
        return [
            ("Труд помощника с взносами, отпуском и дорогой", self.труд),
            ("Расходники и средства защиты", self.расходники),
            ("Организатор ухода, бухгалтерия, связь, помещение", self.накладные),
            ("Резерв на замену и кассовый разрыв", self.рентабельность),
            ("Налог УСН", self.налог),
        ]


def минимальная_ставка() -> float:
    """Ниже этого часовая ставка нарушает ТК: полная занятость
    должна давать не меньше МРОТ."""
    return МРОТ / НОРМА_ЧАСОВ


def заработок(ставка: float = СТАВКА_ПОМОЩНИКА) -> tuple[int, int]:
    """Сколько выходит у помощника при полной занятости: до НДФЛ и на руки."""
    начислено = ставка * НОРМА_ЧАСОВ
    return round(начислено), round(начислено * (1 - НДФЛ))


def постоянные_в_месяц() -> int:
    return sum(ПОСТОЯННЫЕ.values())


def накладные_на_час(объём: float = ОБЪЁМ,
                     доля: float = ДОЛЯ_НАКЛАДНЫХ) -> float:
    """Постоянные расходы, приходящиеся на один оплачиваемый час.

    Главная цифра всего расчёта. Объём меняет её втрое, и именно
    поэтому прайс нельзя составить, не решив, на какой объём
    служба рассчитывает.
    """
    if объём <= 0:
        raise ValueError("объём должен быть больше нуля")
    return постоянные_в_месяц() * доля / объём


def труд_на_час(блок: float, *, ночных: float = 0.0, дорога: float = ДОРОГА,
                ставка: float = СТАВКА_ПОМОЩНИКА) -> float:
    """Себестоимость труда на один час у подопечного.

    Дорога размазывается по длине блока: у часового визита она
    добавляет половину часа к одному, у двенадцатичасовой смены —
    к двенадцати. Отсюда и вся разница в цене часа.
    """
    if блок <= 0:
        raise ValueError("блок должен быть больше нуля")
    if ночных > блок:
        raise ValueError("ночных часов больше, чем длина блока")
    рабочее = 1 + дорога / блок
    ночной = (ночных * НОЧНОЙ_КОЭФФИЦИЕНТ + (блок - ночных)) / блок
    return ставка * рабочее * (1 + РЕЗЕРВ_ОТПУСКОВ) * (1 + ВЗНОСЫ) * ночной


def час(блок: float, *, ночных: float = 0.0, дорога: float = ДОРОГА,
        ставка: float = СТАВКА_ПОМОЩНИКА, объём: float = ОБЪЁМ,
        рентабельность: float = РЕНТАБЕЛЬНОСТЬ) -> Расчёт:
    """Полный расчёт часа у подопечного — от труда до цены."""
    т = труд_на_час(блок, ночных=ночных, дорога=дорога, ставка=ставка)
    н = накладные_на_час(объём)
    себестоимость = т + РАСХОДНИКИ + н
    без_налога = себестоимость / (1 - рентабельность)
    цена = без_налога / (1 - УСН)
    return Расчёт(
        труд=т, расходники=float(РАСХОДНИКИ), накладные=н,
        себестоимость=себестоимость,
        рентабельность=без_налога - себестоимость,
        налог=цена - без_налога,
        цена=цена,
    )


def услуга(блок: float, **прочее) -> Расчёт:
    """То же, но за услугу целиком, а не за час."""
    за_час = час(блок, **прочее)
    return Расчёт(*(значение * блок for значение in (
        за_час.труд, за_час.расходники, за_час.накладные,
        за_час.себестоимость, за_час.рентабельность, за_час.налог,
        за_час.цена)))


def безубыточность(средняя_цена_часа: float,
                   доля: float = ДОЛЯ_НАКЛАДНЫХ) -> float:
    """Сколько оплачиваемых часов в месяц нужно, чтобы выйти в ноль.

    Считается по прямым расходам: каждый проданный час приносит
    разницу между ценой и прямыми расходами, и эта разница должна
    покрыть постоянные.
    """
    прямые = труд_на_час(3) + РАСХОДНИКИ          # средний блок — три часа
    вклад = средняя_цена_часа * (1 - УСН) - прямые
    if вклад <= 0:
        raise ValueError("цена не покрывает даже прямых расходов")
    return постоянные_в_месяц() * доля / вклад
