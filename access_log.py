#!/usr/bin/env python3
"""Журнал доступа к персональным данным.

Зачем
-----
Статья 19 ФЗ-152 требует от оператора учёта тех, кто имеет доступ
к персональным данным, и обнаружения фактов несанкционированного
доступа. Без журнала нельзя ответить на простой вопрос: кто выгрузил
базу обращений в прошлый вторник. А выгрузка — это все имена, телефоны,
адреса и сведения о здоровье разом, в файле, который потом живёт своей
жизнью.

Права в CRM проверялись и раньше, но проверка отвечает на вопрос
«можно ли», а журнал — на вопрос «кто и когда». Это разные вопросы,
и второй возникает уже после беды.

Что записывается
----------------
Кто (логин и роль), когда, что сделал и с чьим обращением. Ничего
больше: ни имени человека, ни телефона, ни ответов, ни текста заметки.
Журнал, в котором лежат сами данные, — это вторая копия базы, и
защищать её пришлось бы наравне с первой.

Идентификатор обращения записывается: без него нельзя выяснить, чьи
именно данные смотрели. Он же делает журнал персональными данными,
поэтому у журнала свой срок хранения и своя чистка.

Куда
----
Отдельный файл, по строке JSON на событие, дозаписью. Дозапись важна:
журнал, который можно переписать целиком, не журнал. Строки ротуются
по размеру, чтобы файл не рос без предела.
"""

from __future__ import annotations

import json
import os
import threading
from datetime import datetime
from typing import Any

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ЖУРНАЛ = os.path.join(ЗДЕСЬ, "access.log")

# Когда файл перерастает предел, он становится access.log.1, а записи
# идут в новый. Старше — удаляется: журнал тоже персональные данные,
# и хранить его вечно нельзя ровно по тем же причинам, что и анкеты.
ПРЕДЕЛ_БАЙТ = 5 * 1024 * 1024

_замок = threading.Lock()


def записать(*, кто: str, роль: str, действие: str,
             обращение: str | None = None, ещё: dict[str, Any] | None = None) -> None:
    """Отметить обращение оператора к персональным данным.

    Ошибка записи не должна ронять работу координатора: человек ждёт
    ответа, и отказать ему из-за журнала хуже, чем не записать строку.
    Но и молчать нельзя — поэтому беда уходит в обычный лог.
    """
    запись = {
        "ts": datetime.now().isoformat(timespec="seconds"),
        "кто": str(кто or "?"),
        "роль": str(роль or "?"),
        "действие": str(действие),
    }
    if обращение:
        запись["обращение"] = str(обращение)
    if ещё:
        # Только числа и короткие пометки: «сколько записей выгружено»,
        # «какой статус поставлен». Персональные данные сюда не кладём.
        запись.update({к: v for к, v in ещё.items() if isinstance(v, (int, bool, str))})

    строка = json.dumps(запись, ensure_ascii=False, separators=(",", ":"))
    try:
        with _замок:
            _повернуть_если_велик()
            with open(ЖУРНАЛ, "a", encoding="utf-8") as файл:
                файл.write(строка + "\n")
    except OSError as ошибка:                               # pragma: no cover
        import logging

        logging.getLogger(__name__).warning(
            "Не удалось записать журнал доступа: %s", type(ошибка).__name__)


def _повернуть_если_велик() -> None:
    try:
        велик = os.path.getsize(ЖУРНАЛ) >= ПРЕДЕЛ_БАЙТ
    except OSError:
        return
    if not велик:
        return
    старый = ЖУРНАЛ + ".1"
    try:
        if os.path.exists(старый):
            os.remove(старый)
        os.replace(ЖУРНАЛ, старый)
    except OSError:                                         # pragma: no cover
        pass


def прочитать(предел: int = 200) -> list[dict[str, Any]]:
    """Последние записи, свежие снизу. Для разбора инцидента."""
    try:
        with open(ЖУРНАЛ, encoding="utf-8") as файл:
            строки = файл.readlines()
    except OSError:
        return []
    итог = []
    for строка in строки[-предел:]:
        try:
            итог.append(json.loads(строка))
        except ValueError:
            continue
    return итог


__all__ = ["записать", "прочитать", "ЖУРНАЛ"]
