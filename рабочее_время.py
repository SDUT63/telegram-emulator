#!/usr/bin/env python3
"""Рабочее время службы и внутренние сроки по уровню сигнала (К5, Р2).

Сроки здесь — цели для задачи координатора и сортировки в CRM, а не
обещание человеку: людям срок связи не называется нигде (решение 3).
Обещанием они станут, когда директор подтвердит, что их держит штат.

Рабочее время — пн–пт, 9:00–18:00 по Самаре (UTC+4, без перехода на
летнее время). Праздники пока не учитываются: производственного
календаря в системе нет — это известное ограничение, срок в праздник
координатор видит как просроченный.
"""
from __future__ import annotations

from datetime import datetime, time, timedelta

from cases import SAMARA

НАЧАЛО = time(9, 0)
КОНЕЦ = time(18, 0)
РАБОЧИЕ_ДНИ = frozenset({0, 1, 2, 3, 4})       # пн–пт


def _рабочий_день(день: datetime) -> bool:
    return день.weekday() in РАБОЧИЕ_ДНИ


def _следующий_рабочий_день(момент: datetime) -> datetime:
    день = (момент + timedelta(days=1)).replace(hour=НАЧАЛО.hour, minute=0, second=0, microsecond=0)
    while not _рабочий_день(день):
        день += timedelta(days=1)
    return день


def в_рабочее_время(момент: datetime) -> bool:
    местное = момент.astimezone(SAMARA)
    return _рабочий_день(местное) and НАЧАЛО <= местное.time() < КОНЕЦ


def _конец_дня(день: datetime) -> datetime:
    return день.replace(hour=КОНЕЦ.hour, minute=0, second=0, microsecond=0)


def срок(уровень: str, сейчас: datetime) -> datetime:
    """Срок задачи `safety_contact` по уровню: P0, P1, P2 (К5)."""
    местное = сейчас.astimezone(SAMARA)
    if в_рабочее_время(местное):
        начало_окна = местное
    else:
        сегодня_до_начала = _рабочий_день(местное) and местное.time() < НАЧАЛО
        начало_окна = (местное.replace(hour=НАЧАЛО.hour, minute=0, second=0, microsecond=0)
                       if сегодня_до_начала else _следующий_рабочий_день(местное))
    if уровень == "P0":
        # Как можно раньше в тот же рабочий день: час, но не позже конца дня.
        return min(начало_окна + timedelta(hours=1), _конец_дня(начало_окна))
    if уровень == "P1":
        return _конец_дня(начало_окна)
    # P2 и ниже — до конца следующего рабочего дня.
    return _конец_дня(_следующий_рабочий_день(начало_окна))


__all__ = ["срок", "в_рабочее_время"]
