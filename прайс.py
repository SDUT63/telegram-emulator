def _пакет(уровень: int, название: str, кому: str, график: str,
           часов_в_неделю: int, блок: float, входит: str) -> "Пакет":
    """Пакет по рыночной ставке своего уровня.

    Час в пакете дешевле разового визита той же длины: это месячный
    договор, и помощнику не надо искать клиента каждую неделю.
    """
    часов_в_месяц = round(часов_в_неделю * 4.345, 2)
    # Месячный договор дешевле разовых визитов той же длины на
    # десятую часть: помощнику не надо искать клиента каждую неделю,
    # и маршрут известен на месяц вперёд.
    за_час = round(рынок.ставка_часа(блок) * 0.9)
    return Пакет(уровень, название, кому, график, часов_в_неделю,
                 часов_в_месяц,
                 _округлить_вверх(за_час * часов_в_месяц, ШАГ_ПАКЕТА),
                 входит, блок=блок)


