# Из чего складывается час — по-честному, той же формулой, которой
# посчитан прайс. Показывать эти цифры семье не стыдно: они объясняют
# цену лучше любого «качественный уход от профессионалов».
def где_на_рынке(идентификатор: str = "v2") -> dict:
    """Положение нашей цены на шкале рынка — одной картинкой.

    Человеку не нужна таблица по пяти городам. Ему нужно понять
    за пять секунд: дороже частника, дешевле агентства, сильно
    дешевле Москвы. Всё остальное — для тех, кто сам спросит.
    """
    позиция = найти(идентификатор)
    часов = getattr(позиция, "часов", None) or позиция.часов_в_месяц
    return рынок.где_мы(позиция.цена / часов)


def разбор_часа(идентификатор: str = "v2") -> list[tuple[str, int]]:
    """Во что обходится час у подопечного — строка за строкой.

    Сумма строк — это полная стоимость часа, а не цена на экране:
    цену задаёт рынок, и она ниже. Разницу добирает служба, и её
    видно как раз потому, что строки сходятся в другое число.

    Показывать это не страшно, а выгодно: человек, который видит,
    что его час стоит дороже, чем он платит, перестаёт торговаться.
    """
    п = покрытие(идентификатор)
    строки = [
        ("Труд помощника с взносами, отпуском и дорогой",
         round(п.себестоимость - экономика.РАСХОДНИКИ
               - экономика.накладные_на_час())),
        ("Расходники и средства защиты", экономика.РАСХОДНИКИ),
        ("Организатор ухода, бухгалтерия, связь, помещение",
         round(экономика.накладные_на_час())),
        ("Резерв на замену и кассовый разрыв", round(п.резерв)),
        ("Налог УСН с того, что платит семья", round(п.налог)),
    ]
    # Строки округляются поодиночке, и копейки расходятся. Прячем
    # разницу в самой большой строке: показывать «округление» там,
    # где его не просили, — лишний повод для недоверия.
    расхождение = round(п.платит_семья + п.нужно_программ) - sum(
        с for _, с in строки)
    if расхождение:
        имя, было = строки[0]
        строки[0] = (имя, было + расхождение)
    return строки


