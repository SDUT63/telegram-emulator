def ставка_рынка(блок: float) -> int:
    """Рыночная ставка за час у подопечного для блока такой длины."""
    return рынок.ставка_часа(блок)


def _цена(блок: float, *, ночных: float = 0.0, за_час: float | None = None,
          доля: float = 1.0, шаг: int = ШАГ) -> int:
    """Рыночная цена услуги целиком.

    `ночных` удорожает час так же, как удорожает труд: ночная работа
    дороже не только нам, но и любому конкуренту, и прятать это
    в общей ставке нечестно перед помощником.

    `доля` — для позиций, которые служба намеренно продаёт дешевле
    рынка: пробный визит, знакомство.
    """
    базовая = за_час if за_час is not None else ставка_рынка(блок)
    если_ночь = ((ночных * экономика.НОЧНОЙ_КОЭФФИЦИЕНТ + (блок - ночных))
                 / блок) if блок else 1.0
    return _по_рыночному(базовая * блок * если_ночь * доля)


def покрытие(идентификатор: str) -> экономика.Покрытие:
    """Сколько за этот час должны дать программы."""
    позиция = найти(идентификатор)
    if позиция is None:
        raise KeyError(идентификатор)
    # Длина визита и число оплаченных часов — разные вещи, и путать
    # их нельзя. У пакета цена месячная, а блок двухчасовой: делить
    # цену на блок значило бы получить восемь тысяч за час.
    часов = getattr(позиция, "часов", None)
    if часов is None:                                   # это пакет
        блок, оплачено = позиция.блок, позиция.часов_в_месяц
    else:
        блок = оплачено = часов
    за_час = позиция.цена / оплачено

    ночных = 8.0 if getattr(позиция, "ночная", False) and блок == 12 else 0.0
    дорога = экономика.ДОРОГА / 7 if идентификатор == "live_in" else экономика.ДОРОГА
    if идентификатор == "first_visit":
        return экономика.покрытие(блок, за_час, дорога=дорога,
                                  ставка=экономика.СТАВКА_ОРГАНИЗАТОРА)
    return экономика.покрытие(блок, за_час, ночных=ночных, дорога=дорога)

