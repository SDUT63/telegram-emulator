# Цены округляем до десятков, пакеты — до сотен: рыночная цена
# и выглядеть должна как цена, а не как результат деления.
ШАГ = 10
ШАГ_ПАКЕТА = 100

def _округлить_вверх(сумма: float, шаг: int = ШАГ) -> int:
    return int(-(-сумма // шаг) * шаг)


def _по_рыночному(сумма: float) -> int:
    """Округлить так, как округляют цену, а не результат деления.

    До полутора тысяч — десятки, дальше полусотни: «3 510 ₽»
    выглядит вычисленным, «3 500 ₽» — назначенным. Разница
    в восприятии больше, чем в десяти рублях.
    """
    шаг = ШАГ if сумма <= 1500 else 50
    return int(-(-сумма // шаг) * шаг)


