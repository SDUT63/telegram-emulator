#!/usr/bin/env python3
"""Прайс платного ухода АНО «СДУТ». Цены выведены, а не назначены.

Зачем отдельный модуль. Цены нужны в трёх местах: в мини-приложении
(калькулятор), в ответах бота и в договоре. Если каждое место держит
свою копию, копии расходятся — и человек видит одну сумму на экране,
а в договоре другую. Здесь цифры лежат один раз, а
scripts/собрать_данные.py делает из них JSON для страницы.

Откуда берутся цены. Из рынка своего города (`рынок.py`),
а не из себестоимости.
Считать цену как «себестоимость плюс десять процентов» можно только
там, где семье некуда уйти, — а ей есть куда: частные объявления
начинаются от 160 ₽ в час. Служба, назвавшая 425 ₽, просто не получит
клиента и не узнает, почему.

Разрыв между рыночной ценой и себестоимостью служба закрывает сама.
Сегодня — из пожертвований и целевых средств; в расчёте на то, что
со временем его закроют программы: система долговременного ухода,
реестр поставщиков социальных услуг, гранты. Сколько именно нужно
на каждый час, считает `экономика.покрытие`, и это число не
прячется — оно есть и в выгрузке, и на экране.

Что здесь нельзя перепутать. Семья платит цену с экрана целиком.
Система долговременного ухода идёт в Самарской области пилотом,
в Тольятти её пока нет, и раньше 2027 года мы её не ждём. Поэтому
у каждой программы в `ПРОГРАММЫ` есть состояние, и «в ожидании»
не имеет права выглядеть как «действует»: обещание чужих денег,
которых нет, семья принимает за скидку и планирует под неё бюджет.

Чего цена не может. Быть ниже суммы, которую семья и программы дают
вместе: иначе служба обещает то, что нечем оплатить. И быть выше
рыночного ориентира: иначе прайс красивый, а клиентов нет. Обе
границы сторожит tests/test_price.py.

Что изменилось против первого прайса. Тот был набором цифр:
часовой визит стоил 1100 ₽ при себестоимости 415 ₽, а смены, сутки
и проживание продавались ниже себестоимости, потому что в расчёт
не входили накладные расходы и резерв отпусков. То есть служба
зарабатывала на разовых визитах и теряла на всём регулярном —
ровно наоборот тому, ради чего она создана.

Себестоимость здесь не прячется: человек вправе видеть, из чего
сложился его час. Прячется только внутренняя кухня — зарплатная
ведомость и то, сколько накладных закрыто грантами.
"""

