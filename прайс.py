def _округлить(число: float) -> int:
    """Половина — вверх, как в браузере.

    Python округляет 0,5 к чётному, JavaScript — всегда вверх. Разница
    вылезает редко, но вылезает рублём: на экране одна сумма, в расчёте
    координатора другая. Дешевле округлять одинаково.
    """
    return int(число + 0.5) if число >= 0 else -int(-число + 0.5)


def найти(идентификатор: str) -> Услуга | Пакет | None:
    """Позиция прайса по её идентификатору."""
    for у in УСЛУГИ:
        if у.id == идентификатор:
            return у
    for п in ПАКЕТЫ:
        if f"level{п.уровень}" == идентификатор:
            return п
    return None


def применимы(идентификатор: str) -> tuple[Поправка, ...]:
    """Поправки, которые к этой позиции вообще можно применить.

    Ночная надбавка к ночной смене не применяется: двадцать процентов
    за ночь уже сидят в её цене, и второй раз их брать нельзя.
    """
    return tuple(п for п in ПОПРАВКИ
                 if идентификатор not in п.кроме and not п.справочно)


def посчитать(идентификатор: str, сколько: float = 1,
              поправки: tuple[str, ...] | list[str] = ()) -> dict:
    """Итог по позиции прайса.

    Надбавки и скидки складываются процентами к базовой цене, а не
    накручиваются одна на другую: так написано в прайсе и так проще
    объяснить семье. Отрицательным итог не бывает.
    """
    позиция = найти(идентификатор)
    if позиция is None:
        raise KeyError(идентификатор)

    база = позиция.цена
    процент = 0
    разовые = 0
    учтено: list[Поправка] = []
    пропущено: list[Поправка] = []
    for имя in поправки:
        п = next((x for x in ПОПРАВКИ if x.id == имя), None)
        if п is None:
            raise KeyError(имя)
        if п.процент is None or п.справочно or идентификатор in п.кроме:
            пропущено.append(п)
            continue
        if п.разово:
            разовые += п.процент
        else:
            процент += -п.процент if п.скидка else п.процент
        учтено.append(п)

    доля = max(0.0, 1 + процент / 100)
    за_единицу = _округлить(база * доля)
    итог = max(0, _округлить(за_единицу * сколько + база * разовые / 100))

    часов = getattr(позиция, "часов", None)
    if часов is None:
        часов = getattr(позиция, "часов_в_месяц", 0)
    в_час = _округлить(за_единицу / часов) if часов else None

    return {
        "позиция": идентификатор,
        "база": база,
        "процент": процент,
        "за_единицу": за_единицу,
        "разово": _округлить(база * разовые / 100),
        "сколько": сколько,
        "итог": итог,
        "в_час": в_час,
        "учтено": [п.id for п in учтено],
        "пропущено": [п.id for п in пропущено],
    }
