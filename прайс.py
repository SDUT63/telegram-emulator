# Цены округляем вверх до десятков: вниз округлять нельзя — цена
# уйдёт ниже расчётной, а расчёт и так без запаса.
ШАГ = 10
ШАГ_ПАКЕТА = 100


def _округлить_вверх(сумма: float, шаг: int = ШАГ) -> int:
    return int(-(-сумма // шаг) * шаг)


def _цена(блок: float, *, ночных: float = 0.0,
          дорога: float = экономика.ДОРОГА,
          ставка: float = экономика.СТАВКА_ПОМОЩНИКА,
          рентабельность: float = экономика.РЕНТАБЕЛЬНОСТЬ,
          шаг: int = ШАГ) -> int:
    """Цена услуги целиком, выведенная из расчёта."""
    расчёт = экономика.час(блок, ночных=ночных, дорога=дорога, ставка=ставка,
                           рентабельность=рентабельность)
    return _округлить_вверх(расчёт.цена * блок, шаг)

