def разбор_часа(идентификатор: str = "v2") -> list[tuple[str, int]]:
    """Строки должны сходиться ровно в ту цену, которая на экране.

    Показать разбор на 421 ₽ рядом с ценой 425 ₽ — значит дать
    человеку повод усомниться во всём остальном. Разница берётся
    от округления вверх, и она такая же строка, как прочие.
    """
    позиция = найти(идентификатор)
