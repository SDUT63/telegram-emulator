# Лифт решает, поедет ли бригада на пятый этаж с носилками. Спрашивать
# отдельной кнопкой после подробного адреса — лишний шаг; ищем в тексте.
БЕЗ_ЛИФТА = ("лифта нет", "без лифта", "нет лифта", "лифт не работает")
С_ЛИФТОМ = ("есть лифт", "лифт есть", "с лифтом", "лифт работает")


def place_from(text: str) -> dict[str, str]:
    """Достать из строки адреса то, что нужно отдельным полем.

    Возвращает только распознанное. Не разобралось — поля нет, и в
    карточке координатор видит пустое место, а не выдуманное значение.
    """
    low = (text or "").lower()
    найдено: dict[str, str] = {}

    for ключ, район in РАЙОНЫ.items():
        if ключ in low:
            найдено["district"] = район
            break

    if any(слова in low for слова in БЕЗ_ЛИФТА):
        найдено["lift"] = "Лифта нет"
    elif any(слова in low for слова in С_ЛИФТОМ):
        найдено["lift"] = "Есть лифт"
    elif "частн" in low or "свой дом" in low:
        найдено["lift"] = "Частный дом"

    return найдено


def continues(answers: dict[str, str]) -> bool:
    """Человек согласился отвечать на подробную часть."""
    return picked(answers, "continue", "продолж")


