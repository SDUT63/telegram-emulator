"""
Вопросы анкеты СДУТ.

Отдельный файл, чтобы формулировки можно было править, не трогая логику
бота. Логика живёт в chatbot_survey.py.

Поля вопроса
------------
id        внутреннее имя, попадёт в заголовок столбца таблицы
section   раздел — с него начинается строка над вопросом
text      сам вопрос
kind      text | phone | email | choice
options   варианты для choice
multi     True — можно отметить несколько
required  False — можно пропустить
when      функция от уже данных ответов: задавать ли вопрос вообще
alerts    список правил. Правило срабатывает, если выбран один из
          "options" либо если отмечено не меньше "min_selected" вариантов.
          Тогда бот сразу выдаёт "text", а обращение помечается "label"
after     функция от уже данных ответов: что сказать сразу после ответа
          на этот вопрос. Пусто — ничего не говорим. Так к первому вопросу
          привязан рассказ о том, какое согласие человеку понадобится

О формулировках
---------------
В тексте вопроса не перечисляем варианты и не объясняем, как отвечать:
варианты человек видит кнопками, а подсказку бот добавит сам и только
там, где она нужна. Вопрос — это одна короткая строка.

Подписи вариантов держим короткими: короткие бот раскладывает
в два столбца, и список кнопок становится вдвое ниже. Длинные — в один
столбец, потому что MAX не переносит длинную подпись, а обрезает её
многоточием: «Программа соцусл…». Ориентир — 15–17 знаков.

Вариант, начинающийся со слова «Ничего», бот показывает не в общем
списке, а отдельной кнопкой внизу — он отменяет остальные отметки.
"""

