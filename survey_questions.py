def толкование(question_id: str, текст: str) -> str | None:
    """Точное прочтение свободного ответа там, где догадка не нужна.

    Возраст люди пишут числом: «82». Кнопок в этом вопросе четыре, и
    «82» бот принимал за промах по кнопке, отвечая «нужен номер от 1
    до 4». Число от 40 до 120 в вопросе о возрасте — это возраст,
    и разброс лет по группам здесь не догадка, а арифметика.
    """
    if question_id != "age":
        return None
    цифры = (текст or "").strip()
    if not цифры.isdigit():
        return None
    лет = int(цифры)
    if not 40 <= лет <= 120:
        return None
    if лет < 60:
        return "До 60 лет"
    if лет < 75:
        return "60–74 года"
    if лет < 85:
        return "75–84 года"
    return "85 и старше"


