def picked(answers: dict[str, str], key: str, *values: str) -> bool:
    """Выбран ли хотя бы один из вариантов в ответе на вопрос key."""
    got = answers.get(key, "")
    return any(v.lower() in got.lower() for v in values)


def lying_or_wheelchair(answers: dict[str, str]) -> bool:
    return picked(answers, "mobility", "не встаёт", "коляск")


def has_pain(answers: dict[str, str]) -> bool:
    return picked(answers, "pain", "постоянная", "бывает")


def about_other(answers: dict[str, str]) -> bool:
    """Речь не о самом обратившемся — о близком или о подопечном.

    От этого зависит многое: чьё имя писать в карточку, кто вправе
    подписать согласие и надо ли уведомлять человека по ч. 3 ст. 18.
    """
    return not picked(answers, "who", "о себе")


def about_relative(answers: dict[str, str]) -> bool:
    """Речь о близком человеке.

    Отдельно от about_other: специалист обращается о подопечном, и
    спрашивать его, кем он приходится, бессмысленно — он никем
    не приходится, он по работе.
    """
    return picked(answers, "who", "о близком")


