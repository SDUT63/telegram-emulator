ЗАГОЛОВОК = re.compile(r"^#\s+(.+)$")
ПОЛЕ = re.compile(r"^(источник|ключи|раздел):\s*(.+)$", re.I)


def _из_файла(путь: str) -> list[Статья]:
    """Разобрать один файл базы. Статьи разделены строкой «# Заголовок»."""
    имя = os.path.splitext(os.path.basename(путь))[0]
    статьи: list[Статья] = []
    заголовок = раздел = источник = ""
    ключи: tuple[str, ...] = ()
    тело: list[str] = []

    def закрыть() -> None:
        if заголовок and "".join(тело).strip():
            статьи.append(Статья(
                id=f"{имя}#{len(статьи) + 1}", заголовок=заголовок,
                раздел=раздел or имя, текст="\n".join(тело).strip(),
                источник=источник, ключи=ключи))

    for строка in open(путь, encoding="utf-8").read().split("\n"):
        шапка = ЗАГОЛОВОК.match(строка)
        if шапка:
            закрыть()
            заголовок, тело = шапка.group(1).strip(), []
            источник, ключи = "", ()
            continue
        поле = ПОЛЕ.match(строка.strip()) if not тело else None
        if поле:
            имя_поля, значение = поле.group(1).lower(), поле.group(2).strip()
            if имя_поля == "источник":
                источник = значение
            elif имя_поля == "раздел":
                раздел = значение
            else:
                ключи = tuple(k.strip() for k in значение.split(",") if k.strip())
            continue
        тело.append(строка)
    закрыть()
    return статьи


