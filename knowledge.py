"""
База знаний службы: то, из чего бот отвечает на вопросы.

Два источника, и оба настоящие.

Первый — папка `база/`: выдержки из нормативных документов, которых нет
в справочнике, но которые нужны, чтобы отвечать по существу. Приказ № 731
с оценочной шкалой, Приказ № 208н/243н о паллиативной помощи, маршруты
службы. Это обычные текстовые файлы; править их может кто угодно,
программиста звать не нужно.

Второй — сам справочник `webapp/index.html`. Всё, что там опубликовано,
бот берёт оттуда напрямую. Заводить вторую копию тех же текстов нельзя:
копии расходятся, и однажды бот скажет одно, а страница другое.

Поиск здесь без нейросетей и без интернета: слова вопроса сравниваются
с текстом статьи по началу слова — этого хватает для русского языка,
где «уровень», «уровня» и «уровни» отличаются хвостом. Работает всегда,
в том числе когда модель отключена или недоступна.

Запуск для проверки:

    python knowledge.py уровень нуждаемости
"""
from __future__ import annotations

