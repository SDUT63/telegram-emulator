@dataclass
class Статья:
    id: str
    заголовок: str
    раздел: str
    текст: str
    источник: str = ""
    ключи: tuple[str, ...] = ()
    _основы: set[str] = field(default_factory=set, init=False, repr=False)

    def __post_init__(self) -> None:
        self._основы = set(основы(self.заголовок + " " + self.текст + " " + " ".join(self.ключи)))

    def вес(self, спрошено: set[str], редкость: dict[str, float]) -> float:
        совпало = [о for о in спрошено if о in self._основы]
        if not совпало: return 0.0
        return sum(min(ПОТОЛОК, редкость.get(о, 1.0) * РЕЗКОСТЬ) for о in совпало) + max(0, len(совпало) - 1) * РАЗНООБРАЗИЕ

def основы(text: str) -> list[str]:
    слова = re.findall(r"[а-яёa-z0-9-]+", (text or "").lower())
    result = []
    for слово in слова:
        if len(слово) < КОРОТКИЕ or слово in ШУМ: continue
        if слово in СИНОНИМЫ:
            result.extend(основы(СИНОНИМЫ[слово])); continue
        основа = слово
        for окончание in ОКОНЧАНИЯ:
            if len(основа) - len(окончание) >= МИНИМУМ_ОСНОВЫ and основа.endswith(окончание):
                основа = основа[:-len(окончание)]; break
        result.append(основа[:ОСНОВА])
    return result

