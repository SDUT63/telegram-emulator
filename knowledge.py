# Сколько статей показывать на одной странице ветви. Больше шести — это уже
# стена кнопок, в которой человек снова теряется.
НА_СТРАНИЦЕ = 6


def _по_ветвям() -> dict[str, list[str]]:
    """Заголовки статей, разложенные по ветвям карты. Считается один раз."""
    global _карта_кэш
    if _карта_кэш is not None:
        return _карта_кэш

    статьи = загрузить()
    занято: set[str] = set()
    вышло: dict[str, list[str]] = {}

    # Сначала закрепления — все и по всем ветвям сразу. Иначе статья,
    # закреплённая в одной ветви, достаётся другой просто потому, что та
    # стоит выше по списку и забрала её по разделу. Закрепление важнее
    # раздела: его ставили руками и ради конкретного человека.
    закреплено: dict[str, list[str]] = {}
    for ветвь in КАРТА:
        своё = []
        for заголовок in ветвь.первыми:
            if по_заголовку(заголовок) and заголовок not in занято:
                своё.append(заголовок)
                занято.add(заголовок)
        закреплено[ветвь.id] = своё

    for ветвь in КАРТА:
        список: list[str] = list(закреплено[ветвь.id])
        # Внутри ветви порядок не случайный. Сначала свои статьи — они
        # написаны для чтения в чате; потом позиции шкалы; в конце карточки
        # справочника: они короткие и рассчитаны на страницу, а не на диалог.
        наши, шкала, справочник = [], [], []
        for с in статьи:
            if с.раздел not in ветвь.разделы or с.заголовок in занято:
                continue
            занято.add(с.заголовок)
            откуда = с.id.split("#")[0]
            if откуда == "шкала":
                шкала.append(с.заголовок)
            elif откуда.startswith("b-"):
                справочник.append(с.заголовок)
            else:
                наши.append(с.заголовок)
        вышло[ветвь.id] = список + наши + шкала + справочник

    _карта_кэш = вышло
    return вышло


def карта() -> list[dict]:
    """Корень: ветви и сколько в каждой тем."""
    по_ветвям = _по_ветвям()
    return [{"id": в.id, "название": в.название, "кратко": в.кратко,
             "сколько": len(по_ветвям.get(в.id, []))}
            for в in КАРТА if по_ветвям.get(в.id)]


def ветвь(id: str) -> dict | None:
    """Одна ветвь целиком: название и все её темы по порядку."""
    for в in КАРТА:
        if в.id == id:
            return {"id": в.id, "название": в.название, "кратко": в.кратко,
                    "статьи": list(_по_ветвям().get(в.id, []))}
    return None


def страница(id: str, номер: int = 1) -> dict | None:
    """Страница ветви. Номер считается с единицы и сам не выходит за края."""
    в = ветвь(id)
    if not в:
        return None
    всего = max(1, -(-len(в["статьи"]) // НА_СТРАНИЦЕ))
    номер = min(max(1, номер), всего)
    начало = (номер - 1) * НА_СТРАНИЦЕ
    return {"id": в["id"], "название": в["название"], "кратко": в["кратко"],
            "номер": номер, "всего": всего, "статей": len(в["статьи"]),
            "первая": начало + 1,
            "статьи": в["статьи"][начало:начало + НА_СТРАНИЦЕ]}


def где(заголовок: str) -> str | None:
    """В какой ветви лежит статья. Нужно для «назад» и для хлебных крошек."""
    for id, список in _по_ветвям().items():
        if заголовок in список:
            return id
    return None


def путь(заголовок: str) -> str:
    """Хлебные крошки: человек должен видеть, где он находится.

    Короткое имя ветви и стрелка вниз — строка читается как путь,
    а не как второй заголовок над заголовком.
    """
    id = где(заголовок)
    в = ветвь(id) if id else None
    return f"{в['кратко']} ›" if в else ""


def соседи(заголовок: str, сколько: int = 3) -> list[str]:
    """Темы рядом по карте — те, что человек чаще всего смотрит следующими."""
    id = где(заголовок)
    if not id:
        return []
    список = _по_ветвям().get(id, [])
    место = список.index(заголовок)
    рядом = список[место + 1:] + список[:место]
    return рядом[:сколько]


def вне_карты() -> list[str]:
    """Статьи, не попавшие ни в одну ветвь. В норме — только исключённые."""
    занято = {з for список in _по_ветвям().values() for з in список}
    return [с.заголовок for с in загрузить()
            if с.заголовок not in занято and с.раздел not in НЕ_В_КАРТЕ]


# Подпись на кнопке во всю ширину. MAX режет длинное многоточием,
# и «Пролежни: где искать и что дела…» человек читать не станет.
ШИРИНА_КНОПКИ = 34


def подпись(заголовок: str) -> str:
    """Короткая подпись кнопки из длинного заголовка статьи.

    Сначала пробуем отрезать по двоеточию: у заголовков вида
    «Пролежни: где искать и что делать» слева стоит именно то, о чём
    статья. Если и это длинно — обрезаем по слову.
    """
    заголовок = (заголовок or "").strip()
    if len(заголовок) <= ШИРИНА_КНОПКИ:
        return заголовок

    # Голова до двоеточия годится, только если она сама по себе фраза:
    # «Кресло-коляска» вместо «Кресло-коляска: комнатная или прогулочная»
    # превращает подсказку в загадку.
    голова = заголовок.split(":")[0].strip()
    if 14 <= len(голова) <= ШИРИНА_КНОПКИ and len(голова.split()) >= 2:
        return голова

    вышло = ""
    for слово in заголовок.split():
        if len(вышло) + len(слово) + 1 > ШИРИНА_КНОПКИ - 1:
            break
        вышло += (" " if вышло else "") + слово
    return (вышло or заголовок[:ШИРИНА_КНОПКИ - 1]).rstrip(" ,.—-") + "…"


def по_заголовку(заголовок: str) -> Статья | None:
    """Статья по её точному заголовку — так работают кнопки-подсказки."""
    нужен = (заголовок or "").strip().lower()
    for с in загрузить():
        if с.заголовок.strip().lower() == нужен:
            return с
    return None


def _по_теме(вопрос: str) -> list[str]:
    """Подсказки по ключевому слову. Для коротких и беспомощных обращений."""
    low = (вопрос or "").lower()
    вышло: list[str] = []
    for слова, темы in ТЕМЫ.items():
        if any(с in low for с in слова.split()):
            вышло += [т for т in темы if т not in вышло]
    return вышло


def подсказки(вопрос: str = "", сколько: int = 4,
              кроме: str = "") -> list[str]:
    """О чём ещё можно спросить. Готовые вопросы, а не темы.

    Порядок такой: сначала статьи, которые нашлись по самому вопросу
    (кроме уже показанной), потом соседи по разделу — они почти всегда
    про то же самое, — потом подсказки по ключевому слову, и в самом
    конце начальный набор для тех, кому не подошло ничего.
    """
    вышло: list[str] = []

    def добавить(заголовки) -> None:
        for з in заголовки:
            if з and з != кроме and з not in вышло and по_заголовку(з):
                вышло.append(з)

    найденные = найти(вопрос, сколько=сколько + 2) if вопрос else []
    по_теме = _по_теме(вопрос)

    # «Мама лежит» — это не вопрос, а состояние. По двум словам искать
    # нечего, зато понятно, о чём человек скорее всего спросит дальше:
    # тут вперёд выходит подобранный список, а не поиск.
    коротко = len(set(основы(вопрос))) < 3
    if коротко and по_теме:
        добавить(по_теме)

    # Из поиска берём немного: он находит похожее по словам, а подобранная
    # тема — то, что человек спросит следующим. Дальше — соседи по разделу
    # и, если совсем нечем, начальный набор.
    добавить((с.заголовок for с in найденные[:2]))
    добавить(по_теме)
    добавить(с.заголовок for с in найденные)

    if найденные:
        раздел = найденные[0].раздел
        добавить(с.заголовок for с in загрузить()
                 if с.раздел == раздел and len(с.текст) > 200)

    добавить(НАЧАЛО)
    return вышло[:сколько]


def начать() -> tuple[str, list[str]]:
    """Что показать тому, кто написал «не знаю, с чего начать».

    Возвращает вступление и список готовых вопросов кнопками.
    """
    вступление = (
        "Могу подсказать по материалам службы. Выберите, что ближе, "
        "или напишите своими словами — отвечу и передам координатору."
    )
    return вступление, [з for з in НАЧАЛО if по_заголовку(з)]


def статья_целиком(заголовок: str, предел: int = 1500) -> str | None:
    """Текст статьи для отправки в чат. Длинную режем по абзацу."""
    с = по_заголовку(заголовок)
    if not с:
        return None
    текст = с.текст.strip()
    if len(текст) > предел:
        куски, вышло = текст.split("\n"), ""
        for кусок in куски:
            if len(вышло) + len(кусок) > предел:
                break
            вышло += кусок + "\n"
        текст = (вышло.strip() or текст[:предел]) + "\n\n…"
    return f"{с.заголовок}\n\n{текст}"


