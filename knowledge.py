@dataclass
class Статья:
    """Один кусок базы: заголовок, откуда взят и сам текст."""

    id: str
    заголовок: str
    раздел: str
    текст: str
    источник: str = ""
    ключи: tuple[str, ...] = ()
    _основы: dict[str, int] = field(default_factory=dict, repr=False)

    def __post_init__(self) -> None:
        # Заголовок и ключи весят больше тела: попадание в них точнее.
        self._основы = {}
        for текст, вес in ((self.заголовок, 4), (" ".join(self.ключи), 5),
                           (self.раздел, 2), (self.текст, 1)):
            for слово in основы(текст):
                self._основы[слово] = self._основы.get(слово, 0) + вес
        # Одно слово, повторённое двадцать раз, не делает статью в двадцать
        # раз более подходящей. Выше потолка вклад не растёт — иначе поиск
        # выбирает самую многословную статью, а не самую близкую.
        self._основы = {о: min(в, ПОТОЛОК) for о, в in self._основы.items()}

    def вес(self, спрошено: set[str], редкость: dict[str, float]) -> float:
        """Совпадения, взвешенные редкостью слова.

        «Обращаться» есть в половине статей и ничего не различает,
        «пролежень» — в двух и попадает точно. Без этой поправки поиск
        выдаёт самую многословную статью, а не самую подходящую.

        Статья, совпавшая по нескольким разным словам, идёт выше той,
        что совпала по одному: два попадания из вопроса — уже не совпадение.
        """
        попало = [о for о in спрошено if о in self._основы]
        if not попало:
            return 0.0
        сумма = sum(self._основы[о] * редкость.get(о, 1.0) ** РЕЗКОСТЬ
                    for о in попало)
        return сумма * (1 + РАЗНООБРАЗИЕ * (len(попало) - 1))


def расширить(вопрос: str) -> str:
    """Добавить к вопросу служебные слова, которыми написана база."""
    низом = (вопрос or "").lower()
    добавка = [СИНОНИМЫ[с] for с in re.findall(r"[а-яё]+", низом)
               if с in СИНОНИМЫ]
    добавка += [значение for оборот, значение in ОБОРОТЫ.items()
                if оборот in низом]
    return вопрос + " " + " ".join(добавка) if добавка else вопрос


def основы(текст: str) -> list[str]:
    """Слова текста, обрезанные до начала. Числа остаются как есть."""
    вышло = []
    for слово in re.findall(r"[0-9а-яёa-z]+", (текст or "").lower()):
        if слово in ШУМ:
            continue
        if слово.isdigit():
            вышло.append(слово)
        elif len(слово) >= КОРОТКИЕ:
            вышло.append(слово[:ОСНОВА])
    return вышло


# ------------------------------------------------------------ папка «база»

ЗАГОЛОВОК = re.compile(r"^#\s+(.+)$")
ПОЛЕ = re.compile(r"^(источник|ключи|раздел):\s*(.+)$", re.I)


def _из_файла(путь: str) -> list[Статья]:
    """Разобрать один файл базы. Статьи разделены строкой «# Заголовок»."""
    имя = os.path.splitext(os.path.basename(путь))[0]
    статьи: list[Статья] = []
    заголовок = раздел = источник = ""
    ключи: tuple[str, ...] = ()
    тело: list[str] = []

    def закрыть() -> None:
        if заголовок and "".join(тело).strip():
            статьи.append(Статья(
                id=f"{имя}#{len(статьи) + 1}", заголовок=заголовок,
                раздел=раздел or имя, текст="\n".join(тело).strip(),
                источник=источник, ключи=ключи))

    for строка in open(путь, encoding="utf-8").read().split("\n"):
        шапка = ЗАГОЛОВОК.match(строка)
        if шапка:
            закрыть()
            заголовок, тело = шапка.group(1).strip(), []
            источник, ключи = "", ()
            continue
        поле = ПОЛЕ.match(строка.strip()) if not тело else None
        if поле:
            имя_поля, значение = поле.group(1).lower(), поле.group(2).strip()
            if имя_поля == "источник":
                источник = значение
            elif имя_поля == "раздел":
                раздел = значение
            else:
                ключи = tuple(k.strip() for k in значение.split(",") if k.strip())
            continue
        тело.append(строка)
    закрыть()
    return статьи


# ------------------------------------------------------- справочник в MAX

БЛОК = re.compile(
    r'<section class="block" id="(?P<id>[^"]+)".*?<h2[^>]*>(?P<name>.*?)</h2>'
    r'(?P<body>.*?)</section>', re.S)

# Три формы, в которых в справочнике живёт ответ на вопрос: карточка
# с заголовком, раскрывающийся вопрос-ответ и строка списка. Всё
# остальное — оформление.
КАРТОЧКА = re.compile(
    r'<div class="card"[^>]*>(?P<body>.*?)(?=<div class="card"|\Z)', re.S)
ВОПРОС = re.compile(
    r'<details class="q"[^>]*>\s*<summary>(?P<title>.*?)</summary>'
    r'(?P<body>.*?)</details>', re.S)
СТРОКА = re.compile(
    r'<div class="row__body">\s*<span class="row__title">(?P<title>.*?)</span>'
    r'\s*<span class="row__text">(?P<body>.*?)</span>', re.S)
ПОДЗАГОЛОВОК = re.compile(r"<h2[^>]*>(.*?)</h2>", re.S)

КОРОТКАЯ = 60         # короче — это подпись к картинке, а не статья


def _без_разметки(кусок: str) -> str:
    """Текст без тегов. Картинки и значки выбрасываем вместе с описаниями."""
    кусок = re.sub(r"<svg.*?</svg>", " ", кусок, flags=re.S)
    кусок = re.sub(r"<(script|style|figcaption).*?</\1>", " ", кусок, flags=re.S)
    кусок = re.sub(r"<img[^>]*>", " ", кусок)
    кусок = re.sub(r"</(p|li|div|h2|h3|tr)>", "\n", кусок)
    кусок = re.sub(r"<[^>]+>", " ", кусок)
    кусок = html.unescape(кусок)
    кусок = re.sub(r"[ \t\u00a0]+", " ", кусок)
    return re.sub(r"\n{2,}", "\n", кусок).strip()


def _из_справочника(путь: str) -> list[Статья]:
    """Разобрать «Навигатор помощи» на статьи.

    Раскрывающиеся вопросы разбираем первыми и вырезаем из блока: иначе
    тот же текст попал бы в базу второй раз внутри карточки, и поиск
    выдавал бы два одинаковых ответа подряд.
    """
    if not os.path.exists(путь):
        return []
    страница = open(путь, encoding="utf-8").read()
    статьи: list[Статья] = []

    for блок in БЛОК.finditer(страница):
        раздел = _без_разметки(блок.group("name"))
        тело = блок.group("body")
        откуда = "Навигатор помощи, справочник службы"

        def добавить(титул: str, текст: str, номер: int) -> None:
            if len(текст) < КОРОТКАЯ:
                return
            статьи.append(Статья(
                id=f"{блок.group('id')}#{номер}",
                заголовок=титул or раздел, раздел=раздел,
                текст=текст, источник=откуда))

        счёт = 0
        for вопрос in ВОПРОС.finditer(тело):
            счёт += 1
            добавить(_без_разметки(вопрос.group("title")),
                     _без_разметки(вопрос.group("body")), счёт)
        тело = ВОПРОС.sub(" ", тело)

        for строка in СТРОКА.finditer(тело):
            счёт += 1
            титул = _без_разметки(строка.group("title"))
            добавить(титул, титул + " — " + _без_разметки(строка.group("body")), счёт)
        тело = СТРОКА.sub(" ", тело)

        for карточка in КАРТОЧКА.finditer(тело):
            счёт += 1
            сырое = карточка.group("body")
            титул = ПОДЗАГОЛОВОК.search(сырое)
            добавить(_без_разметки(титул.group(1)) if титул else "",
                     _без_разметки(сырое), счёт)
    return статьи


# ------------------------------------------------------------------ поиск

_кэш: list[Статья] | None = None
_редкость: dict[str, float] = {}


def _посчитать_редкость(статьи: list[Статья]) -> dict[str, float]:
    """Насколько слово различает статьи. Частое — почти ничего не весит."""
    из_скольких: dict[str, int] = {}
    for с in статьи:
        for основа in с._основы:
            из_скольких[основа] = из_скольких.get(основа, 0) + 1
    всего = max(len(статьи), 1)
    return {основа: math.log(1 + всего / сколько)
            for основа, сколько in из_скольких.items()}


def загрузить(перечитать: bool = False) -> list[Статья]:
    """Вся база. Читается один раз, дальше держится в памяти."""
    global _кэш, _редкость
    if _кэш is not None and not перечитать:
        return _кэш
    статьи: list[Статья] = []
    if os.path.isdir(БАЗА):
        for имя in sorted(os.listdir(БАЗА)):
            if имя.endswith(".md"):
                статьи += _из_файла(os.path.join(БАЗА, имя))
    статьи += _из_справочника(СПРАВОЧНИК)
    _кэш = статьи
    _редкость = _посчитать_редкость(статьи)
    return статьи


def найти(вопрос: str, сколько: int = 3, порог: float = 9.0) -> list[Статья]:
    """Статьи, подходящие к вопросу, — от самой подходящей.

    Порог отсекает случайные совпадения по одному частому слову: лучше
    промолчать и позвать координатора, чем выдать статью не по делу.
    """
    статьи = загрузить()
    спрошено = set(основы(расширить(вопрос)))
    if not спрошено:
        return []
    # Длинный вопрос, совпавший по одному слову, — это совпадение, а не
    # ответ. От вопроса в три слова и длиннее требуем два попадания.
    нужно_попаданий = 2 if len(спрошено) >= 3 else 1
    с_весом = [(с.вес(спрошено, _редкость), с) for с in статьи
               if sum(1 for о in спрошено if о in с._основы) >= нужно_попаданий]
    с_весом = [(в, с) for в, с in с_весом if в >= порог]
    с_весом.sort(key=lambda пара: (-пара[0], пара[1].id))
    return [с for _, с in с_весом[:сколько]]


def выдержка(статьи: list[Статья], предел: int = 4000) -> str:
    """Материалы для модели: заголовок, источник, текст — и ничего сверх.

    Предел нужен деньгам: у модели платят за каждый знак на входе.
    """
    куски, всего = [], 0
    for с in статьи:
        кусок = f"### {с.заголовок}\n"
        if с.источник:
            кусок += f"(источник: {с.источник})\n"
        кусок += с.текст.strip()
        if всего + len(кусок) > предел:
            break
        куски.append(кусок)
        всего += len(кусок)
    return "\n\n".join(куски)


def ответ_без_модели(вопрос: str) -> str | None:
    """Что бот может ответить сам, без языковой модели.

    Не пересказ, а сама статья: без модели пересказывать нечем, а
    показать найденное честнее, чем промолчать.
    """
    статьи = найти(вопрос, сколько=1, порог=14.0)
    if not статьи:
        return None
    текст = статья_целиком(статьи[0].заголовок, предел=900)
    хвост = "\n\nЕсли ответ не тот — напишите словами, координатор ответит сам."
    return текст + хвост if текст else None



