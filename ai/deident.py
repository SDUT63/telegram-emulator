# -*- coding: utf-8 -*-
"""Деперсонализация текста перед отправкой в языковую модель.

Работает до любого сетевого вызова. Если модель российская, это снижает риск;
если зарубежная — это единственное, что делает вызов допустимым вообще.

Правило простое: из текста уходит всё, по чему человека можно узнать.
Остаётся то, ради чего мы к модели обращаемся, — описание ситуации.
"""
from __future__ import annotations
import re

# Телефон в любом виде: +7, 8, со скобками, дефисами, пробелами
PHONE = re.compile(r'(?:\+?7|8)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}')
# Электронная почта
EMAIL = re.compile(r'[\w.\-+]+@[\w\-]+\.[a-zA-Zа-яА-Я]{2,}')
# СНИЛС и полис ОМС
SNILS = re.compile(r'\b\d{3}[\s\-]?\d{3}[\s\-]?\d{3}[\s\-]?\d{2}\b')
OMS   = re.compile(r'\b\d{16}\b')
# Адрес: улица, дом, квартира. Регистр указателя нечувствителен только
# внутри самого указателя — иначе «пиШИТЕ» опознаётся как «шоссе».
# Название улицы обязано начинаться с заглавной: это и есть отличие
# адреса от обычного текста.
ADDRESS = re.compile(
    r'\b(?i:ул\.|ул\b|улица|пр-т|пр\.|проспект|б-р|бульвар|пер\.|переулок|ш\.|шоссе|мкр\.|микрорайон)'
    r'\s*[А-ЯЁ][\w\-]+(?:\s+[А-ЯЁ][\w\-]+)?'
    r'(?:\s*,?\s*(?i:д\.|дом)\s*\d+[\w/]*)?'
    r'(?:\s*,?\s*(?i:кв\.|квартира)\s*\d+)?'
    r'|\b(?i:д\.|дом)\s*\d+[\w/]*\s*,?\s*(?i:кв\.|квартира)\s*\d+')
# Дата рождения
BIRTH = re.compile(r'\b\d{1,2}[.\-/]\d{1,2}[.\-/](?:19|20)\d{2}\b')

# Имена собственные не ловятся регулярным выражением надёжно, поэтому имя
# подставляется из анкеты явно: мы его знаем и вырезаем по значению.
def strip_names(text: str, *names: str) -> str:
    for name in names:
        name = (name or "").strip()
        if len(name) < 3:          # «Ия» вырезать по подстроке опасно
            continue
        for form in {name, name.capitalize(), name.upper(), name.lower()}:
            text = text.replace(form, "[имя]")
    return text


def clean(text: str, *names: str) -> str:
    """Убрать из текста всё, по чему можно узнать человека."""
    if not text:
        return ""
    text = strip_names(text, *names)
    text = PHONE.sub("[телефон]", text)
    text = EMAIL.sub("[почта]", text)
    text = OMS.sub("[полис]", text)
    text = SNILS.sub("[номер]", text)
    text = BIRTH.sub("[дата рождения]", text)
    text = ADDRESS.sub("[адрес]", text)
    return text


# Ключи анкеты, которые НИКОГДА не уходят в модель, даже после очистки.
NEVER_SEND = {"name", "phone"}

def safe_answers(answers: dict, *, names: tuple = ()) -> dict:
    """Ответы анкеты, пригодные для отправки: без имени и телефона, остальное очищено."""
    out = {}
    for k, v in (answers or {}).items():
        if k in NEVER_SEND:
            continue
        out[k] = clean(str(v), *names)
    return out


def assert_clean(text: str) -> None:
    """Последняя проверка перед отправкой. Падает, а не отправляет."""
    for name, rx in (("телефон", PHONE), ("почта", EMAIL), ("полис", OMS),
                     ("дата рождения", BIRTH)):
        if rx.search(text):
            raise ValueError(
                f"В тексте для модели остался {name}. Отправка отменена. "
                f"Это ошибка в коде, а не повод отключить проверку.")
