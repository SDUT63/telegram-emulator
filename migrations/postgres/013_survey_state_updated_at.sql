-- Срок хранения анкет ищет просроченные карточки по времени последнего
-- изменения (ops/purge_expired_cases.py). Индекса на это поле не было,
-- и чистка каждую ночь читала таблицу целиком: EXPLAIN показывал
-- Seq Scan. На двух сотнях карточек это незаметно, на десятках тысяч —
-- ночная задача, которая держит таблицу, куда бот пишет прямо сейчас.
--
-- Тот же индекс пригодится и любому отчёту «кто обращался за период».
CREATE INDEX IF NOT EXISTS idx_survey_state_updated_at
    ON survey_state (updated_at);
