#!/usr/bin/env python3
"""Нагрузка на анкету: много людей сразу, один человек в несколько рук,
мусор во входе.

Запуск:
    python нагрузка/бот.py [--людей 200] [--сообщений 20]

Что ищем — не «упадёт или нет», а то, что не видно на одном человеке:
перепутанные между людьми ответы, потерянный ответ при одновременной
записи, разрастание хранилища от мусора, необработанное исключение
внутри потока, которое молча съест сообщение.
"""

from __future__ import annotations

import argparse
import os
import random
import string
import sys
import tempfile
import threading
import time
import traceback
from concurrent.futures import ThreadPoolExecutor

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, КОРЕНЬ)


ШАГИ = [
    "О близком человеке", "Дочь или сын", "Да, знает", "Ирина",
    "Анна Петровна", "89170000000", "Утром", "Тольятти, Ленина 1",
    "85 и старше", "Боль", "Помощь на дому", "Продолжить", "Не встаёт",
]

# То, что человек и правда присылает: эмодзи, вставленный из письма текст
# с переносами, случайный набор символов. И то, что присылает не человек.
МУСОР = [
    "'; DROP TABLE survey; --",
    "<script>alert(document.cookie)</script>",
    "{{7*7}}",
    "${jndi:ldap://x/a}",
    "../../etc/passwd",
    "\x00\x01\x02",
    "‮текст задом наперёд",
    "А" * 100_000,
    "\n" * 5_000,
    "👨‍👩‍👧‍👦" * 500,
    "%s%s%s%n",
    "0" * 10_000,
]


class Отчёт:
    def __init__(self) -> None:
        self.ошибки: list[str] = []
        self.замок = threading.Lock()

    def беда(self, что: str) -> None:
        with self.замок:
            self.ошибки.append(что)

    def итог(self, название: str) -> bool:
        if self.ошибки:
            print(f"  [!]  {название}: {len(self.ошибки)}")
            for строка in self.ошибки[:5]:
                print(f"       {строка}")
            if len(self.ошибки) > 5:
                print(f"       ... и ещё {len(self.ошибки) - 5}")
            return False
        print(f"  [ок] {название}")
        return True


def _анкета(путь: str):
    from chatbot_survey import Survey
    return Survey(storage_path=путь)


def многолюдно(людей: int, сообщений: int) -> bool:
    """Много разных людей одновременно. Ответы не должны перемешаться."""
    путь = tempfile.mktemp(suffix=".json")
    анкета = _анкета(путь)
    отчёт = Отчёт()

    def один(номер: int) -> None:
        кто = f"u{номер}"
        имя = f"Человек{номер}"
        try:
            анкета.grant_consent(кто)
            шаги = list(ШАГИ)
            шаги[3] = имя                      # у каждого своё имя
            for текст in шаги[:сообщений]:
                анкета.handle(кто, текст)
            ответы = анкета.state.get(кто, {}).get("answers", {})
            если_чужое = ответы.get("name")
            if если_чужое and если_чужое != имя:
                отчёт.беда(f"{кто}: в ответах чужое имя {если_чужое!r}")
        except Exception:                                       # noqa: BLE001
            отчёт.беда(f"{кто}: {traceback.format_exc(limit=2)}")

    начало = time.time()
    with ThreadPoolExecutor(max_workers=32) as пул:
        list(пул.map(один, range(людей)))
    прошло = time.time() - начало

    всего = len(анкета.state)
    if всего != людей:
        отчёт.беда(f"в хранилище {всего} человек вместо {людей}")
    размер = os.path.getsize(путь) / 1024 if os.path.exists(путь) else 0
    print(f"       {людей} человек × {сообщений} сообщений за {прошло:.1f} с "
          f"({людей * сообщений / прошло:.0f} сообщений/с), файл {размер:.0f} КБ")
    os.path.exists(путь) and os.unlink(путь)
    return отчёт.итог("много людей одновременно")


def один_в_несколько_рук(повторов: int = 200) -> bool:
    """Одно и то же сообщение приходит дважды — так бывает, когда
    мессенджер не дождался ответа и повторил доставку, и когда человек
    дважды нажал кнопку. Ответ не должен потеряться и не должен
    записаться не в тот вопрос."""
    отчёт = Отчёт()
    for попытка in range(повторов):
        путь = tempfile.mktemp(suffix=".json")
        анкета = _анкета(путь)
        анкета.grant_consent("u")
        анкета.handle("u", "О близком человеке")

        барьер = threading.Barrier(2)

        def послать(текст: str) -> None:
            барьер.wait()
            анкета.handle("u", текст)

        нити = [threading.Thread(target=послать, args=("Дочь или сын",)),
                threading.Thread(target=послать, args=("Дочь или сын",))]
        for н in нити:
            н.start()
        for н in нити:
            н.join()

        ответы = анкета.state["u"]["answers"]
        if ответы.get("relation") != "Дочь или сын":
            отчёт.беда(f"попытка {попытка}: relation = {ответы.get('relation')!r}")
        # Дубль не должен был уехать в следующий вопрос
        if ответы.get("aware") == "Дочь или сын":
            отчёт.беда(f"попытка {попытка}: дубль записан в следующий вопрос")
        os.path.exists(путь) and os.unlink(путь)
    return отчёт.итог(f"дубль доставки ({повторов} попыток)")


def мусор_на_входе() -> bool:
    """Что угодно вместо ответа. Ничего не должно упасть, а хранилище —
    распухнуть от одного сообщения."""
    отчёт = Отчёт()
    путь = tempfile.mktemp(suffix=".json")
    анкета = _анкета(путь)
    анкета.grant_consent("u")

    for что in МУСОР:
        try:
            ответ = анкета.handle("u", что)
        except Exception:                                       # noqa: BLE001
            отчёт.беда(f"{что[:30]!r}: {traceback.format_exc(limit=2)}")
            continue
        if ответ is None:
            отчёт.беда(f"{что[:30]!r}: бот промолчал")

    анкета.save()
    размер = os.path.getsize(путь) / 1024
    print(f"       после {len(МУСОР)} мусорных сообщений файл {размер:.0f} КБ")
    if размер > 512:
        отчёт.беда(f"хранилище распухло до {размер:.0f} КБ от {len(МУСОР)} сообщений")

    # Разметку бот не обезвреживает намеренно: в чате это обычный текст,
    # а в CRM его экранируют при показе. Портить ответ здесь значило бы
    # показать координатору не то, что написал человек, — а это может
    # оказаться уликой. Что разметка и правда не выполняется в CRM,
    # проверено в браузере на живом сервере; см. отчёт о нагрузке.

    # И самое важное: длинный мусор не должен вытеснить настоящие ответы
    сохранено = анкета.state["u"]["answers"]
    длинные = [к for к, з in сохранено.items() if len(str(з)) > 5000]
    if длинные:
        отчёт.беда(f"в ответах сохранены огромные строки: {длинные}")
    os.path.exists(путь) and os.unlink(путь)
    return отчёт.итог("мусор на входе")


def поток_от_одного(сообщений: int = 2000) -> bool:
    """Один человек шлёт без остановки. Интересует не скорость,
    а то, во что превращается его запись."""
    отчёт = Отчёт()
    путь = tempfile.mktemp(suffix=".json")
    анкета = _анкета(путь)
    анкета.grant_consent("u")
    for шаг in ШАГИ:
        анкета.handle("u", шаг)

    начало = time.time()
    for номер in range(сообщений):
        try:
            анкета.handle("u", f"вопрос номер {номер} про пролежни")
        except Exception:                                       # noqa: BLE001
            отчёт.беда(f"сообщение {номер}: {traceback.format_exc(limit=2)}")
            break
    прошло = time.time() - начало
    анкета.save()

    человек = анкета.state["u"]
    сообщений_в_записи = len(человек.get("messages", []))
    размер = os.path.getsize(путь) / 1024
    print(f"       {сообщений} сообщений за {прошло:.1f} с; "
          f"в карточке сохранено {сообщений_в_записи}, файл {размер:.0f} КБ")
    if размер > 5 * 1024:
        отчёт.беда(f"одна карточка выросла до {размер:.0f} КБ — "
                   "это отказ в обслуживании одним человеком")
    os.path.exists(путь) and os.unlink(путь)
    return отчёт.итог(f"поток от одного человека ({сообщений} сообщений)")


def случайные_слова(сообщений: int = 500) -> bool:
    """Случайный текст: ищем необработанное исключение в разборе."""
    отчёт = Отчёт()
    путь = tempfile.mktemp(suffix=".json")
    анкета = _анкета(путь)
    анкета.grant_consent("u")
    алфавит = string.printable + "йцукенгшщзхъфывапролджэячсмитьбю ёЁ—–«»№"
    случай = random.Random(20260916)
    for _ in range(сообщений):
        длина = случай.randint(0, 400)
        текст = "".join(случай.choice(алфавит) for _ in range(длина))
        try:
            анкета.handle("u", текст)
        except Exception:                                       # noqa: BLE001
            отчёт.беда(f"{текст[:40]!r}: {traceback.format_exc(limit=2)}")
    os.path.exists(путь) and os.unlink(путь)
    return отчёт.итог(f"случайный текст ({сообщений} сообщений)")


def главное() -> int:
    разбор = argparse.ArgumentParser()
    разбор.add_argument("--людей", type=int, default=200)
    разбор.add_argument("--сообщений", type=int, default=13)
    аргументы = разбор.parse_args()

    print("НАГРУЗКА НА АНКЕТУ")
    всё = [
        многолюдно(аргументы.людей, аргументы.сообщений),
        один_в_несколько_рук(),
        мусор_на_входе(),
        поток_от_одного(),
        случайные_слова(),
    ]
    return 0 if all(всё) else 1


if __name__ == "__main__":
    raise SystemExit(главное())
