def найти(идентификатор: str) -> Средство | None:
    return next((с for с in СРЕДСТВА if с.id == идентификатор), None)


def группы() -> list[str]:
    порядок: list[str] = []
    for с in СРЕДСТВА:
        if с.группа not in порядок:
            порядок.append(с.группа)
    return порядок


def для_шаблона(шаблон: str) -> list[Средство]:
    """Что нужно при таком плане ухода."""
    return [с for с in СРЕДСТВА if шаблон in с.шаблоны]


def за_месяцы(идентификаторы: list[str] | tuple[str, ...],
              месяцев: int = 1) -> dict:
    """Сколько выйдет аренда и с чем её сравнить.

    Показываем и покупку: когда аренда за срок догоняет цену покупки,
    человек должен это увидеть сам, а не узнать через полгода.
    """
    если_нет = [и for и in идентификаторы if найти(и) is None]
    if если_нет:
        raise KeyError(если_нет[0])
    выбрано = [найти(и) for и in идентификаторы]
    аренда = sum(с.аренда for с in выбрано) * max(1, месяцев)
    залог = sum(с.залог for с in выбрано)
    покупка = sum(с.покупка for с in выбрано)
    доставка = ДОСТАВКА["цена"] if выбрано else 0
    return {
        "позиций": len(выбрано),
        "месяцев": max(1, месяцев),
        "аренда": аренда,
        "залог": залог,
        "доставка": доставка,
        "итого": аренда + доставка,
        "покупка": покупка,
        "выгоднее_купить": bool(выбрано) and аренда >= покупка,
        "по_ипра": [с.название for с in выбрано if с.ипра == "да"],
    }
