def уточнения_из_анкеты(ответы_бота: dict[str, str]) -> list[dict[str, str]]:
    """Что добавляет к плану то, что человек уже рассказал боту."""
    собрано: list[dict[str, str]] = []
    for ключ, годные, заголовок, текст in УТОЧНЕНИЯ_АНКЕТЫ:
        было = str((ответы_бота or {}).get(ключ, ""))
        if any(г.lower() in было.lower() for г in годные):
            собрано.append({"заголовок": заголовок, "текст": текст,
                            "из": ключ})
    return собрано


def противоречия(ответы_плана: dict[str, str],
                 ответы_бота: dict[str, str]) -> list[dict[str, str]]:
    """Где анкета и опросник говорят разное.

    Молчать об этом нельзя: план, построенный на неверной посылке,
    выглядит так же уверенно, как правильный.
    """
    найдено: list[dict[str, str]] = []
    for ключ_бота, годные_бота, ключ_плана, годные_плана, текст in ПРОТИВОРЕЧИЯ:
        было_бота = str((ответы_бота or {}).get(ключ_бота, ""))
        было_плана = str((ответы_плана or {}).get(ключ_плана, ""))
        if (any(г.lower() in было_бота.lower() for г in годные_бота)
                and any(г.lower() in было_плана.lower() for г in годные_плана)):
            найдено.append({"текст": текст, "из": ключ_бота})
    return найдено


def точность(ответы_плана: dict[str, str],
             ответы_бота: dict[str, str]) -> dict:
    """Насколько план точен и чего не хватает для точного."""
    из_плана = sum(1 for в in ВОПРОСЫ if (ответы_плана or {}).get(в.id))
    полезные = {к for к, _, _, _ in УТОЧНЕНИЯ_АНКЕТЫ}
    из_анкеты = sum(1 for к in полезные if (ответы_бота or {}).get(к))
    return {
        "отвечено_здесь": из_плана,
        "всего_здесь": len(ВОПРОСЫ),
        "учтено_из_анкеты": из_анкеты,
        "уточнён": из_анкеты > 0,
        "степень": ("Уточнённый план" if из_анкеты >= 3
                    else "Первичная оценка"),
    }


def найти_шаблон(идентификатор: str) -> Шаблон | None:
    return next((ш for ш in ШАБЛОНЫ if ш.id == идентификатор), None)


def _подходит(ответы: dict[str, str], правило: dict) -> bool:
    for ключ, годные in правило.items():
        было = str(ответы.get(ключ, ""))
        if not any(г in было for г in годные):
            return False
    return True


def подобрать(ответы: dict[str, str]) -> Шаблон | None:
    """Шаблон по ответам. Ничего не подошло — значит, рано показывать."""
    for идентификатор, правило in ПРАВИЛА:
        if _подходит(ответы, правило):
            return найти_шаблон(идентификатор)
    return None


