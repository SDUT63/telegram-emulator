def блоки_по_ответам(шаблон: Шаблон, ответы: dict[str, str]) -> list[Блок]:
    """Только те части суток, которые человек отметил.

    Ночной блок показываем всегда, если человек не встаёт: ночь
    не отменяется тем, что о ней не подумали.

    А когда помощь нужна почти постоянно, показываем все части
    суток: отмечать «когда нужнее» в этом случае бессмысленно,
    и половина плана иначе просто не появится на экране.
    """
    if "Почти постоянно" in str(ответы.get("раз", "")):
        return list(шаблон.блоки)
    отмечено = str(ответы.get("когда", ""))
    если_лежит = "В кровати" in str(ответы.get("день", ""))
    выбрано = [б for б in шаблон.блоки
               if б.когда in отмечено or (если_лежит and б.время == "Ночь")]
    return выбрано or list(шаблон.блоки)


