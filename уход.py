# Какой позиции прайса соответствует шаблон. Нужно, чтобы человек,
# получивший план, сразу увидел порядок суммы, а не искал её сам
# на другой вкладке и не сопоставлял в уме.
ЦЕНА_ПО_ШАБЛОНУ: dict[str, str] = {
    "присмотр": "level1",
    "сопровождение": "level1",
    "кресло": "level2",
    "постель": "level3",
    "круглосуточный": "round",
}


def сколько_примерно(идентификатор: str) -> dict | None:
    """Порядок суммы для этого плана — в месяц.

    Именно порядок, а не счёт: точную цену называет договор после
    первичного выезда. Но человек, увидевший план и не увидевший
    цифры, всё равно её придумает — и обычно неверно.
    """
    import прайс

    позиция_ид = ЦЕНА_ПО_ШАБЛОНУ.get(идентификатор)
    if not позиция_ид:
        return None
    позиция = прайс.найти(позиция_ид)
    покрытие = прайс.покрытие(позиция_ид)
    в_месяц = (позиция.цена * 30 if getattr(позиция, "единица", "") == "сутки"
               else позиция.цена)
    часов = getattr(позиция, "часов", None) or позиция.часов_в_месяц
    если_сутки = getattr(позиция, "единица", "") == "сутки"
    return {
        "позиция": позиция_ид,
        "название": позиция.название,
        "в_месяц": в_месяц,
        "в_час": round(позиция.цена / часов),
        "программы_в_час": round(покрытие.нужно_программ),
        "доля_семьи": round(покрытие.доля_семьи * 100),
        "посуточно": если_сутки,
    }


