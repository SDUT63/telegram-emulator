# Какой позиции прайса соответствует шаблон. Нужно, чтобы человек,
# получивший план, сразу увидел порядок суммы, а не искал её сам
# на другой вкладке и не сопоставлял в уме.
ЦЕНА_ПО_ШАБЛОНУ: dict[str, str] = {
    "присмотр": "level1",
    "сопровождение": "level1",
    "кресло": "level2",
    "постель": "level3",
    "круглосуточный": "round",
}


def сколько_примерно(идентификатор: str) -> dict | None:
    """Порядок суммы для этого плана — в месяц.

    Именно порядок, а не счёт: точную цену называет договор после
    первичного выезда. Но человек, увидевший план и не увидевший
    цифры, всё равно её придумает — и обычно неверно.
    """
    import прайс

    позиция_ид = ЦЕНА_ПО_ШАБЛОНУ.get(идентификатор)
    if not позиция_ид:
        return None
    позиция = прайс.найти(позиция_ид)
    покрытие = прайс.покрытие(позиция_ид)
    в_месяц = (позиция.цена * 30 if getattr(позиция, "единица", "") == "сутки"
               else позиция.цена)
    часов = getattr(позиция, "часов", None) or позиция.часов_в_месяц
    если_сутки = getattr(позиция, "единица", "") == "сутки"
    return {
        "позиция": позиция_ид,
        "название": позиция.название,
        "в_месяц": в_месяц,
        "в_час": round(позиция.цена / часов),
        "программы_в_час": round(покрытие.нужно_программ),
        "доля_семьи": round(покрытие.доля_семьи * 100),
        "посуточно": если_сутки,
    }


def найти_шаблон(идентификатор: str) -> Шаблон | None:
    return next((ш for ш in ШАБЛОНЫ if ш.id == идентификатор), None)


def _подходит(ответы: dict[str, str], правило: dict) -> bool:
    for ключ, годные in правило.items():
        было = str(ответы.get(ключ, ""))
        if not any(г in было for г in годные):
            return False
    return True


def подобрать(ответы: dict[str, str]) -> Шаблон | None:
    """Шаблон по ответам. Ничего не подошло — значит, рано показывать."""
    for идентификатор, правило in ПРАВИЛА:
        if _подходит(ответы, правило):
            return найти_шаблон(идентификатор)
    return None


def добавки(ответы: dict[str, str]) -> list[dict[str, str]]:
    """Что дописать к шаблону из-за отдельных ответов."""
    собрано: list[dict[str, str]] = []
    for ключ, годные, заголовок, текст in ДОБАВКИ:
        было = str(ответы.get(ключ, ""))
        if any(г in было for г in годные):
            собрано.append({"заголовок": заголовок, "текст": текст})
    return собрано


def блоки_по_ответам(шаблон: Шаблон, ответы: dict[str, str]) -> list[Блок]:
    """Только те части суток, которые человек отметил.

    Ночной блок показываем всегда, если человек не встаёт: ночь
    не отменяется тем, что о ней не подумали.

    А когда помощь нужна почти постоянно, показываем все части
    суток: отмечать «когда нужнее» в этом случае бессмысленно,
    и половина плана иначе просто не появится на экране.
    """
    if "Почти постоянно" in str(ответы.get("раз", "")):
        return list(шаблон.блоки)
    отмечено = str(ответы.get("когда", ""))
    если_лежит = "В кровати" in str(ответы.get("день", ""))
    выбрано = [б for б in шаблон.блоки
               if б.когда in отмечено or (если_лежит and б.время == "Ночь")]
    return выбрано or list(шаблон.блоки)


def часов_ориентир(шаблон: Шаблон, ответы: dict[str, str]) -> str:
    """Сколько времени это займёт — грубо, чтобы не было сюрприза."""
    if "Почти постоянно" in str(ответы.get("раз", "")):
        return "больше 8 часов в день"
    return шаблон.часов_в_день
