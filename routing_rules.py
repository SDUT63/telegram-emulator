def has(a, key, *vals):
    got = (a.get(key) or "")
    return any(v.lower() in got.lower() for v in vals)

def losses(a):
    return [k for k, vals in LOSS.items() if has(a, k, *vals)]

def med_signs(a):
    return [k for k, vals in MED.items() if has(a, k, *vals)]

def contradictions(a):
    out = []
    for (k1, v1), (k2, v2), text in CONTRADICTIONS:
        if has(a, k1, v1) and has(a, k2, v2):
            out.append(text)
    return out

def route(a):
    """Вернуть (маршрут, основание, сопутствующие маршруты)."""
    L, Mfl = losses(a), med_signs(a)
    n = len(L)
    also = []

    # Ступень 0 — не маршрут, а немедленная эскалация
    if has(a, "flags", *URGENT_FLAGS):
        return ("СМП", "Экстренные признаки в ответе на вопрос «Что беспокоит прямо "
                "сейчас»: " + a.get("flags", ""), [])

    # Сферы для проверки межведомственности
    spheres = set()
    if Mfl: spheres.add("медицина")
    if n >= 1: spheres.add("соцзащита")
    if has(a, "caregiver", "Почти никто"): spheres.add("опека")
    if has(a, "burnout", "На пределе", "Не справляемся"): spheres.add("поддержка семьи")
    if has(a, "need", "Кровать, коляска") or has(a, "equipment", "Ничего из этого нет"):
        spheres.add("ТСР и транспорт")
    if has(a, "status", "Ничего не оформлено", "Не знаю") and n >= 2:
        spheres.add("оформление статуса")

    # М1 — паллиативная медицинская помощь
    if has(a, "status", "Паллиативный статус") or has(a, "pain", "Постоянная") \
       or has(a, "devices", "Трахеостома") or has(a, "skin", "Открытая рана"):
        if n >= 3: also.append("М3")
        if len(spheres) >= 3: also.append("М5")
        return ("М1", "Паллиативные признаки: " + ", ".join(Mfl) +
                (f"; утрачено параметров: {n}" if n else ""), also)

    # М5 — межведомственное сопровождение: потребность охватывает две и более сферы
    if len(spheres) >= 3 or (len(spheres) >= 2 and n >= 3):
        if n >= 3: also.append("М3")
        elif n >= 1: also.append("М2")
        return ("М5", "Затронуто сфер: " + ", ".join(sorted(spheres)) +
                f"; утрачено параметров: {n}", also)

    # Противоречие в ответах — считать уровень нуждаемости нельзя
    contra = contradictions(a)
    if contra:
        return ("М4", "Ответы противоречат друг другу: " + "; ".join(contra) +
                ". Уровень нуждаемости по такой анкете не считается", also)

    # М3 — долговременный уход
    if n >= 3:
        if Mfl: also.append("М1")
        return ("М3", f"Утрачено параметров самообслуживания: {n} — " + ", ".join(L), also)

    # М2 — социальное обслуживание на дому
    if 1 <= n <= 2 and not has(a, "caregiver", "Почти никто") and not Mfl:
        return ("М2", f"Частичная утрата ({n} параметра), уход обеспечен: "
                + a.get("caregiver", ""), also)

    # М4 — консультация эксперта по нуждаемости
    reasons = []
    if has(a, "continue", "Достаточно"): reasons.append("анкета остановлена после 7-го вопроса")
    if has(a, "need", "Не знаю с чего"): reasons.append("запрос не сформулирован")
    if has(a, "who", "Я специалист"): reasons.append("обращение от специалиста")
    if n == 0 and not Mfl: reasons.append("признаков утраты и медицинских признаков нет")
    return ("М4", "; ".join(reasons) or "картина неясная", also)


